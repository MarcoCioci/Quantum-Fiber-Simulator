function plot_single_arm_pmd_summary(results_experiment_6, do_save)
% PLOT_SINGLE_ARM_PMD_SUMMARY  Plot the Experiment 6 PMD benchmark summary.

    if nargin < 1 || nargin > 2
        error('plot_single_arm_pmd_summary:InvalidNumInputs', ...
            'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = false;
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error('plot_single_arm_pmd_summary:InvalidDoSave', ...
            'do_save must be a logical scalar.');
    end

    required_fields = { ...
        'dgd_values', 'sigma_A', ...
        'c_xx', 'c_yy', 'c_zz', ...
        'purity_global', 'purity_A', 'purity_B', ...
        'fidelity_psi_plus', 'concurrence', 'S_max', ...
        'analytical' ...
    };

    check_required_fields(results_experiment_6, required_fields, ...
        'plot_single_arm_pmd_summary:MissingField');

    required_analytical_fields = { ...
        'c_xx', 'c_yy', 'c_zz', ...
        'purity_global', 'purity_A', 'purity_B', ...
        'fidelity_psi_plus', 'concurrence', 'S_max' ...
    };

    check_required_fields(results_experiment_6.analytical, ...
        required_analytical_fields, ...
        'plot_single_arm_pmd_summary:MissingAnalyticalField');


    % =========================
    % Extract data
    % =========================

    dgd_values = results_experiment_6.dgd_values(:).';
    sigma_A = real(results_experiment_6.sigma_A);

    normalized_dgd = sigma_A * dgd_values;

    correlation_num = real([ ...
        results_experiment_6.c_xx; ...
        results_experiment_6.c_yy; ...
        results_experiment_6.c_zz ...
    ]);

    correlation_analytical = real([ ...
        results_experiment_6.analytical.c_xx; ...
        results_experiment_6.analytical.c_yy; ...
        results_experiment_6.analytical.c_zz ...
    ]);

    metric_num = real([ ...
        results_experiment_6.purity_global; ...
        results_experiment_6.purity_A; ...
        results_experiment_6.purity_B; ...
        results_experiment_6.fidelity_psi_plus; ...
        results_experiment_6.concurrence ...
    ]);

    metric_analytical = real([ ...
        results_experiment_6.analytical.purity_global; ...
        results_experiment_6.analytical.purity_A; ...
        results_experiment_6.analytical.purity_B; ...
        results_experiment_6.analytical.fidelity_psi_plus; ...
        results_experiment_6.analytical.concurrence ...
    ]);

    S_max_num = real(results_experiment_6.S_max);
    S_max_analytical = real(results_experiment_6.analytical.S_max);

    marker_offset = 0.003 * (max(normalized_dgd) - min(normalized_dgd));
    normalized_dgd_yy_markers = normalized_dgd + marker_offset;

    style = get_plot_style();
    palette = get_plot_palette();


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = get_experiment_figure_tab( ...
        style.figure.experiment_6_id, ...
        'Single-arm PMD summary', ...
        'Experiment 6 — Single-Arm PMD', ...
        style);

    build_plot(tab);

    set(fig, 'Visible', style.figure.visible_after_build);


    % =========================
    % Save (conditional)
    % =========================

    if do_save

        output_folder = [ ...
            '/home/marcocioci/HPC/THESIS-Quantum-Communications/', ...
            'Quantum-Fiber-Simulator/images/experiment_6' ...
        ];

        output_path = fullfile(output_folder, ...
            'experiment_6_single_arm_pmd_summary.png');

        export_plot(output_path, @build_plot, style);

    end


    % =========================
    % Local plot builder
    % =========================

    function layout = build_plot(parent_container)

        layout = tiledlayout(parent_container, 3, 1, ...
            'TileSpacing', 'compact', ...
            'Padding', 'compact');


        % Correlations
        ax = nexttile(layout);
        hold(ax, 'on');
        grid(ax, 'on');
        box(ax, 'on');

        plot(ax, normalized_dgd, correlation_analytical(1, :), '-', ...
            'Color', palette.obs_x, 'LineWidth', 1.8, ...
            'DisplayName', '$c_{xx}$ analytical');

        plot(ax, normalized_dgd, correlation_num(1, :), 'o', ...
            'Color', palette.obs_x, ...
            'MarkerFaceColor', palette.obs_x, ...
            'MarkerSize', 3, ...
            'DisplayName', '$c_{xx}$ numerical');

        plot(ax, normalized_dgd, correlation_analytical(2, :), '-', ...
            'Color', palette.obs_y, 'LineWidth', 1.8, ...
            'DisplayName', '$c_{yy}$ analytical');

        plot(ax, normalized_dgd_yy_markers, correlation_num(2, :), 'o', ...
            'Color', palette.obs_y, ...
            'MarkerFaceColor', palette.obs_y, ...
            'MarkerSize', 3, ...
            'DisplayName', '$c_{yy}$ numerical');

        plot(ax, normalized_dgd, correlation_analytical(3, :), '-', ...
            'Color', palette.obs_z, 'LineWidth', 1.8, ...
            'DisplayName', '$c_{zz}$ analytical');

        plot(ax, normalized_dgd, correlation_num(3, :), 'o', ...
            'Color', palette.obs_z, ...
            'MarkerFaceColor', palette.obs_z, ...
            'MarkerSize', 3, ...
            'DisplayName', '$c_{zz}$ numerical');

        ylabel(ax, 'Correlation', 'Interpreter', 'latex');
        ylim(ax, style.axes.correlation_limits);
        legend(ax, 'Interpreter', 'latex', 'Location', 'southwest', ...
            'NumColumns', 2);


        % State metrics
        ax = nexttile(layout);
        hold(ax, 'on');
        grid(ax, 'on');
        box(ax, 'on');

        plot_metric_pair(ax, normalized_dgd, metric_analytical(1, :), ...
            metric_num(1, :), palette.metric_global, '$\gamma_{AB}$');

        plot_metric_pair(ax, normalized_dgd, metric_analytical(2, :), ...
            metric_num(2, :), palette.metric_A, '$\gamma_A$');

        plot_metric_pair(ax, normalized_dgd, metric_analytical(3, :), ...
            metric_num(3, :), palette.metric_B, '$\gamma_B$');

        plot_metric_pair(ax, normalized_dgd, metric_analytical(4, :), ...
            metric_num(4, :), palette.metric_F, '$F_{\Psi^+}$');

        plot_metric_pair(ax, normalized_dgd, metric_analytical(5, :), ...
            metric_num(5, :), palette.metric_C, '$C$');

        ylabel(ax, 'State metric', 'Interpreter', 'latex');
        ylim(ax, style.axes.metric_limits);
        legend(ax, 'Interpreter', 'latex', 'Location', 'southwest', ...
            'NumColumns', 3);


        % CHSH value
        ax = nexttile(layout);
        hold(ax, 'on');
        grid(ax, 'on');
        box(ax, 'on');

        plot(ax, normalized_dgd, S_max_analytical, '-', ...
            'Color', palette.black, ...
            'LineWidth', 1.8, ...
            'DisplayName', 'Analytical');

        plot(ax, normalized_dgd, S_max_num, 'o', ...
            'Color', palette.red, ...
            'MarkerFaceColor', palette.red, ...
            'MarkerSize', 3, ...
            'DisplayName', 'Numerical');

        yline(ax, 2, '--', ...
            'Color', palette.gray_mid, ...
            'LineWidth', 1.2, ...
            'DisplayName', 'CHSH classical bound');

        xlabel(ax, '$\sigma_A \tau$', 'Interpreter', 'latex');
        ylabel(ax, '$S_{\max}$', 'Interpreter', 'latex');
        ylim(ax, [1.8, 2 * sqrt(2) + 0.05]);
        legend(ax, 'Interpreter', 'latex', 'Location', 'southwest');

        title(layout, ...
            'Single-arm PMD: frequency-induced polarization decoherence', ...
            'Interpreter', 'none');

    end

end


function plot_metric_pair(ax, x_values, analytical_values, numerical_values, ...
        color, metric_label)

    plot(ax, x_values, analytical_values, '-', ...
        'Color', color, ...
        'LineWidth', 1.8, ...
        'DisplayName', [metric_label, ' analytical']);

    plot(ax, x_values, numerical_values, 'o', ...
        'Color', color, ...
        'MarkerFaceColor', color, ...
        'MarkerSize', 3, ...
        'HandleVisibility', 'off');

end

