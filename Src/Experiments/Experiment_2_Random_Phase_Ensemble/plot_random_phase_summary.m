function plot_random_phase_summary(results_case, do_save)
% PLOT_RANDOM_PHASE_SUMMARY  Plot a compact summary for one Experiment 2 case.
%
% Objective:
%   Provide a single figure summarizing one random-phase ensemble case:
%
%       1) sampled phase distribution
%       2) pure-state trend cos(θ) and sampled realizations
%       3) ensemble correlation observables
%       4) purity, fidelity, and concurrence metrics
%
% Input:
%   results_case - structure containing numerical and analytical quantities
%                  assembled by the Experiment 2 runner.
%
%   do_save      - optional logical flag to enable figure saving.
%                  Default value: false.
%
% Output:
%   None

    % =========================
    % Robustness checks
    % =========================

    if nargin < 1 || nargin > 2
        error('plot_random_phase_summary:InvalidNumInputs', ...
              'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = false;
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error('plot_random_phase_summary:InvalidDoSave', ...
              'do_save must be a logical scalar.');
    end

    if ~isstruct(results_case)
        error('plot_random_phase_summary:InvalidInputType', ...
              'results_case must be a structure.');
    end

    required_fields = { ...
        'theta_samples', ...
        'case_label', ...
        'distribution_type', ...
        'c_xx', ...
        'c_yy', ...
        'c_zz', ...
        'purity_global', ...
        'purity_A', ...
        'purity_B', ...
        'fidelity_psi_plus', ...
        'concurrence', ...
        'sample_mean_cos_theta', ...
        'sample_mean_sin_theta', ...
        'analytical' ...
    };

    check_required_fields(results_case, required_fields, ...
        'plot_random_phase_summary:MissingField');

    if ~isstruct(results_case.analytical)
        error('plot_random_phase_summary:InvalidAnalyticalType', ...
              'Field "analytical" must be a structure.');
    end

    required_analytical_fields = { ...
        'c_xx', ...
        'c_yy', ...
        'c_zz', ...
        'purity_global', ...
        'purity_A', ...
        'purity_B', ...
        'fidelity_psi_plus', ...
        'concurrence' ...
    };

    check_required_fields(results_case.analytical, required_analytical_fields, ...
        'plot_random_phase_summary:MissingAnalyticalField');


    % =========================
    % Extract data
    % =========================

    theta_samples = results_case.theta_samples(:).';
    case_label = char(results_case.case_label);
    distribution_type = char(results_case.distribution_type);

    if ~isnumeric(theta_samples) || ~isreal(theta_samples) || isempty(theta_samples)
        error('plot_random_phase_summary:InvalidThetaSamples', ...
              'theta_samples must be a non-empty real numeric vector.');
    end

    if any(~isfinite(theta_samples))
        error('plot_random_phase_summary:InvalidThetaSamplesValues', ...
              'theta_samples must contain only finite values.');
    end

    correlation_labels = {'c_{xx}', 'c_{yy}', 'c_{zz}'};

    correlation_num = real([ ...
        results_case.c_xx, ...
        results_case.c_yy, ...
        results_case.c_zz ...
    ]);

    correlation_analytical = real([ ...
        results_case.analytical.c_xx, ...
        results_case.analytical.c_yy, ...
        results_case.analytical.c_zz ...
    ]);

    metric_labels = { ...
        '\gamma(\rho_{AB})', ...
        '\gamma(\rho_A)', ...
        '\gamma(\rho_B)', ...
        'F_{\Psi^+}', ...
        'C' ...
    };

    metric_num = real([ ...
        results_case.purity_global, ...
        results_case.purity_A, ...
        results_case.purity_B, ...
        results_case.fidelity_psi_plus, ...
        results_case.concurrence ...
    ]);

    metric_analytical = real([ ...
        results_case.analytical.purity_global, ...
        results_case.analytical.purity_A, ...
        results_case.analytical.purity_B, ...
        results_case.analytical.fidelity_psi_plus, ...
        results_case.analytical.concurrence ...
    ]);

    sample_mean_cos_theta = real(results_case.sample_mean_cos_theta);
    sample_mean_sin_theta = real(results_case.sample_mean_sin_theta);

    scalar_values = [ ...
        correlation_num, ...
        correlation_analytical, ...
        metric_num, ...
        metric_analytical, ...
        sample_mean_cos_theta, ...
        sample_mean_sin_theta ...
    ];

    if any(~isfinite(scalar_values))
        error('plot_random_phase_summary:InvalidScalarValues', ...
              'All scalar numerical values must be finite.');
    end


    % =========================
    % Plot style
    % =========================

    style = get_plot_style();
    palette = get_plot_palette();


    % =========================
    % Auxiliary quantities
    % =========================

    theta_min = min(theta_samples);
    theta_max = max(theta_samples);

    if theta_min == theta_max
        theta_min = theta_min - 0.5;
        theta_max = theta_max + 0.5;
    end

    theta_plot = linspace(theta_min, theta_max, 400);
    pure_state_cosine_trend = cos(theta_plot);
    sampled_cosine_values = cos(theta_samples);

    correlation_errors = abs(correlation_num - correlation_analytical);
    metric_errors = abs(metric_num - metric_analytical);


    % =========================
    % Figure and tab
    % =========================

    tab_title = sprintf('Summary | %s', case_label);
    figure_name = 'Experiment 2 — Random Phase Ensemble';

    [fig, tab] = get_experiment_figure_tab( ...
        style.figure.experiment_2_id, ...
        tab_title, ...
        figure_name, ...
        style);

    build_plot(tab);

    set(fig, 'Visible', style.figure.visible_after_build);


    % =========================
    % Save (conditional)
    % =========================

    if do_save
        distribution_label_file = lower(distribution_type);
        distribution_label_file = regexprep(distribution_label_file, '\s+', '_');
        distribution_label_file = regexprep(distribution_label_file, '[^a-z0-9_]', '');
        distribution_label_file = regexprep(distribution_label_file, '_+', '_');
        distribution_label_file = regexprep(distribution_label_file, '^_|_$', '');

        output_folder = '/home/marcocioci/HPC/THESIS-Quantum-Communications/Quantum-Fiber-Simulator/Images/Experiment_2';

        if ~exist(output_folder, 'dir')
            mkdir(output_folder);
        end

        output_path = fullfile(output_folder, ...
            sprintf('experiment_2_summary_%s_distribution.png', distribution_label_file));

        export_plot(output_path, @build_plot, style);
    end


    % =========================
    % Local plot builder
    % =========================

    function build_plot(parent_container)

        layout = tiledlayout(parent_container, 2, 2, ...
            'TileSpacing', 'compact', ...
            'Padding', 'compact');


        % =========================
        % Panel 1: phase distribution
        % =========================

        nexttile(layout);
        hold on;
        grid on;
        box on;

        num_bins = max(10, round(sqrt(numel(theta_samples))));

        histogram(theta_samples, num_bins, ...
            'Normalization', 'pdf', ...
            'FaceColor', palette.samples, ...
            'EdgeColor', palette.gray_dark);

        xlim([theta_min, theta_max]);

        xlabel('\theta');
        ylabel('pdf');
        title('Phase distribution');

        mean_theta = mean(theta_samples);
        std_theta = std(theta_samples);

        text(0.02, 0.95, ...
            sprintf(['Distribution: %s\n' ...
                     'N = %d\n' ...
                     'mean(theta) = %.4f\n' ...
                     'std(theta) = %.4f\n' ...
                     'mean(cos(theta)) = %.4f\n' ...
                     'mean(sin(theta)) = %.4f'], ...
                    distribution_type, ...
                    numel(theta_samples), ...
                    mean_theta, ...
                    std_theta, ...
                    sample_mean_cos_theta, ...
                    sample_mean_sin_theta), ...
            'Units', 'normalized', ...
            'VerticalAlignment', 'top', ...
            'BackgroundColor', 'w', ...
            'EdgeColor', palette.gray_dark);


        % =========================
        % Panel 2: pure-state trend and samples
        % =========================

        nexttile(layout);
        hold on;
        grid on;
        box on;

        plot(theta_plot, pure_state_cosine_trend, ...
            'LineWidth', 1.8, ...
            'Color', palette.obs_x);

        plot(theta_samples, sampled_cosine_values, 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.samples, ...
            'MarkerEdgeColor', palette.gray_dark);

        yline(sample_mean_cos_theta, '--', ...
            'LineWidth', 1.2, ...
            'Color', palette.mean_line);

        yline(real(results_case.c_xx), '-', ...
            'LineWidth', 1.2, ...
            'Color', palette.numerical);

        xlim([theta_min, theta_max]);
        ylim([-1.1, 1.1]);

        xlabel('\theta');
        ylabel('cos(\theta)');
        title('cos(\theta): pure-state vs ensemble');

        legend({ ...
            'cos(\theta)', ...
            'sample realizations', ...
            '<cos(\theta)>', ...
            'c_{xx} numerical' ...
            }, ...
            'Location', 'southoutside', ...
            'Orientation', 'horizontal');


        % =========================
        % Panel 3: correlation observables
        % =========================

        nexttile(layout);
        plot_grouped_bar_comparison( ...
            correlation_analytical, ...
            correlation_num, ...
            correlation_labels, ...
            'correlation observables', ...
            'Correlation observables', ...
            [-1.1, 1.1], ...
            palette);

        correlation_error_text = sprintf(['|analytical - numerical|:\n' ...
                                          'c_{xx}: %.3e\n' ...
                                          'c_{yy}: %.3e\n' ...
                                          'c_{zz}: %.3e'], ...
                                          correlation_errors(1), ...
                                          correlation_errors(2), ...
                                          correlation_errors(3));

        add_error_box(correlation_error_text, palette);


        % =========================
        % Panel 4: state metrics
        % =========================

        nexttile(layout);
        plot_grouped_bar_comparison( ...
            metric_analytical, ...
            metric_num, ...
            metric_labels, ...
            'state metrics', ...
            'State metrics', ...
            [0, 1.05], ...
            palette);

        metric_error_text = sprintf(['|analytical - numerical|:\n' ...
                                     '\\gamma(\\rho_{AB}): %.3e\n' ...
                                     '\\gamma(\\rho_A): %.3e\n' ...
                                     '\\gamma(\\rho_B): %.3e\n' ...
                                     'F_{\\Psi^+}: %.3e\n' ...
                                     'C: %.3e'], ...
                                     metric_errors(1), ...
                                     metric_errors(2), ...
                                     metric_errors(3), ...
                                     metric_errors(4), ...
                                     metric_errors(5));

        add_error_box(metric_error_text, palette);


        % =========================
        % Global title
        % =========================

        title(layout, ...
            sprintf('Experiment 2 — Random Phase Ensemble | %s', case_label), ...
            'FontWeight', 'bold');

    end

end


function check_required_fields(input_struct, required_fields, error_id)
% CHECK_REQUIRED_FIELDS  Verify that all required fields are present.

    for field_idx = 1:numel(required_fields)
        field_name = required_fields{field_idx};

        if ~isfield(input_struct, field_name)
            error(error_id, 'Field "%s" not found.', field_name);
        end
    end

end


function plot_grouped_bar_comparison(analytical_values, numerical_values, x_labels, x_axis_label, plot_title, y_limits, palette)
% PLOT_GROUPED_BAR_COMPARISON  Plot analytical and numerical values as grouped bars.

    hold on;
    grid on;
    box on;

    x_values = 1:numel(analytical_values);
    bar_width = 0.36;

    bar(x_values - bar_width/2, analytical_values, bar_width, ...
        'FaceColor', palette.analytical, ...
        'EdgeColor', palette.gray_dark);

    bar(x_values + bar_width/2, numerical_values, bar_width, ...
        'FaceColor', palette.numerical, ...
        'EdgeColor', palette.gray_dark);

    xlim([0.4, numel(x_values) + 0.6]);
    ylim(y_limits);

    set(gca, ...
        'XTick', x_values, ...
        'XTickLabel', x_labels, ...
        'TickLabelInterpreter', 'tex');

    xlabel(x_axis_label);
    ylabel('value');
    title(plot_title);

    legend({'analytical', 'numerical'}, ...
        'Location', 'southoutside', ...
        'Orientation', 'horizontal');

    for value_idx = 1:numel(x_values)
        add_bar_value_label(x_values(value_idx) - bar_width/2, analytical_values(value_idx), y_limits, palette);
        add_bar_value_label(x_values(value_idx) + bar_width/2, numerical_values(value_idx), y_limits, palette);
    end

end


function add_bar_value_label(x_position, y_value, y_limits, palette)
% ADD_BAR_VALUE_LABEL  Add a numeric label above or below a bar.

    y_offset = 0.04 * diff(y_limits);

    if y_value >= 0
        label_y_position = y_value + y_offset;
        vertical_alignment = 'bottom';
    else
        label_y_position = y_value - y_offset;
        vertical_alignment = 'top';
    end

    text(x_position, label_y_position, sprintf('%.4f', y_value), ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', vertical_alignment, ...
        'FontSize', 9, ...
        'Color', palette.gray_dark);

end


function add_error_box(error_text, palette)
% ADD_ERROR_BOX  Add a lower-right text box containing numerical errors.

    text(0.98, 0.05, error_text, ...
        'Units', 'normalized', ...
        'HorizontalAlignment', 'right', ...
        'VerticalAlignment', 'bottom', ...
        'BackgroundColor', 'w', ...
        'EdgeColor', palette.gray_dark);

end