function results = experiment_03_two_arm_pmd_spectral_operating_regions( ...
        do_plot, do_save)
% EXPERIMENT_03_TWO_ARM_PMD_SPECTRAL_OPERATING_REGIONS
% Two-arm PMD and spectral-correlation BBM92 operating regions.
%
% Objective:
%   Determine how PMD in both propagation arms and spectral correlation
%   between the two photons modify the BBM92 operating region.
%
%   The physical parameter set considered here is
%
%       (delta_tau_A, delta_tau_B, r),
%
%   where delta_tau_A and delta_tau_B are the differential group delays
%   of the two arms and r is the spectral correlation coefficient.
%
%   A fixed Gaussian marginal spectral bandwidth sigma_omega is used.
%   Both arms contain one first-order PMD segment with the same fixed
%   birefringence axis. This isolates the combined role of two-arm DGD
%   and spectral correlation; PMD-axis mismatch is investigated
%   separately in Experiment 4.
%
%   The reduced polarization state is obtained by tracing over the
%   unresolved joint spectrum.
%
%   The operational quantity is
%
%       Q_worst = max(Q_Z, Q_X),
%
%   and the adopted BBM92 condition is
%
%       Q_worst < Q_th.
%
% Inputs:
%   do_plot - Logical flag enabling figure visualization.
%   do_save - Logical flag enabling thesis-ready PNG export.
%
% Output:
%   results - Structure containing physical parameters, QBER operating
%             maps, concurrence maps, and symmetric-DGD operating
%             boundary versus spectral correlation.


    % =========================
    % Input handling
    % =========================

    if nargin < 1
        do_plot = true;
    end

    if nargin < 2
        do_save = false;
    end


    % =========================
    % Experiment parameters
    % =========================

    sigma_omega = 1.0e11;

    num_frequency_nodes = 41;

    spectral_window_sigma = 6.0;

    qber_threshold = 0.11;


    % =========================
    % Two-arm DGD parameter space
    % =========================

    num_dgd_points = 31;

    max_dgd = 20e-12;

    delta_tau_values = linspace( ...
        0, ...
        max_dgd, ...
        num_dgd_points);


    % Representative spectral correlations used for the two-dimensional
    % two-arm operating maps.

    correlation_cases = [ ...
        -0.9, ...
         0.0, ...
         0.9];


    % Finer correlation sweep used to determine the symmetric two-arm
    % operating boundary.

    num_correlation_points = 37;

    correlation_values = linspace( ...
        -0.9, ...
         0.9, ...
        num_correlation_points);


    % Symmetric DGD sweep for the correlation-dependent boundary.

    num_symmetric_dgd_points = 81;

    symmetric_delta_tau_values = linspace( ...
        0, ...
        max_dgd, ...
        num_symmetric_dgd_points);


    % =========================
    % PMD configuration
    % =========================

    % One segment per arm.
    %
    % The same x-oriented PMD axis is used in both arms so that this
    % experiment isolates two-arm PMD and spectral-correlation effects.

    delta_phase_A = 0;

    delta_phase_B = 0;

    pmd_axis_A = [1, 0, 0];

    pmd_axis_B = [1, 0, 0];


    % =========================
    % Reference state
    % =========================

    psi_reference = bell_state( ...
        'psi_plus');

    rho_reference = state_to_density_matrix( ...
        psi_reference);


    % =========================
    % Frequency grids
    % =========================

    max_frequency_offset = ...
        spectral_window_sigma * sigma_omega;

    omega_offsets_A = pmd_frequency_grid( ...
        num_frequency_nodes, ...
        max_frequency_offset);

    omega_offsets_B = pmd_frequency_grid( ...
        num_frequency_nodes, ...
        max_frequency_offset);


    % =========================
    % Console header
    % =========================

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf(' Experiment 3 - Two-Arm PMD and Spectral Correlations\n');
    fprintf(' BBM92 Operating Regions\n');
    fprintf('============================================================\n');
    fprintf('DGD points / arm:             %d\n', ...
        num_dgd_points);
    fprintf('Symmetric DGD points:         %d\n', ...
        num_symmetric_dgd_points);
    fprintf('Correlation points:           %d\n', ...
        num_correlation_points);
    fprintf('Frequency nodes / arm:        %d\n', ...
        num_frequency_nodes);
    fprintf('Marginal sigma_omega:         %.3e rad/s\n', ...
        sigma_omega);
    fprintf('Spectral window:              +/- %.1f sigma_omega\n', ...
        spectral_window_sigma);
    fprintf('DGD range:                    [%.3f, %.3f] ps\n', ...
        min(delta_tau_values) * 1e12, ...
        max(delta_tau_values) * 1e12);
    fprintf('Correlation range:            [%.2f, %.2f]\n', ...
        min(correlation_values), ...
        max(correlation_values));
    fprintf('PMD axis arm A:               [%.1f %.1f %.1f]\n', ...
        pmd_axis_A);
    fprintf('PMD axis arm B:               [%.1f %.1f %.1f]\n', ...
        pmd_axis_B);
    fprintf('BBM92 QBER threshold:         %.4f\n', ...
        qber_threshold);
    fprintf('============================================================\n\n');


    % =========================
    % Allocate representative maps
    % =========================

    num_correlation_cases = ...
        numel(correlation_cases);

    map_size = [ ...
        num_dgd_points, ...
        num_dgd_points, ...
        num_correlation_cases];

    Q_worst_maps = zeros( ...
        map_size);

    concurrence_maps = zeros( ...
        map_size);

    operating_maps = false( ...
        map_size);


    % =========================
    % Representative two-arm operating maps
    % =========================

    fprintf('Computing two-arm operating maps...\n\n');

    for i_r = 1:num_correlation_cases

        r = correlation_cases(i_r);


        % ----------------------------------------------------------
        % Joint Gaussian spectrum
        % ----------------------------------------------------------
        %
        % For equal marginal bandwidth sigma_omega and correlation r,
        %
        %   sigma_sum =
        %       sigma_omega * sqrt(2 * (1 + r))
        %
        %   sigma_difference =
        %       sigma_omega * sqrt(2 * (1 - r)).
        %
        % ----------------------------------------------------------

        sigma_sum = ...
            sigma_omega * sqrt( ...
                2 * (1 + r));

        sigma_difference = ...
            sigma_omega * sqrt( ...
                2 * (1 - r));

        spectral_weights = pmd_joint_spectral_weights( ...
            omega_offsets_A, ...
            omega_offsets_B, ...
            sigma_sum, ...
            sigma_difference);


        fprintf( ...
            'Correlation case %d/%d: r = %+.2f\n', ...
            i_r, ...
            num_correlation_cases, ...
            r);


        % ----------------------------------------------------------
        % Two-arm DGD sweep
        % ----------------------------------------------------------

        for i_A = 1:num_dgd_points

            delta_tau_A = ...
                delta_tau_values(i_A);

            for i_B = 1:num_dgd_points

                delta_tau_B = ...
                    delta_tau_values(i_B);


                % --------------------------------------------------
                % Frequency-resolved propagation
                % --------------------------------------------------

                frequency_states = pmd_frequency_resolved_states( ...
                    rho_reference, ...
                    omega_offsets_A, ...
                    omega_offsets_B, ...
                    delta_phase_A, ...
                    delta_tau_A, ...
                    pmd_axis_A, ...
                    delta_phase_B, ...
                    delta_tau_B, ...
                    pmd_axis_B);


                % --------------------------------------------------
                % Spectral trace
                % --------------------------------------------------

                rho_pol = pmd_spectral_average_state( ...
                    frequency_states, ...
                    spectral_weights);


                % --------------------------------------------------
                % State and operational quantities
                % --------------------------------------------------

                concurrence_maps(i_A, i_B, i_r) = ...
                    compute_concurrence( ...
                        rho_pol);

                qber = compute_bbm92_qber( ...
                    rho_pol);

                Q_worst_maps(i_A, i_B, i_r) = ...
                    max( ...
                        qber.Q_Z, ...
                        qber.Q_X);

                operating_maps(i_A, i_B, i_r) = ...
                    Q_worst_maps(i_A, i_B, i_r) < ...
                    qber_threshold;

            end

        end

    end


    % =========================
    % Symmetric two-arm operating boundary
    % =========================
    %
    % Here
    %
    %   delta_tau_A = delta_tau_B = delta_tau.
    %
    % The resulting boundary quantifies how spectral correlation changes
    % the maximum symmetric PMD that can be tolerated by the link.
    % =========================

    fprintf('\n');
    fprintf('Computing symmetric-DGD boundary versus correlation...\n\n');

    symmetric_Q_worst = zeros( ...
        num_correlation_points, ...
        num_symmetric_dgd_points);

    symmetric_concurrence = zeros( ...
        num_correlation_points, ...
        num_symmetric_dgd_points);

    symmetric_dgd_boundary = nan( ...
        1, ...
        num_correlation_points);

    symmetric_chi_boundary = nan( ...
        1, ...
        num_correlation_points);

    symmetric_concurrence_boundary = nan( ...
        1, ...
        num_correlation_points);


    for i_r = 1:num_correlation_points

        r = ...
            correlation_values(i_r);


        % ----------------------------------------------------------
        % Joint Gaussian spectrum
        % ----------------------------------------------------------

        sigma_sum = ...
            sigma_omega * sqrt( ...
                2 * (1 + r));

        sigma_difference = ...
            sigma_omega * sqrt( ...
                2 * (1 - r));

        spectral_weights = pmd_joint_spectral_weights( ...
            omega_offsets_A, ...
            omega_offsets_B, ...
            sigma_sum, ...
            sigma_difference);


        fprintf( ...
            'Correlation %2d/%2d: r = %+.3f\n', ...
            i_r, ...
            num_correlation_points, ...
            r);


        % ----------------------------------------------------------
        % Symmetric DGD sweep
        % ----------------------------------------------------------

        for i_dgd = 1:num_symmetric_dgd_points

            delta_tau = ...
                symmetric_delta_tau_values(i_dgd);


            frequency_states = pmd_frequency_resolved_states( ...
                rho_reference, ...
                omega_offsets_A, ...
                omega_offsets_B, ...
                delta_phase_A, ...
                delta_tau, ...
                pmd_axis_A, ...
                delta_phase_B, ...
                delta_tau, ...
                pmd_axis_B);

            rho_pol = pmd_spectral_average_state( ...
                frequency_states, ...
                spectral_weights);

            symmetric_concurrence(i_r, i_dgd) = ...
                compute_concurrence( ...
                    rho_pol);

            qber = compute_bbm92_qber( ...
                rho_pol);

            symmetric_Q_worst(i_r, i_dgd) = ...
                max( ...
                    qber.Q_Z, ...
                    qber.Q_X);

        end


        % ----------------------------------------------------------
        % Extract QBER operating boundary
        % ----------------------------------------------------------

        boundary = extract_operating_boundary( ...
            symmetric_delta_tau_values, ...
            symmetric_Q_worst(i_r, :), ...
            qber_threshold);

        if boundary.num_crossings > 0

            symmetric_dgd_boundary(i_r) = ...
                boundary.first_crossing;

            symmetric_chi_boundary(i_r) = ...
                sigma_omega * ...
                boundary.first_crossing;

            symmetric_concurrence_boundary(i_r) = interp1( ...
                symmetric_delta_tau_values, ...
                symmetric_concurrence(i_r, :), ...
                boundary.first_crossing, ...
                'linear');

        end

    end


    % =========================
    % Numerical consistency
    % =========================

    zero_dgd_qber_error = max(abs( ...
        reshape( ...
            Q_worst_maps(1, 1, :), ...
            [], ...
            1)));

    zero_dgd_concurrence_error = max(abs( ...
        reshape( ...
            concurrence_maps(1, 1, :), ...
            [], ...
            1) ...
        - 1));


    % =========================
    % Representative boundary summary
    % =========================

    valid_boundary = ...
        ~isnan(symmetric_dgd_boundary);

    min_boundary_dgd = min( ...
        symmetric_dgd_boundary(valid_boundary));

    max_boundary_dgd = max( ...
        symmetric_dgd_boundary(valid_boundary));

    [~, min_boundary_index] = min( ...
        symmetric_dgd_boundary);

    [~, max_boundary_index] = max( ...
        symmetric_dgd_boundary);


    % =========================
    % Console summary
    % =========================

    fprintf('\n');
    fprintf('Numerical consistency\n');
    fprintf('------------------------------------------------------------\n');

    fprintf( ...
        'Zero-DGD worst-QBER error:    %.3e\n', ...
        zero_dgd_qber_error);

    fprintf( ...
        'Zero-DGD concurrence error:   %.3e\n', ...
        zero_dgd_concurrence_error);


    fprintf('\n');
    fprintf('Symmetric two-arm BBM92 boundary\n');
    fprintf('------------------------------------------------------------\n');

    fprintf( ...
        'Minimum tolerable DGD:        %.3f ps at r = %+.3f\n', ...
        min_boundary_dgd * 1e12, ...
        correlation_values(min_boundary_index));

    fprintf( ...
        'Maximum tolerable DGD:        %.3f ps at r = %+.3f\n', ...
        max_boundary_dgd * 1e12, ...
        correlation_values(max_boundary_index));


    % Report the three representative correlation cases.

    for i_case = 1:num_correlation_cases

        [~, correlation_index] = min(abs( ...
            correlation_values - ...
            correlation_cases(i_case)));

        fprintf( ...
            'r = %+.2f: DGD_th = %.3f ps, chi_th = %.4f, C_th = %.4f\n', ...
            correlation_cases(i_case), ...
            symmetric_dgd_boundary(correlation_index) * 1e12, ...
            symmetric_chi_boundary(correlation_index), ...
            symmetric_concurrence_boundary(correlation_index));

    end

    fprintf('============================================================\n\n');


    % =========================
    % Assemble results
    % =========================

    results = struct();


    % --------------------------------------------------------------
    % Parameters
    % --------------------------------------------------------------

    results.parameters.sigma_omega = ...
        sigma_omega;

    results.parameters.delta_tau = ...
        delta_tau_values;

    results.parameters.correlation_cases = ...
        correlation_cases;

    results.parameters.correlation_values = ...
        correlation_values;

    results.parameters.symmetric_delta_tau = ...
        symmetric_delta_tau_values;

    results.parameters.pmd_axis_A = ...
        pmd_axis_A;

    results.parameters.pmd_axis_B = ...
        pmd_axis_B;

    results.parameters.qber_threshold = ...
        qber_threshold;

    results.parameters.num_frequency_nodes = ...
        num_frequency_nodes;

    results.parameters.spectral_window_sigma = ...
        spectral_window_sigma;


    % --------------------------------------------------------------
    % Two-arm maps
    % --------------------------------------------------------------

    results.maps.Q_worst = ...
        Q_worst_maps;

    results.maps.concurrence = ...
        concurrence_maps;

    results.maps.operating = ...
        operating_maps;


    % --------------------------------------------------------------
    % Symmetric-DGD analysis
    % --------------------------------------------------------------

    results.symmetric.Q_worst = ...
        symmetric_Q_worst;

    results.symmetric.concurrence = ...
        symmetric_concurrence;

    results.symmetric.delta_tau_boundary = ...
        symmetric_dgd_boundary;

    results.symmetric.chi_boundary = ...
        symmetric_chi_boundary;

    results.symmetric.concurrence_boundary = ...
        symmetric_concurrence_boundary;


    % =========================
    % Figures
    % =========================

    figure_handles = struct();

    if do_plot || do_save

        figure_handles = build_experiment_plots( ...
            delta_tau_values, ...
            correlation_cases, ...
            Q_worst_maps, ...
            correlation_values, ...
            symmetric_dgd_boundary, ...
            qber_threshold, ...
            do_plot);

    end


    % =========================
    % Save figures
    % =========================

    if do_save

        project_root = locate_project_root();

        output_directory = fullfile( ...
            project_root, ...
            'text', ...
            'thesis', ...
            'figures', ...
            'experiment_3');

        if ~exist(output_directory, 'dir')

            mkdir( ...
                output_directory);

        end


        fprintf('Saving thesis figures...\n');

        fprintf( ...
            'Output directory:\n%s\n\n', ...
            output_directory);


        exportgraphics( ...
            figure_handles.operating_maps, ...
            fullfile( ...
                output_directory, ...
                'two_arm_pmd_operating_regions.png'), ...
            'Resolution', ...
            300);

        exportgraphics( ...
            figure_handles.correlation_boundary, ...
            fullfile( ...
                output_directory, ...
                'spectral_correlation_dgd_boundary.png'), ...
            'Resolution', ...
            300);


        fprintf('Saved thesis figures:\n');

        fprintf( ...
            '  two_arm_pmd_operating_regions.png\n');

        fprintf( ...
            '  spectral_correlation_dgd_boundary.png\n\n');

    end

end


% ==================================================================
% Local function - Build experiment plots
% ==================================================================

function figure_handles = build_experiment_plots( ...
        delta_tau_values, ...
        correlation_cases, ...
        Q_worst_maps, ...
        correlation_values, ...
        symmetric_dgd_boundary, ...
        qber_threshold, ...
        do_plot)

    figure_handles = struct();


    % =========================
    % Visibility
    % =========================

    if do_plot

        figure_visibility = 'on';

    else

        figure_visibility = 'off';

    end


    % =========================
    % Plot coordinates
    % =========================

    dgd_plot = ...
        delta_tau_values * 1e12;


    % =========================
    % Figure 1 - Two-arm operating regions
    % =========================

    figure_handles.operating_maps = figure( ...
        'Name', ...
        'Experiment 3 - Two-Arm PMD Operating Regions', ...
        'Visible', ...
        figure_visibility);

    tiledlayout( ...
        1, ...
        numel(correlation_cases), ...
        'TileSpacing', ...
        'compact', ...
        'Padding', ...
        'compact');


    for i_r = 1:numel(correlation_cases)

        nexttile;

        imagesc( ...
            dgd_plot, ...
            dgd_plot, ...
            Q_worst_maps(:, :, i_r));

        set( ...
            gca, ...
            'YDir', ...
            'normal');

        hold on;

        contour( ...
            dgd_plot, ...
            dgd_plot, ...
            Q_worst_maps(:, :, i_r), ...
            [qber_threshold, qber_threshold], ...
            'k--', ...
            'LineWidth', ...
            1.8);

        plot( ...
            dgd_plot, ...
            dgd_plot, ...
            'k:', ...
            'LineWidth', ...
            1.0);

        % Add a compact legend only to the first panel.
        if i_r == 1

            h_boundary = plot( ...
                nan, ...
                nan, ...
                'k--', ...
                'LineWidth', ...
                1.8);

            h_symmetric = plot( ...
                nan, ...
                nan, ...
                'k:', ...
                'LineWidth', ...
                1.0);

            legend( ...
                [h_boundary, h_symmetric], ...
                { ...
                    sprintf( ...
                        'Q_{worst} = %.2f', ...
                        qber_threshold), ...
                    '\Delta\tau_A = \Delta\tau_B' ...
                }, ...
                'Location', ...
                'northwest');

        end

        hold off;

        xlabel( ...
            '\Delta\tau_B [ps]');

        ylabel( ...
            '\Delta\tau_A [ps]');

        title( ...
            sprintf( ...
                'r = %+.1f', ...
                correlation_cases(i_r)));

        axis square;

        xlim([ ...
            min(dgd_plot), ...
            max(dgd_plot)]);

        ylim([ ...
            min(dgd_plot), ...
            max(dgd_plot)]);

        clim([0, 0.5]);

        grid on;

    end

    colorbar;

    % =========================
    % Figure 2 - Symmetric-DGD boundary versus correlation
    % =========================

    figure_handles.correlation_boundary = figure( ...
        'Name', ...
        'Experiment 3 - Spectral Correlation Boundary', ...
        'Visible', ...
        figure_visibility);

    valid_boundary = ...
        ~isnan(symmetric_dgd_boundary);

    plot( ...
        correlation_values(valid_boundary), ...
        symmetric_dgd_boundary(valid_boundary) * 1e12, ...
        'o-', ...
        'LineWidth', ...
        1.5, ...
        'MarkerSize', ...
        5);

    xlabel( ...
        'Spectral correlation coefficient r');

    ylabel( ...
        'Maximum symmetric DGD \Delta\tau_{th} [ps]');

    title( ...
        'BBM92 symmetric two-arm PMD tolerance');

    xlim([ ...
        min(correlation_values), ...
        max(correlation_values)]);

    grid on;

end


% ==================================================================
% Local function - Locate project root
% ==================================================================

function project_root = locate_project_root()

    experiment_file = ...
        mfilename('fullpath');

    project_root = ...
        fileparts(experiment_file);

    while ~isfolder(fullfile( ...
            project_root, ...
            'text', ...
            'thesis'))

        parent_directory = ...
            fileparts(project_root);

        if strcmp( ...
                parent_directory, ...
                project_root)

            error( ...
                ['experiment_03_two_arm_pmd_spectral_operating_regions:', ...
                 'ProjectRootNotFound'], ...
                ['Unable to locate the project root containing ', ...
                 'text/thesis.']);

        end

        project_root = ...
            parent_directory;

    end

end