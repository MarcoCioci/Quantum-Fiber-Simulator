function fig = ...
        plot_experiment_6_effective_model_comparison_regime_map( ...
            results_experiment_6, do_save)
% PLOT_EXPERIMENT_6_EFFECTIVE_MODEL_COMPARISON_REGIME_MAP
% Compare model predictions and concurrence-quality regions.
%
% Objective:
%   Display a compact model-by-PMD-strength map for:
%
%       - concurrence,
%       - global purity,
%       - maximal CHSH parameter,
%       - operational concurrence-quality classification.
%
%   Rows correspond to:
%
%       1) physical frequency-resolved PMD,
%       2) matched effective dephasing,
%       3) matched isotropic depolarization.
%
% Input:
%   results_experiment_6 - Structure produced by
%                          run_experiment_6_effective_model_comparison
%
%   do_save              - Optional logical scalar. If true, export the
%                          regime-map figure as a PNG file.
%
% Output:
%   fig                  - Handle to the Experiment 6 figure window


    % =========================
    % Default input handling
    % =========================

    if nargin < 1 || nargin > 2
        error( ...
            ['plot_experiment_6_effective_model_comparison_regime_map:', ...
             'InvalidNumInputs'], ...
            'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = ...
            false;
    end


    % =========================
    % Robustness checks
    % =========================

    if ~isstruct(results_experiment_6)
        error( ...
            ['plot_experiment_6_effective_model_comparison_regime_map:', ...
             'InvalidResultsType'], ...
            'results_experiment_6 must be a structure.');
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error( ...
            ['plot_experiment_6_effective_model_comparison_regime_map:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    required_fields = { ...
        'parameters', ...
        'physical_pmd', ...
        'effective_dephasing', ...
        'effective_depolarizing' ...
    };

    for i_field = 1:numel(required_fields)

        if ~isfield(results_experiment_6, required_fields{i_field})
            error( ...
                ['plot_experiment_6_effective_model_comparison_regime_map:', ...
                 'MissingField'], ...
                'Missing field results_experiment_6.%s.', ...
                required_fields{i_field});
        end

    end


    % =========================
    % Extract data
    % =========================

    parameters = ...
        results_experiment_6.parameters;

    physical = ...
        results_experiment_6.physical_pmd;

    dephasing = ...
        results_experiment_6.effective_dephasing;

    depolarizing = ...
        results_experiment_6.effective_depolarizing;

    xi_values = ...
        parameters.xi_values(:).';

    concurrence_threshold = ...
        parameters.concurrence_threshold;

    model_labels = { ...
        'Physical PMD', ...
        'Matched dephasing', ...
        'Isotropic depolarization' ...
    };


    % =========================
    % Map construction
    % =========================

    concurrence_map = [ ...
        physical.concurrence; ...
        dephasing.concurrence; ...
        depolarizing.concurrence ...
    ];

    purity_map = [ ...
        physical.purity; ...
        dephasing.purity; ...
        depolarizing.purity ...
    ];

    chsh_map = [ ...
        physical.chsh_max; ...
        dephasing.chsh_max; ...
        depolarizing.chsh_max ...
    ];

    quality_map = ...
        double( ...
            concurrence_map >= concurrence_threshold);


    % =========================
    % Plot style
    % =========================

    style = ...
        get_plot_style();


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = ...
        get_experiment_figure_tab( ...
            style.figure.experiment_6_id, ...
            'Model-quality regime map', ...
            'Experiment 6 — Effective Model Comparison', ...
            style);

    build_plot(tab, false);

    set( ...
        fig, ...
        'Visible', ...
        style.figure.visible_after_build);


    % =========================
    % Save
    % =========================

    if do_save

        experiment_folder = ...
            fileparts(mfilename('fullpath'));

        thesis_experiments_folder = ...
            fileparts(experiment_folder);

        experiments_folder = ...
            fileparts(thesis_experiments_folder);

        src_folder = ...
            fileparts(experiments_folder);

        project_root = ...
            fileparts(src_folder);

        output_path = ...
            fullfile( ...
                project_root, ...
                'images', ...
                'experiment_6', ...
                'experiment_6_effective_model_comparison_regime_map.png');

        export_plot( ...
            output_path, ...
            @(parent) build_plot(parent, false), ...
            style);

    end


    % =========================
    % Local plot builder
    % =========================

    function layout = build_plot(parent_container, show_title)
    % BUILD_PLOT  Build the complete Experiment 6 regime map.

        if nargin < 2
            show_title = ...
                false;
        end

        layout = ...
            tiledlayout( ...
                parent_container, ...
                2, ...
                2, ...
                'TileSpacing', style.layout.tile_spacing, ...
                'Padding', style.layout.padding);


        % =====================================================
        % Panel 1: concurrence
        % =====================================================

        ax = ...
            nexttile(layout);

        plot_map( ...
            ax, ...
            concurrence_map, ...
            [0, 1], ...
            '$C$', ...
            'Concurrence');


        % =====================================================
        % Panel 2: purity
        % =====================================================

        ax = ...
            nexttile(layout);

        plot_map( ...
            ax, ...
            purity_map, ...
            [0.25, 1], ...
            '$\gamma$', ...
            'Global purity');


        % =====================================================
        % Panel 3: CHSH
        % =====================================================

        ax = ...
            nexttile(layout);

        plot_map( ...
            ax, ...
            chsh_map, ...
            [0, 2 * sqrt(2)], ...
            '$S_{\max}$', ...
            'Optimized CHSH parameter');


        % =====================================================
        % Panel 4: concurrence quality
        % =====================================================

        ax = ...
            nexttile(layout);

        imagesc( ...
            ax, ...
            xi_values, ...
            1:3, ...
            quality_map);

        set( ...
            ax, ...
            'YDir', 'normal');

        colormap( ...
            ax, ...
            parula(2));

        clim( ...
            ax, ...
            [0, 1]);

        cb = ...
            colorbar(ax);

        cb.Ticks = ...
            [0, 1];

        cb.TickLabels = ...
            {'Below threshold', 'Meets threshold'};

        cb.TickLabelInterpreter = ...
            'none';

        configure_map_axes( ...
            ax, ...
            sprintf( ...
                'Concurrence quality: C >= %.2f', ...
                concurrence_threshold));


        % =========================
        % Global title
        % =========================

        if show_title

            title( ...
                layout, ...
                'Experiment 6 — Effective-Model Regimes', ...
                'FontSize', style.title.font_size, ...
                'FontWeight', style.title.font_weight, ...
                'Interpreter', style.title.interpreter);

        end

    end


    % =========================
    % Local map plotter
    % =========================

    function plot_map( ...
            ax, metric_map, color_limits, colorbar_label, panel_title)
    % PLOT_MAP  Plot one 3-by-N model comparison map.

        imagesc( ...
            ax, ...
            xi_values, ...
            1:3, ...
            metric_map);

        set( ...
            ax, ...
            'YDir', 'normal');

        colormap( ...
            ax, ...
            parula(256));

        clim( ...
            ax, ...
            color_limits);

        cb = ...
            colorbar(ax);

        cb.Label.String = ...
            colorbar_label;

        cb.Label.Interpreter = ...
            style.labels.interpreter;

        cb.Label.FontSize = ...
            style.labels.font_size;

        configure_map_axes( ...
            ax, ...
            panel_title);

    end


    % =========================
    % Local axes configuration
    % =========================

    function configure_map_axes(ax, panel_title)
    % CONFIGURE_MAP_AXES  Apply common formatting to one model map.

        set( ...
            ax, ...
            'FontSize', style.axes.font_size, ...
            'LineWidth', style.axes.line_width, ...
            'Box', style.axes.box, ...
            'Layer', style.axes.layer, ...
            'TickLabelInterpreter', ...
                style.axes.tick_label_interpreter, ...
            'YTick', 1:3, ...
            'YTickLabel', model_labels);

        xlim( ...
            ax, ...
            [min(xi_values), max(xi_values)]);

        ylim( ...
            ax, ...
            [0.5, 3.5]);

        xlabel( ...
            ax, ...
            '$\xi=\sigma_\omega\,\mathrm{DGD}$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title( ...
            ax, ...
            panel_title, ...
            'Interpreter', style.title.interpreter, ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight);

    end

end
