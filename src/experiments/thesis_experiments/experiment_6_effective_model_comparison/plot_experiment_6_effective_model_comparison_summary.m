function fig = ...
        plot_experiment_6_effective_model_comparison_summary( ...
            results_experiment_6, do_save)
% PLOT_EXPERIMENT_6_EFFECTIVE_MODEL_COMPARISON_SUMMARY
% Plot the principal physical/effective model comparisons.
%
% Objective:
%   Compare frequency-resolved PMD, matched dephasing, and matched isotropic
%   depolarization using concurrence, purity, maximal CHSH parameter, and
%   representative polarization correlations.
%
% Input:
%   results_experiment_6 - Structure produced by
%                          run_experiment_6_effective_model_comparison
%
%   do_save              - Optional logical scalar. If true, export the
%                          summary figure as a PNG file.
%
% Output:
%   fig                  - Handle to the Experiment 6 figure window


    % =========================
    % Default input handling
    % =========================

    if nargin < 1 || nargin > 2
        error( ...
            ['plot_experiment_6_effective_model_comparison_summary:', ...
             'InvalidNumInputs'], ...
            'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = ...
            false;
    end


    % =========================
    % Robustness checks
    % =========================

    if ~isstruct(results_experiment_6)
        error( ...
            ['plot_experiment_6_effective_model_comparison_summary:', ...
             'InvalidResultsType'], ...
            'results_experiment_6 must be a structure.');
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error( ...
            ['plot_experiment_6_effective_model_comparison_summary:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    required_fields = { ...
        'parameters', ...
        'physical_pmd', ...
        'effective_dephasing', ...
        'effective_depolarizing' ...
    };

    for i_field = 1:numel(required_fields)

        if ~isfield(results_experiment_6, required_fields{i_field})
            error( ...
                ['plot_experiment_6_effective_model_comparison_summary:', ...
                 'MissingField'], ...
                'Missing field results_experiment_6.%s.', ...
                required_fields{i_field});
        end

    end


    % =========================
    % Extract data
    % =========================

    parameters = ...
        results_experiment_6.parameters;

    physical = ...
        results_experiment_6.physical_pmd;

    dephasing = ...
        results_experiment_6.effective_dephasing;

    depolarizing = ...
        results_experiment_6.effective_depolarizing;

    xi_values = ...
        parameters.xi_values(:).';

    concurrence_threshold = ...
        parameters.concurrence_threshold;


    % =========================
    % Plot style
    % =========================

    style = ...
        get_plot_style();

    palette = ...
        get_plot_palette();


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = ...
        get_experiment_figure_tab( ...
            style.figure.experiment_6_id, ...
            'Effective-model comparison', ...
            'Experiment 6 — Effective Model Comparison', ...
            style);

    build_plot(tab, false);

    set( ...
        fig, ...
        'Visible', ...
        style.figure.visible_after_build);


    % =========================
    % Save
    % =========================

    if do_save

        experiment_folder = ...
            fileparts(mfilename('fullpath'));

        thesis_experiments_folder = ...
            fileparts(experiment_folder);

        experiments_folder = ...
            fileparts(thesis_experiments_folder);

        src_folder = ...
            fileparts(experiments_folder);

        project_root = ...
            fileparts(src_folder);

        output_path = ...
            fullfile( ...
                project_root, ...
                'images', ...
                'experiment_6', ...
                'experiment_6_effective_model_comparison_summary.png');

        export_plot( ...
            output_path, ...
            @(parent) build_plot(parent, false), ...
            style);

    end


    % =========================
    % Local plot builder
    % =========================

    function layout = build_plot(parent_container, show_title)
    % BUILD_PLOT  Build the complete Experiment 6 summary.

        if nargin < 2
            show_title = ...
                false;
        end

        layout = ...
            tiledlayout( ...
                parent_container, ...
                2, ...
                2, ...
                'TileSpacing', style.layout.tile_spacing, ...
                'Padding', style.layout.padding);


        % =====================================================
        % Panel 1: concurrence and quality threshold
        % =====================================================

        ax = ...
            nexttile(layout);

        hold(ax, 'on');

        plot( ...
            ax, ...
            xi_values, ...
            dephasing.concurrence, ...
            '-', ...
            'Color', palette.blue, ...
            'LineWidth', style.lines.width_main, ...
            'DisplayName', 'Effective dephasing');

        plot( ...
            ax, ...
            xi_values, ...
            depolarizing.concurrence, ...
            '--', ...
            'Color', palette.orange, ...
            'LineWidth', style.lines.width_main, ...
            'DisplayName', 'Isotropic depolarization');

        plot( ...
            ax, ...
            xi_values, ...
            physical.concurrence, ...
            'o', ...
            'LineStyle', 'none', ...
            'Color', palette.black, ...
            'MarkerSize', style.markers.size, ...
            'DisplayName', 'Physical PMD');

        yline( ...
            ax, ...
            concurrence_threshold, ...
            ':', ...
            '$C_{\mathrm{th}}$', ...
            'Interpreter', 'latex', ...
            'LineWidth', style.lines.width_secondary, ...
            'Color', palette.red, ...
            'HandleVisibility', 'off');

        add_threshold_line( ...
            ax, ...
            parameters.xi_threshold_physical, ...
            palette.blue);

        add_threshold_line( ...
            ax, ...
            parameters.xi_threshold_depolarizing, ...
            palette.orange);

        configure_axes( ...
            ax, ...
            '$\xi=\sigma_\omega\,\mathrm{DGD}$', ...
            '$C$', ...
            'Concurrence and operational quality', ...
            [0, 1.05]);

        legend( ...
            ax, ...
            'Location', style.legend.location, ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);


        % =====================================================
        % Panel 2: purity
        % =====================================================

        ax = ...
            nexttile(layout);

        hold(ax, 'on');

        plot_model_triplet( ...
            ax, ...
            physical.purity, ...
            dephasing.purity, ...
            depolarizing.purity);

        configure_axes( ...
            ax, ...
            '$\xi=\sigma_\omega\,\mathrm{DGD}$', ...
            '$\gamma=\mathrm{Tr}(\rho^2)$', ...
            'Global polarization purity', ...
            [0.2, 1.05]);


        % =====================================================
        % Panel 3: maximal CHSH
        % =====================================================

        ax = ...
            nexttile(layout);

        hold(ax, 'on');

        plot_model_triplet( ...
            ax, ...
            physical.chsh_max, ...
            dephasing.chsh_max, ...
            depolarizing.chsh_max);

        yline( ...
            ax, ...
            2, ...
            ':', ...
            '$S_{\max}=2$', ...
            'Interpreter', 'latex', ...
            'LineWidth', style.lines.width_secondary, ...
            'Color', palette.red, ...
            'HandleVisibility', 'off');

        configure_axes( ...
            ax, ...
            '$\xi=\sigma_\omega\,\mathrm{DGD}$', ...
            '$S_{\max}$', ...
            'Optimized CHSH parameter', ...
            [0, 2 * sqrt(2) + 0.1]);


        % =====================================================
        % Panel 4: correlation structure
        % =====================================================

        ax = ...
            nexttile(layout);

        hold(ax, 'on');

        % The transverse component is deliberately matched by both
        % effective models.
        plot( ...
            ax, ...
            xi_values, ...
            physical.c_xx, ...
            ':', ...
            'Color', palette.gray_dark, ...
            'LineWidth', style.lines.width_secondary, ...
            'DisplayName', '$c_{xx}$ (all models)');

        % Longitudinal correlation distinguishes anisotropic PMD/dephasing
        % from isotropic depolarization.
        plot( ...
            ax, ...
            xi_values, ...
            dephasing.c_zz, ...
            '-', ...
            'Color', palette.blue, ...
            'LineWidth', style.lines.width_main, ...
            'DisplayName', '$c_{zz}$ PMD/dephasing');

        plot( ...
            ax, ...
            xi_values, ...
            depolarizing.c_zz, ...
            '--', ...
            'Color', palette.orange, ...
            'LineWidth', style.lines.width_main, ...
            'DisplayName', '$c_{zz}$ depolarizing');

        plot( ...
            ax, ...
            xi_values, ...
            physical.c_zz, ...
            'o', ...
            'LineStyle', 'none', ...
            'Color', palette.black, ...
            'MarkerSize', style.markers.size, ...
            'HandleVisibility', 'off');

        configure_axes( ...
            ax, ...
            '$\xi=\sigma_\omega\,\mathrm{DGD}$', ...
            '$c_{ij}$', ...
            'Matched transverse decay, different longitudinal behavior', ...
            [-1.1, 1.1]);

        legend( ...
            ax, ...
            'Location', style.legend.location, ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);


        % =========================
        % Global title
        % =========================

        if show_title

            title( ...
                layout, ...
                'Experiment 6 — Physical PMD vs Effective Models', ...
                'FontSize', style.title.font_size, ...
                'FontWeight', style.title.font_weight, ...
                'Interpreter', style.title.interpreter);

        end

    end


    % =========================
    % Local model-triplet plotter
    % =========================

    function plot_model_triplet( ...
            ax, physical_values, dephasing_values, depolarizing_values)
    % PLOT_MODEL_TRIPLET  Plot physical PMD markers and two effective lines.

        plot( ...
            ax, ...
            xi_values, ...
            dephasing_values, ...
            '-', ...
            'Color', palette.blue, ...
            'LineWidth', style.lines.width_main, ...
            'DisplayName', 'Effective dephasing');

        plot( ...
            ax, ...
            xi_values, ...
            depolarizing_values, ...
            '--', ...
            'Color', palette.orange, ...
            'LineWidth', style.lines.width_main, ...
            'DisplayName', 'Isotropic depolarization');

        plot( ...
            ax, ...
            xi_values, ...
            physical_values, ...
            'o', ...
            'LineStyle', 'none', ...
            'Color', palette.black, ...
            'MarkerSize', style.markers.size, ...
            'DisplayName', 'Physical PMD');

        legend( ...
            ax, ...
            'Location', style.legend.location, ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);

    end


    % =========================
    % Local axes configuration
    % =========================

    function configure_axes( ...
            ax, x_label, y_label, panel_title, y_limits)
    % CONFIGURE_AXES  Apply common Experiment 6 axes formatting.

        set( ...
            ax, ...
            'FontSize', style.axes.font_size, ...
            'LineWidth', style.axes.line_width, ...
            'Box', style.axes.box, ...
            'Layer', style.axes.layer, ...
            'TickLabelInterpreter', ...
                style.axes.tick_label_interpreter);

        grid( ...
            ax, ...
            style.axes.grid);

        xlim( ...
            ax, ...
            [min(xi_values), max(xi_values)]);

        ylim( ...
            ax, ...
            y_limits);

        xlabel( ...
            ax, ...
            x_label, ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel( ...
            ax, ...
            y_label, ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title( ...
            ax, ...
            panel_title, ...
            'Interpreter', style.title.interpreter, ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight);

    end


    % =========================
    % Local threshold marker
    % =========================

    function add_threshold_line(ax, xi_threshold, line_color)
    % ADD_THRESHOLD_LINE  Mark an analytical concurrence-quality crossing.

        if xi_threshold >= min(xi_values) && ...
                xi_threshold <= max(xi_values)

            xline( ...
                ax, ...
                xi_threshold, ...
                '--', ...
                'LineWidth', 1.0, ...
                'Color', line_color, ...
                'HandleVisibility', 'off');

        end

    end

end
