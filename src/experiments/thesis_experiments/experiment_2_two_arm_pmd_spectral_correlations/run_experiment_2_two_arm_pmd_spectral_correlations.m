function results_experiment_2 = ...
        run_experiment_2_two_arm_pmd_spectral_correlations( ...
            do_summary_plot, do_regime_map, do_save)
% RUN_EXPERIMENT_2_TWO_ARM_PMD_SPECTRAL_CORRELATIONS
% Study two-arm PMD under different two-photon spectral correlations.
%
% Objective:
%   Numerically investigate how correlations between the angular-frequency
%   offsets of two polarization-entangled photons modify PMD-induced
%   polarization decoherence when both photons propagate through
%   birefringent segments.
%
%   The input polarization state is
%
%       |Ψ+⟩ = (|01⟩ + |10⟩) / sqrt(2).
%
%   Both arms contain one PMD segment with equal physical differential
%   group delay
%
%       τ_A = τ_B = τ,
%
%   but opposite birefringence axes
%
%       n_A = +z_hat,
%       n_B = -z_hat.
%
%   The deterministic carrier-frequency differential phases are set to
%   zero so that the experiment isolates the frequency-dependent PMD
%   contribution.
%
%   The marginal angular-frequency standard deviation of each photon is
%   fixed to σ_ω, while the joint spectrum is varied through the spectral
%   correlation coefficient
%
%       r = Cov(Ω_A, Ω_B) / σ_ω^2.
%
%   The corresponding Gaussian widths are
%
%       σ_sum^2        = 2 σ_ω^2 (1 + r),
%       σ_difference^2 = 2 σ_ω^2 (1 - r).
%
%   For the chosen opposite PMD axes and equal DGD values, the
%   frequency-dependent relative phase is
%
%       θ = τ (Ω_A + Ω_B).
%
%   Consequently, the continuous Gaussian analytical prediction for the
%   residual polarization coherence is
%
%       g(τ,r)
%       =
%       exp[-σ_ω^2 τ^2 (1 + r)].
%
%   Introducing the normalized PMD strength
%
%       ξ = σ_ω τ,
%
%   gives
%
%       g(ξ,r) = exp[-(1+r) ξ^2].
%
% Input:
%   do_summary_plot - Logical scalar. If true, generate the Experiment 2
%                     summary figure.
%
%   do_regime_map   - Logical scalar. If true, generate the Experiment 2
%                     spectral-correlation regime map.
%
%   do_save         - Logical scalar. If true, save generated figures.
%
% Output:
%   results_experiment_2 - Structure containing:
%
%       .parameters
%       .spectrum
%       .input
%       .numerical
%       .analytical
%       .error
%       .max_abs_error
%
% Notes:
%   All physical and numerical parameters defining Experiment 2 are
%   intentionally configured inside this runner. The top-level main.m
%   therefore controls only experiment selection, plotting, and saving.
%
%   Scalar metric maps have dimensions
%
%       N_r x N_DGD.
%
%   The density-operator array has dimensions
%
%       4 x 4 x N_r x N_DGD.
%
%   The correlation-tensor array has dimensions
%
%       3 x 3 x N_r x N_DGD.
%
%   Frequency-resolved polarization states depend on the DGD and fiber
%   transformations, but not on the spectral probability distribution.
%   They are therefore computed once per DGD value and reused for all
%   spectral-correlation values.


    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 3
        error( ...
            ['run_experiment_2_two_arm_pmd_spectral_correlations:', ...
             'InvalidNumInputs'], ...
            ['Expected exactly 3 input arguments: do_summary_plot, ', ...
             'do_regime_map, do_save.']);
    end

    if ~islogical(do_summary_plot) || ~isscalar(do_summary_plot)
        error( ...
            ['run_experiment_2_two_arm_pmd_spectral_correlations:', ...
             'InvalidDoSummaryPlot'], ...
            'do_summary_plot must be a logical scalar.');
    end

    if ~islogical(do_regime_map) || ~isscalar(do_regime_map)
        error( ...
            ['run_experiment_2_two_arm_pmd_spectral_correlations:', ...
             'InvalidDoRegimeMap'], ...
            'do_regime_map must be a logical scalar.');
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error( ...
            ['run_experiment_2_two_arm_pmd_spectral_correlations:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end


    % =========================
    % Experiment configuration
    % =========================

    % Marginal angular-frequency standard deviation of each photon.
    sigma_omega = ...
        1.0e11;  % rad/s

    % Normalized PMD strength:
    %
    %   xi = sigma_omega * tau.
    %
    % The sweep reaches the strongly decoherent regime while retaining the
    % analytically transparent dimensionless representation.
    xi_values = ...
        linspace(0, 4, 61);

    % Physical DGD values corresponding to the normalized PMD sweep.
    dgd_values = ...
        xi_values / sigma_omega;

    % Two-photon spectral correlation coefficient.
    %
    %   r < 0  -> frequency anticorrelation
    %   r = 0  -> uncorrelated spectrum
    %   r > 0  -> positive frequency correlation
    %
    % The limiting values +/-1 are excluded because one of the Gaussian
    % principal widths would become exactly zero.
    correlation_values = ...
        linspace(-0.9, 0.9, 37);

    % Number of angular-frequency nodes per arm.
    %
    % An odd number guarantees that Omega = 0 is sampled exactly.
    % Experiment 2 uses a slightly denser grid than the single-arm
    % experiment because strongly correlated spectra contain narrower
    % Gaussian directions.
    num_frequency_points = ...
        101;

    % Symmetric numerical frequency window:
    %
    %   Omega in [-K sigma_omega, +K sigma_omega].
    max_offset_factor = ...
        6.0;


    % =========================
    % Input normalization
    % =========================

    dgd_values = ...
        dgd_values(:).';

    correlation_values = ...
        correlation_values(:);

    num_dgd_values = ...
        numel(dgd_values);

    num_correlation_values = ...
        numel(correlation_values);


    % =========================
    % Input polarization state
    % =========================

    psi_input = ...
        bell_state('psi_plus');

    rho_input = ...
        state_to_density_matrix(psi_input);


    % =========================
    % Fixed fiber configuration
    % =========================

    % Arm A:
    %
    %   - one PMD segment
    %   - zero deterministic carrier phase
    %   - birefringence axis +z

    delta_phase_A = ...
        0;

    axis_A = ...
        [0, 0, 1];

    % Arm B:
    %
    %   - equal physical DGD magnitude
    %   - zero deterministic carrier phase
    %   - opposite birefringence axis -z
    %
    % This opposite orientation makes the effective Bell-state phase
    % proportional to Omega_A + Omega_B and therefore exposes nonlocal
    % compensation for anticorrelated spectra.

    delta_phase_B = ...
        0;

    axis_B = ...
        [0, 0, -1];


    % =========================
    % Analytical reference
    % =========================

    analytics = ...
        analytical_values_experiment_2_two_arm_pmd_spectral_correlations( ...
            dgd_values, ...
            sigma_omega, ...
            correlation_values);

    sigma_sum_values = ...
        analytics.sigma_sum_values;

    sigma_difference_values = ...
        analytics.sigma_difference_values;

    normalized_pmd_strength = ...
        analytics.normalized_pmd_strength;


    % =========================
    % Frequency grid
    % =========================

    max_frequency_offset = ...
        max_offset_factor * sigma_omega;

    [omega_offsets, delta_omega] = ...
        pmd_frequency_grid( ...
            num_frequency_points, ...
            max_frequency_offset);


    % =========================
    % Spectral-resolution check
    % =========================

    % Strong spectral correlations make either sigma_sum or
    % sigma_difference significantly narrower than sigma_omega.
    %
    % This diagnostic estimates how many frequency-grid intervals resolve
    % the narrowest Gaussian standard deviation.

    minimum_spectral_width = ...
        min( ...
            [ ...
                sigma_sum_values; ...
                sigma_difference_values ...
            ], ...
            [], ...
            'all');

    points_per_minimum_sigma = ...
        minimum_spectral_width / delta_omega;

    if points_per_minimum_sigma < 3

        warning( ...
            ['run_experiment_2_two_arm_pmd_spectral_correlations:', ...
             'CoarseSpectralResolution'], ...
            ['The narrowest JSI standard deviation is sampled by only ', ...
             '%.2f grid intervals. Increase num_frequency_points or ', ...
             'reduce the maximum |r| if analytical agreement becomes ', ...
             'insufficient.'], ...
            points_per_minimum_sigma);

    end


    % =========================
    % Joint spectral weights
    % =========================

    % One normalized JSI is constructed for every value of r.
    %
    % The same frequency grid is used on arms A and B because the marginal
    % bandwidths are equal.

    spectral_weights = ...
        zeros( ...
            num_frequency_points, ...
            num_frequency_points, ...
            num_correlation_values);

    for i_correlation = 1:num_correlation_values

        spectral_weights(:, :, i_correlation) = ...
            pmd_joint_spectral_weights( ...
                omega_offsets, ...
                omega_offsets, ...
                sigma_sum_values(i_correlation), ...
                sigma_difference_values(i_correlation));

    end


    % =========================
    % Preallocation
    % =========================

    rho_output = ...
        complex( ...
            zeros( ...
                4, ...
                4, ...
                num_correlation_values, ...
                num_dgd_values));

    purity = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    purity_A = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    purity_B = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    fidelity = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    concurrence = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    tangle = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    entanglement_of_formation = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    chsh_max = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    correlation_tensor = ...
        zeros( ...
            3, ...
            3, ...
            num_correlation_values, ...
            num_dgd_values);

    correlation_xx = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    correlation_yy = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    correlation_zz = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);


    % =========================
    % Console experiment header
    % =========================

    fprintf('\n');
    fprintf('============================================\n');
    fprintf(' Experiment 2 — Two-Arm PMD\n');
    fprintf(' Spectral Correlations\n');
    fprintf('============================================\n');

    fprintf('DGD points:              %d\n', ...
        num_dgd_values);

    fprintf('Correlation points:      %d\n', ...
        num_correlation_values);

    fprintf('Frequency nodes / arm:   %d\n', ...
        num_frequency_points);

    fprintf('Marginal sigma_omega:    %.3e rad/s\n', ...
        sigma_omega);

    fprintf('Spectral window:         +/- %.1f sigma_omega\n', ...
        max_offset_factor);

    fprintf('Maximum xi:              %.3f\n', ...
        max(normalized_pmd_strength, [], 'all'));

    fprintf('Correlation range:       [%.3f, %.3f]\n', ...
        min(correlation_values), ...
        max(correlation_values));

    fprintf('Grid intervals / min σ:  %.2f\n', ...
        points_per_minimum_sigma);

    fprintf('\n');


    % =========================
    % Numerical parameter sweep
    % =========================

    % The frequency-resolved propagated state depends on the fiber
    % transformations and on DGD, but not on the JSI used for the final
    % spectral average.
    %
    % Therefore the expensive propagation is performed once per DGD value
    % and reused for every spectral-correlation coefficient.

    for i_dgd = 1:num_dgd_values

        dgd = ...
            dgd_values(i_dgd);

        delta_tau_A = ...
            dgd;

        delta_tau_B = ...
            dgd;


        % =========================
        % Progress monitoring
        % =========================

        fprintf( ...
            'DGD %2d/%2d: tau = %.3e s, xi = %.3f\n', ...
            i_dgd, ...
            num_dgd_values, ...
            dgd, ...
            normalized_pmd_strength(i_dgd));


        % =========================
        % Frequency-resolved PMD
        % =========================

        frequency_states = ...
            pmd_frequency_resolved_states( ...
                rho_input, ...
                omega_offsets, ...
                omega_offsets, ...
                delta_phase_A, ...
                delta_tau_A, ...
                axis_A, ...
                delta_phase_B, ...
                delta_tau_B, ...
                axis_B);


        % =========================
        % Spectral-correlation sweep
        % =========================

        for i_correlation = 1:num_correlation_values

            weights_current = ...
                spectral_weights(:, :, i_correlation);


            % =========================
            % Spectral trace
            % =========================

            rho_current = ...
                pmd_spectral_average_state( ...
                    frequency_states, ...
                    weights_current);

            % Remove numerical anti-Hermitian residuals produced solely by
            % finite floating-point arithmetic.
            rho_current = ...
                (rho_current + rho_current') / 2;

            rho_output( ...
                :, :, i_correlation, i_dgd) = ...
                rho_current;


            % =========================
            % Reduced density operators
            % =========================

            rho_A_current = ...
                partial_trace_B(rho_current);

            rho_B_current = ...
                partial_trace_A(rho_current);


            % =========================
            % State metrics
            % =========================

            purity(i_correlation, i_dgd) = ...
                compute_purity(rho_current);

            purity_A(i_correlation, i_dgd) = ...
                compute_purity(rho_A_current);

            purity_B(i_correlation, i_dgd) = ...
                compute_purity(rho_B_current);

            fidelity(i_correlation, i_dgd) = ...
                compute_fidelity( ...
                    rho_current, ...
                    rho_input);

            concurrence(i_correlation, i_dgd) = ...
                compute_concurrence(rho_current);

            tangle(i_correlation, i_dgd) = ...
                compute_tangle(rho_current);

            entanglement_of_formation(i_correlation, i_dgd) = ...
                compute_entanglement_of_formation( ...
                    rho_current);


            % =========================
            % Correlation tensor
            % =========================

            T_current = ...
                compute_correlation_tensor( ...
                    rho_current);

            correlation_tensor( ...
                :, :, i_correlation, i_dgd) = ...
                real(T_current);

            correlation_xx(i_correlation, i_dgd) = ...
                real(T_current(1, 1));

            correlation_yy(i_correlation, i_dgd) = ...
                real(T_current(2, 2));

            correlation_zz(i_correlation, i_dgd) = ...
                real(T_current(3, 3));


            % =========================
            % Maximal CHSH value
            % =========================

            chsh_max(i_correlation, i_dgd) = ...
                compute_chsh_max_from_tensor( ...
                    T_current);

        end

    end


    % =========================
    % Numerical errors
    % =========================

    error_struct = ...
        struct();

    error_struct.purity = ...
        abs( ...
            purity ...
            - analytics.purity);

    error_struct.purity_A = ...
        abs( ...
            purity_A ...
            - analytics.purity_A);

    error_struct.purity_B = ...
        abs( ...
            purity_B ...
            - analytics.purity_B);

    error_struct.fidelity = ...
        abs( ...
            fidelity ...
            - analytics.fidelity);

    error_struct.concurrence = ...
        abs( ...
            concurrence ...
            - analytics.concurrence);

    error_struct.tangle = ...
        abs( ...
            tangle ...
            - analytics.tangle);

    error_struct.entanglement_of_formation = ...
        abs( ...
            entanglement_of_formation ...
            - analytics.entanglement_of_formation);

    error_struct.chsh_max = ...
        abs( ...
            chsh_max ...
            - analytics.chsh_max);

    error_struct.correlation_xx = ...
        abs( ...
            correlation_xx ...
            - analytics.correlations.xx);

    error_struct.correlation_yy = ...
        abs( ...
            correlation_yy ...
            - analytics.correlations.yy);

    error_struct.correlation_zz = ...
        abs( ...
            correlation_zz ...
            - analytics.correlations.zz);


    % =========================
    % Correlation-tensor error
    % =========================

    error_struct.correlation_tensor_frobenius = ...
        zeros( ...
            num_correlation_values, ...
            num_dgd_values);

    for i_correlation = 1:num_correlation_values

        for i_dgd = 1:num_dgd_values

            numerical_tensor = ...
                correlation_tensor( ...
                    :, :, i_correlation, i_dgd);

            analytical_tensor = ...
                analytics.correlation_tensor( ...
                    :, :, i_correlation, i_dgd);

            error_struct.correlation_tensor_frobenius( ...
                i_correlation, i_dgd) = ...
                norm( ...
                    numerical_tensor ...
                    - analytical_tensor, ...
                    'fro');

        end

    end


    % =========================
    % Maximum errors
    % =========================

    max_abs_error = ...
        struct();

    max_abs_error.purity = ...
        max( ...
            error_struct.purity, ...
            [], ...
            'all');

    max_abs_error.purity_A = ...
        max( ...
            error_struct.purity_A, ...
            [], ...
            'all');

    max_abs_error.purity_B = ...
        max( ...
            error_struct.purity_B, ...
            [], ...
            'all');

    max_abs_error.fidelity = ...
        max( ...
            error_struct.fidelity, ...
            [], ...
            'all');

    max_abs_error.concurrence = ...
        max( ...
            error_struct.concurrence, ...
            [], ...
            'all');

    max_abs_error.tangle = ...
        max( ...
            error_struct.tangle, ...
            [], ...
            'all');

    max_abs_error.entanglement_of_formation = ...
        max( ...
            error_struct.entanglement_of_formation, ...
            [], ...
            'all');

    max_abs_error.chsh_max = ...
        max( ...
            error_struct.chsh_max, ...
            [], ...
            'all');

    max_abs_error.correlation_xx = ...
        max( ...
            error_struct.correlation_xx, ...
            [], ...
            'all');

    max_abs_error.correlation_yy = ...
        max( ...
            error_struct.correlation_yy, ...
            [], ...
            'all');

    max_abs_error.correlation_zz = ...
        max( ...
            error_struct.correlation_zz, ...
            [], ...
            'all');

    max_abs_error.correlation_tensor_frobenius = ...
        max( ...
            error_struct.correlation_tensor_frobenius, ...
            [], ...
            'all');


    % =========================
    % Output structure
    % =========================

    results_experiment_2 = ...
        struct();


    % -------------------------
    % Experiment parameters
    % -------------------------

    results_experiment_2.parameters = ...
        struct();

    results_experiment_2.parameters.dgd_values = ...
        dgd_values;

    results_experiment_2.parameters.sigma_omega = ...
        sigma_omega;

    results_experiment_2.parameters.correlation_values = ...
        correlation_values;

    results_experiment_2.parameters.sigma_sum_values = ...
        sigma_sum_values;

    results_experiment_2.parameters.sigma_difference_values = ...
        sigma_difference_values;

    results_experiment_2.parameters.normalized_pmd_strength = ...
        normalized_pmd_strength;

    results_experiment_2.parameters.num_frequency_points = ...
        num_frequency_points;

    results_experiment_2.parameters.max_offset_factor = ...
        max_offset_factor;

    results_experiment_2.parameters.max_frequency_offset = ...
        max_frequency_offset;

    results_experiment_2.parameters.delta_omega = ...
        delta_omega;

    results_experiment_2.parameters.points_per_minimum_sigma = ...
        points_per_minimum_sigma;

    results_experiment_2.parameters.delta_phase_A = ...
        delta_phase_A;

    results_experiment_2.parameters.axis_A = ...
        axis_A;

    results_experiment_2.parameters.delta_phase_B = ...
        delta_phase_B;

    results_experiment_2.parameters.axis_B = ...
        axis_B;


    % -------------------------
    % Spectral discretization
    % -------------------------

    results_experiment_2.spectrum = ...
        struct();

    results_experiment_2.spectrum.omega_offsets = ...
        omega_offsets;

    results_experiment_2.spectrum.spectral_weights = ...
        spectral_weights;


    % -------------------------
    % Input state
    % -------------------------

    results_experiment_2.input = ...
        struct();

    results_experiment_2.input.psi = ...
        psi_input;

    results_experiment_2.input.rho = ...
        rho_input;


    % -------------------------
    % Numerical results
    % -------------------------

    results_experiment_2.numerical = ...
        struct();

    results_experiment_2.numerical.rho_output = ...
        rho_output;

    results_experiment_2.numerical.purity = ...
        purity;

    results_experiment_2.numerical.purity_A = ...
        purity_A;

    results_experiment_2.numerical.purity_B = ...
        purity_B;

    results_experiment_2.numerical.fidelity = ...
        fidelity;

    results_experiment_2.numerical.concurrence = ...
        concurrence;

    results_experiment_2.numerical.tangle = ...
        tangle;

    results_experiment_2.numerical.entanglement_of_formation = ...
        entanglement_of_formation;

    results_experiment_2.numerical.chsh_max = ...
        chsh_max;

    results_experiment_2.numerical.correlation_tensor = ...
        correlation_tensor;

    results_experiment_2.numerical.correlations = ...
        struct();

    results_experiment_2.numerical.correlations.xx = ...
        correlation_xx;

    results_experiment_2.numerical.correlations.yy = ...
        correlation_yy;

    results_experiment_2.numerical.correlations.zz = ...
        correlation_zz;


    % -------------------------
    % Analytical reference
    % -------------------------

    results_experiment_2.analytical = ...
        analytics;


    % -------------------------
    % Validation errors
    % -------------------------

    results_experiment_2.error = ...
        error_struct;

    results_experiment_2.max_abs_error = ...
        max_abs_error;


    % =========================
    % Validation summary
    % =========================

    fprintf('\n');
    fprintf('Validation against continuous Gaussian theory\n');
    fprintf('--------------------------------------------\n');

    fprintf('max |purity error|       : %.3e\n', ...
        max_abs_error.purity);

    fprintf('max |local purity A|     : %.3e\n', ...
        max_abs_error.purity_A);

    fprintf('max |local purity B|     : %.3e\n', ...
        max_abs_error.purity_B);

    fprintf('max |F_Psi+ error|       : %.3e\n', ...
        max_abs_error.fidelity);

    fprintf('max |C error|            : %.3e\n', ...
        max_abs_error.concurrence);

    fprintf('max |tangle error|       : %.3e\n', ...
        max_abs_error.tangle);

    fprintf('max |E_F error|          : %.3e\n', ...
        max_abs_error.entanglement_of_formation);

    fprintf('max |S_max error|        : %.3e\n', ...
        max_abs_error.chsh_max);

    fprintf('max |c_xx error|         : %.3e\n', ...
        max_abs_error.correlation_xx);

    fprintf('max |c_yy error|         : %.3e\n', ...
        max_abs_error.correlation_yy);

    fprintf('max |c_zz error|         : %.3e\n', ...
        max_abs_error.correlation_zz);

    fprintf('max tensor ||error||_F   : %.3e\n', ...
        max_abs_error.correlation_tensor_frobenius);

    fprintf('============================================\n\n');


    % =========================
    % Plotting
    % =========================

    if do_summary_plot

        plot_experiment_2_two_arm_pmd_spectral_correlations_summary( ...
            results_experiment_2, ...
            do_save);

    end

    if do_regime_map

        plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map( ...
            results_experiment_2, ...
            do_save);

    end

end