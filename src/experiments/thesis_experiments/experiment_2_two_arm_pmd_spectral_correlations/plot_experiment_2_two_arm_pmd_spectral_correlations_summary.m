function fig = ...
        plot_experiment_2_two_arm_pmd_spectral_correlations_summary( ...
            results_experiment_2, do_save)
% PLOT_EXPERIMENT_2_TWO_ARM_PMD_SPECTRAL_CORRELATIONS_SUMMARY
% Plot the main summary of Experiment 2.
%
% Objective:
%   Compare numerical and analytical predictions for the two-arm PMD
%   experiment under different two-photon spectral correlations.
%
%   The figure contains four panels:
%
%       1) concurrence C
%       2) Bell-state fidelity F_{Ψ+}
%       3) global polarization-state purity γ(ρ_AB)
%       4) maximal CHSH parameter S_max
%
%   Each quantity is plotted as a function of the normalized PMD strength
%
%       ξ = σ_ω τ
%
%   for representative values of the spectral correlation coefficient r.
%
%   Analytical predictions are shown as continuous curves, while numerical
%   PMD results are shown as markers.
%
% Input:
%   results_experiment_2 - Structure returned by
%                          run_experiment_2_two_arm_pmd_spectral_correlations.
%
%   do_save              - Optional logical scalar controlling figure
%                          export. Default: false.
%
% Output:
%   fig - Handle of the Experiment 2 figure window.
%
% Notes:
%   If more than seven spectral-correlation values are present, only seven
%   representative cases are displayed in the summary to avoid excessive
%   visual clutter. The complete parameter space is shown by the dedicated
%   regime-map figure.
%
%   Spectral-correlation cases are color-coded continuously from negative
%   correlation to positive correlation using the centralized plot palette.


    % =========================
    % Robustness checks
    % =========================

    if nargin < 1 || nargin > 2
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
             'InvalidNumInputs'], ...
            'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = false;
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    if ~isstruct(results_experiment_2)
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
             'InvalidInputType'], ...
            'results_experiment_2 must be a structure.');
    end

    required_top_fields = { ...
        'parameters', ...
        'numerical', ...
        'analytical' ...
    };

    for k = 1:numel(required_top_fields)

        if ~isfield(results_experiment_2, required_top_fields{k})
            error( ...
                ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
                 'MissingField'], ...
                'Missing required field "%s".', ...
                required_top_fields{k});
        end

    end

    required_parameter_fields = { ...
        'normalized_pmd_strength', ...
        'correlation_values' ...
    };

    for k = 1:numel(required_parameter_fields)

        if ~isfield( ...
                results_experiment_2.parameters, ...
                required_parameter_fields{k})
            error( ...
                ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
                 'MissingParameterField'], ...
                'Missing parameter field "%s".', ...
                required_parameter_fields{k});
        end

    end

    required_numerical_fields = { ...
        'purity', ...
        'fidelity', ...
        'concurrence', ...
        'chsh_max' ...
    };

    for k = 1:numel(required_numerical_fields)

        if ~isfield( ...
                results_experiment_2.numerical, ...
                required_numerical_fields{k})
            error( ...
                ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
                 'MissingNumericalField'], ...
                'Missing numerical field "%s".', ...
                required_numerical_fields{k});
        end

    end

    required_analytical_fields = { ...
        'purity', ...
        'fidelity', ...
        'concurrence', ...
        'chsh_max' ...
    };

    for k = 1:numel(required_analytical_fields)

        if ~isfield( ...
                results_experiment_2.analytical, ...
                required_analytical_fields{k})
            error( ...
                ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
                 'MissingAnalyticalField'], ...
                'Missing analytical field "%s".', ...
                required_analytical_fields{k});
        end

    end


    % =========================
    % Independent variables
    % =========================

    xi_raw = ...
        results_experiment_2.parameters.normalized_pmd_strength(:).';

    correlation_raw = ...
        results_experiment_2.parameters.correlation_values(:);

    if isempty(xi_raw) || ...
            ~isnumeric(xi_raw) || ...
            any(~isfinite(xi_raw), 'all')
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
             'InvalidPMDStrength'], ...
            ['normalized_pmd_strength must be a non-empty finite ', ...
             'numeric vector.']);
    end

    if isempty(correlation_raw) || ...
            ~isnumeric(correlation_raw) || ...
            any(~isfinite(correlation_raw), 'all')
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
             'InvalidCorrelationValues'], ...
            ['correlation_values must be a non-empty finite numeric ', ...
             'vector.']);
    end

    num_xi = numel(xi_raw);
    num_correlation = numel(correlation_raw);

    expected_size = ...
        [num_correlation, num_xi];


    % =========================
    % Validate metric maps
    % =========================

    numerical_maps = { ...
        results_experiment_2.numerical.purity, ...
        results_experiment_2.numerical.fidelity, ...
        results_experiment_2.numerical.concurrence, ...
        results_experiment_2.numerical.chsh_max ...
    };

    analytical_maps = { ...
        results_experiment_2.analytical.purity, ...
        results_experiment_2.analytical.fidelity, ...
        results_experiment_2.analytical.concurrence, ...
        results_experiment_2.analytical.chsh_max ...
    };

    for k = 1:numel(numerical_maps)

        validate_metric_map( ...
            numerical_maps{k}, ...
            expected_size, ...
            'numerical');

        validate_metric_map( ...
            analytical_maps{k}, ...
            expected_size, ...
            'analytical');

    end


    % =========================
    % Sort plotting coordinates
    % =========================

    % Sorting is performed only for visualization. The experiment result
    % structure itself remains unchanged.

    [xi, xi_order] = ...
        sort(xi_raw);

    [correlation_values, correlation_order] = ...
        sort(correlation_raw);


    % =========================
    % Extract ordered data
    % =========================

    data = struct();

    data.xi = ...
        xi;

    data.correlation_values = ...
        correlation_values;

    data.purity_num = ...
        results_experiment_2.numerical.purity( ...
            correlation_order, xi_order);

    data.purity_th = ...
        results_experiment_2.analytical.purity( ...
            correlation_order, xi_order);

    data.fidelity_num = ...
        results_experiment_2.numerical.fidelity( ...
            correlation_order, xi_order);

    data.fidelity_th = ...
        results_experiment_2.analytical.fidelity( ...
            correlation_order, xi_order);

    data.concurrence_num = ...
        results_experiment_2.numerical.concurrence( ...
            correlation_order, xi_order);

    data.concurrence_th = ...
        results_experiment_2.analytical.concurrence( ...
            correlation_order, xi_order);

    data.chsh_num = ...
        results_experiment_2.numerical.chsh_max( ...
            correlation_order, xi_order);

    data.chsh_th = ...
        results_experiment_2.analytical.chsh_max( ...
            correlation_order, xi_order);


    % =========================
    % Plot style
    % =========================

    palette = ...
        get_plot_palette();

    style = ...
        get_plot_style();


    % =========================
    % Representative curves
    % =========================

    data.selected_indices = ...
        select_representative_indices( ...
            num_correlation, ...
            7);

    data.curve_colors = ...
        spectral_correlation_colors( ...
            correlation_values(data.selected_indices), ...
            palette);


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = ...
        get_experiment_figure_tab( ...
            style.figure.experiment_2_id, ...
            'Summary', ...
            'Experiment 2 — Two-Arm PMD and Spectral Correlations', ...
            style);

    build_experiment_2_summary_plot( ...
        tab, ...
        data, ...
        style, ...
        palette, ...
        false);

    set( ...
        fig, ...
        'Visible', ...
        style.figure.visible_after_build);


    % =========================
    % Save
    % =========================

    if do_save

        output_folder = [ ...
            '/home/marcocioci/HPC/THESIS-Quantum-Communications/', ...
            'Quantum-Fiber-Simulator/images/experiment_2'];

        if ~exist(output_folder, 'dir')
            mkdir(output_folder);
        end

        output_path = ...
            fullfile( ...
                output_folder, ...
                ['experiment_2_two_arm_pmd_', ...
                 'spectral_correlations_summary.png']);

        export_plot( ...
            output_path, ...
            @(parent) build_experiment_2_summary_plot( ...
                parent, ...
                data, ...
                style, ...
                palette, ...
                false), ...
            style);

    end

end


function tl = ...
        build_experiment_2_summary_plot( ...
            parent, data, style, palette, show_title)
% BUILD_EXPERIMENT_2_SUMMARY_PLOT  Build the Experiment 2 summary figure.
%
% Objective:
%   Construct the four-panel analytical-versus-numerical comparison.
%
% Input:
%   parent     - Parent figure or tab container.
%   data       - Ordered Experiment 2 plotting data.
%   style      - Centralized plot-style structure.
%   palette    - Centralized plot palette.
%   show_title - Logical flag controlling the global figure title.
%
% Output:
%   tl - Tiled-layout handle.

    if nargin < 5
        show_title = false;
    end


    % =========================
    % Axis limits
    % =========================

    xi_limits = ...
        expanded_limits(data.xi, 0.05);

    concurrence_limits = ...
        [-0.05, 1.05];

    fidelity_limits = ...
        [0.45, 1.05];

    purity_limits = ...
        [0.45, 1.05];

    chsh_limits = ...
        [1.95, 2 * sqrt(2) + 0.05];


    % =========================
    % Layout
    % =========================

    tl = ...
        tiledlayout( ...
            parent, ...
            2, 2, ...
            'TileSpacing', style.layout.tile_spacing, ...
            'Padding', style.layout.padding);


    % =========================
    % Panel 1: Concurrence
    % =========================

    ax = ...
        nexttile(tl);

    plot_metric_family( ...
        ax, ...
        data.xi, ...
        data.correlation_values, ...
        data.selected_indices, ...
        data.curve_colors, ...
        data.concurrence_num, ...
        data.concurrence_th, ...
        '$C$', ...
        'Concurrence', ...
        xi_limits, ...
        concurrence_limits, ...
        style, ...
        palette, ...
        true);


    % =========================
    % Panel 2: Fidelity
    % =========================

    ax = ...
        nexttile(tl);

    plot_metric_family( ...
        ax, ...
        data.xi, ...
        data.correlation_values, ...
        data.selected_indices, ...
        data.curve_colors, ...
        data.fidelity_num, ...
        data.fidelity_th, ...
        '$F_{\Psi^+}$', ...
        'Bell-state fidelity', ...
        xi_limits, ...
        fidelity_limits, ...
        style, ...
        palette, ...
        false);


    % =========================
    % Panel 3: Purity
    % =========================

    ax = ...
        nexttile(tl);

    plot_metric_family( ...
        ax, ...
        data.xi, ...
        data.correlation_values, ...
        data.selected_indices, ...
        data.curve_colors, ...
        data.purity_num, ...
        data.purity_th, ...
        '$\gamma(\rho_{AB})$', ...
        'Global polarization purity', ...
        xi_limits, ...
        purity_limits, ...
        style, ...
        palette, ...
        false);


    % =========================
    % Panel 4: CHSH
    % =========================

    ax = ...
        nexttile(tl);

    plot_metric_family( ...
        ax, ...
        data.xi, ...
        data.correlation_values, ...
        data.selected_indices, ...
        data.curve_colors, ...
        data.chsh_num, ...
        data.chsh_th, ...
        '$S_{\max}$', ...
        'Maximal CHSH parameter', ...
        xi_limits, ...
        chsh_limits, ...
        style, ...
        palette, ...
        false);

    yline( ...
        ax, ...
        2, ...
        ':', ...
        'LineWidth', style.lines.width_secondary, ...
        'Color', palette.gray_dark, ...
        'HandleVisibility', 'off');


    % =========================
    % Global title
    % =========================

    if show_title

        title( ...
            tl, ...
            'Experiment 2 — Two-Arm PMD and Spectral Correlations', ...
            'FontSize', style.title.font_size, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

    end

end


function plot_metric_family( ...
        ax, ...
        xi, ...
        correlation_values, ...
        selected_indices, ...
        curve_colors, ...
        numerical_map, ...
        analytical_map, ...
        y_label, ...
        panel_title, ...
        x_limits, ...
        y_limits, ...
        style, ...
        palette, ...
        do_legend)
% PLOT_METRIC_FAMILY  Plot one metric for representative r values.
%
% Analytical results are continuous lines and numerical results are markers.

    hold(ax, 'on');
    grid(ax, style.axes.grid);
    box(ax, style.axes.box);


    % =========================
    % Marker subsampling
    % =========================

    num_marker_positions = ...
        min(numel(xi), 13);

    marker_indices = ...
        unique( ...
            round( ...
                linspace( ...
                    1, ...
                    numel(xi), ...
                    num_marker_positions)));


    % =========================
    % Legend style indicators
    % =========================

    if do_legend

        plot( ...
            ax, ...
            nan, nan, ...
            '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.gray_dark, ...
            'DisplayName', 'analytical');

        plot( ...
            ax, ...
            nan, nan, ...
            'o', ...
            'LineStyle', 'none', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.gray_mid, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', 'numerical');

    end


    % =========================
    % Spectral-correlation cases
    % =========================

    for k = 1:numel(selected_indices)

        row_idx = ...
            selected_indices(k);

        current_color = ...
            curve_colors(k, :);

        r_value = ...
            correlation_values(row_idx);

        plot( ...
            ax, ...
            xi, ...
            analytical_map(row_idx, :), ...
            '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', current_color, ...
            'DisplayName', sprintf('$r=%+.2f$', r_value));

        plot( ...
            ax, ...
            xi, ...
            numerical_map(row_idx, :), ...
            'o', ...
            'LineStyle', 'none', ...
            'MarkerIndices', marker_indices, ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', current_color, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'HandleVisibility', 'off');

    end


    % =========================
    % Labels
    % =========================

    xlabel( ...
        ax, ...
        '$\xi=\sigma_\omega\tau$', ...
        'Interpreter', style.labels.interpreter, ...
        'FontSize', style.labels.font_size_axis);

    ylabel( ...
        ax, ...
        y_label, ...
        'Interpreter', style.labels.interpreter, ...
        'FontSize', style.labels.font_size_axis);

    title( ...
        ax, ...
        panel_title, ...
        'FontSize', style.title.font_size_small, ...
        'FontWeight', style.title.font_weight, ...
        'Interpreter', style.title.interpreter);

    xlim(ax, x_limits);
    ylim(ax, y_limits);

    set( ...
        ax, ...
        'FontSize', style.axes.font_size, ...
        'LineWidth', style.axes.line_width, ...
        'TickLabelInterpreter', style.axes.tick_label_interpreter, ...
        'Layer', style.axes.layer);


    % =========================
    % Legend
    % =========================

    if do_legend

        legend( ...
            ax, ...
            'Location', 'eastoutside', ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);

    end

end


function indices = ...
        select_representative_indices(num_values, max_curves)
% SELECT_REPRESENTATIVE_INDICES  Select evenly distributed curve indices.

    if num_values <= max_curves

        indices = ...
            1:num_values;

    else

        indices = ...
            unique( ...
                round( ...
                    linspace( ...
                        1, ...
                        num_values, ...
                        max_curves)));

    end

end


function colors = ...
        spectral_correlation_colors(correlation_values, palette)
% SPECTRAL_CORRELATION_COLORS  Map r values to blue-gray-red colors.
%
% Negative correlation -> blue
% Zero correlation     -> dark gray
% Positive correlation -> red

    num_values = ...
        numel(correlation_values);

    colors = ...
        zeros(num_values, 3);

    anchor_r = ...
        [-1, 0, 1];

    anchor_colors = ...
        [ ...
            palette.blue; ...
            palette.gray_dark; ...
            palette.red ...
        ];

    for k = 1:num_values

        colors(k, :) = ...
            interp1( ...
                anchor_r, ...
                anchor_colors, ...
                correlation_values(k), ...
                'linear');

    end

end


function limits = ...
        expanded_limits(values, relative_padding)
% EXPANDED_LIMITS  Construct non-degenerate axis limits.

    minimum_value = ...
        min(values);

    maximum_value = ...
        max(values);

    if minimum_value == maximum_value

        scale = ...
            max(1, abs(minimum_value));

        padding = ...
            relative_padding * scale;

    else

        padding = ...
            relative_padding * ...
            (maximum_value - minimum_value);

    end

    limits = ...
        [ ...
            minimum_value - padding, ...
            maximum_value + padding ...
        ];

end


function validate_metric_map(metric_map, expected_size, source_label)
% VALIDATE_METRIC_MAP  Validate one Experiment 2 scalar metric map.

    if ~isnumeric(metric_map)
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
             'InvalidMetricType'], ...
            '%s metric maps must be numeric.', ...
            source_label);
    end

    if ~isequal(size(metric_map), expected_size)
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
             'InvalidMetricSize'], ...
            ['%s metric maps must have size N_r x N_DGD = ', ...
             '%d x %d.'], ...
            source_label, ...
            expected_size(1), ...
            expected_size(2));
    end

    if any(~isfinite(metric_map), 'all')
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_summary:', ...
             'InvalidMetricValues'], ...
            '%s metric maps must contain only finite values.', ...
            source_label);
    end

end