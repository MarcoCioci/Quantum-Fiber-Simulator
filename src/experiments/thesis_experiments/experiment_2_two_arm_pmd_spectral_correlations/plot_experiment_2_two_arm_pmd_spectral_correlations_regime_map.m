function fig = ...
        plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map( ...
            results_experiment_2, do_save)
% PLOT_EXPERIMENT_2_TWO_ARM_PMD_SPECTRAL_CORRELATIONS_REGIME_MAP
% Plot the two-arm PMD spectral-correlation regime map.
%
% Objective:
%   Visualize how the two-photon spectral correlation coefficient r
%   modifies entanglement degradation under two-arm PMD.
%
%   The figure contains:
%
%       1) numerical concurrence C(ξ,r), with analytical contour lines
%
%       2) concurrence variation relative to the uncorrelated spectrum
%
%              ΔC(ξ,r) = C(ξ,r) - C(ξ,0)
%
%   where
%
%       ξ = σ_ω τ
%
%   is the normalized PMD strength.
%
%   The second panel isolates the contribution of spectral correlations:
%
%       ΔC > 0  -> spectral correlation protects entanglement
%       ΔC = 0  -> uncorrelated spectral baseline
%       ΔC < 0  -> spectral correlation enhances degradation
%
% Input:
%   results_experiment_2 - Structure returned by
%                          run_experiment_2_two_arm_pmd_spectral_correlations.
%
%   do_save              - Optional logical scalar controlling figure
%                          export. Default: false.
%
% Output:
%   fig - Handle of the Experiment 2 figure window.
%
% Notes:
%   The analytical prediction
%
%       C(ξ,r) = exp[-(1+r) ξ^2]
%
%   is superimposed as contour lines on the numerical concurrence map.
%
%   Numerical-versus-analytical errors are intentionally not plotted here
%   because they are reported quantitatively by the experiment runner.


    % =========================
    % Robustness checks
    % =========================

    if nargin < 1 || nargin > 2
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'InvalidNumInputs'], ...
            'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = false;
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    if ~isstruct(results_experiment_2)
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'InvalidInputType'], ...
            'results_experiment_2 must be a structure.');
    end

    required_top_fields = { ...
        'parameters', ...
        'numerical', ...
        'analytical' ...
    };

    for k = 1:numel(required_top_fields)

        if ~isfield(results_experiment_2, required_top_fields{k})
            error( ...
                ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
                 'MissingField'], ...
                'Missing required field "%s".', ...
                required_top_fields{k});
        end

    end

    required_parameter_fields = { ...
        'normalized_pmd_strength', ...
        'correlation_values' ...
    };

    for k = 1:numel(required_parameter_fields)

        if ~isfield( ...
                results_experiment_2.parameters, ...
                required_parameter_fields{k})
            error( ...
                ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
                 'MissingParameterField'], ...
                'Missing parameter field "%s".', ...
                required_parameter_fields{k});
        end

    end

    if ~isfield(results_experiment_2.numerical, 'concurrence')
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'MissingNumericalField'], ...
            'Numerical concurrence field is required.');
    end

    if ~isfield(results_experiment_2.analytical, 'concurrence')
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'MissingAnalyticalField'], ...
            'Analytical concurrence field is required.');
    end


    % =========================
    % Independent variables
    % =========================

    xi_raw = ...
        results_experiment_2.parameters.normalized_pmd_strength(:).';

    correlation_raw = ...
        results_experiment_2.parameters.correlation_values(:);

    if isempty(xi_raw) || ...
            ~isnumeric(xi_raw) || ...
            any(~isfinite(xi_raw), 'all')
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'InvalidPMDStrength'], ...
            ['normalized_pmd_strength must be a non-empty finite ', ...
             'numeric vector.']);
    end

    if isempty(correlation_raw) || ...
            ~isnumeric(correlation_raw) || ...
            any(~isfinite(correlation_raw), 'all')
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'InvalidCorrelationValues'], ...
            ['correlation_values must be a non-empty finite numeric ', ...
             'vector.']);
    end

    num_xi = ...
        numel(xi_raw);

    num_correlation = ...
        numel(correlation_raw);

    expected_size = ...
        [num_correlation, num_xi];


    % =========================
    % Validate maps
    % =========================

    concurrence_num_raw = ...
        results_experiment_2.numerical.concurrence;

    concurrence_th_raw = ...
        results_experiment_2.analytical.concurrence;

    validate_regime_map( ...
        concurrence_num_raw, ...
        expected_size, ...
        'numerical concurrence');

    validate_regime_map( ...
        concurrence_th_raw, ...
        expected_size, ...
        'analytical concurrence');


    % =========================
    % Sort coordinates
    % =========================

    [xi, xi_order] = ...
        sort(xi_raw);

    [correlation_values, correlation_order] = ...
        sort(correlation_raw);


    % =========================
    % Ordered concurrence maps
    % =========================

    data = struct();

    data.xi = ...
        xi;

    data.correlation_values = ...
        correlation_values;

    data.concurrence_num = ...
        concurrence_num_raw( ...
            correlation_order, ...
            xi_order);

    data.concurrence_th = ...
        concurrence_th_raw( ...
            correlation_order, ...
            xi_order);


    % =========================
    % Uncorrelated reference
    % =========================

    % Locate the simulated spectral-correlation value closest to r = 0.
    %
    % The default experiment configuration explicitly contains r = 0, but
    % this implementation remains robust to future changes in the grid.

    [minimum_abs_r, zero_correlation_index] = ...
        min(abs(correlation_values));

    if minimum_abs_r > 1e-12
        warning( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'MissingZeroCorrelation'], ...
            ['The correlation grid does not contain r = 0 exactly. ', ...
             'The closest available value r = %.3e is used as the ', ...
             'reference spectrum.'], ...
            correlation_values(zero_correlation_index));
    end

    concurrence_uncorrelated = ...
        data.concurrence_num( ...
            zero_correlation_index, :);


    % =========================
    % Spectral-correlation benefit
    % =========================

    % Subtract the uncorrelated PMD baseline from every row.
    %
    % MATLAB implicit expansion applies the 1 x N_xi reference curve to
    % every spectral-correlation value.

    data.concurrence_gain = ...
        data.concurrence_num ...
        - concurrence_uncorrelated;


    % =========================
    % Plot style
    % =========================

    palette = ...
        get_plot_palette();

    style = ...
        get_plot_style();


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = ...
        get_experiment_figure_tab( ...
            style.figure.experiment_2_id, ...
            'Regime map', ...
            'Experiment 2 — Two-Arm PMD and Spectral Correlations', ...
            style);

    build_experiment_2_regime_map( ...
        tab, ...
        data, ...
        style, ...
        palette, ...
        false);

    set( ...
        fig, ...
        'Visible', ...
        style.figure.visible_after_build);


    % =========================
    % Save
    % =========================

    if do_save

        output_folder = [ ...
            '/home/marcocioci/HPC/THESIS-Quantum-Communications/', ...
            'Quantum-Fiber-Simulator/images/experiment_2'];

        if ~exist(output_folder, 'dir')
            mkdir(output_folder);
        end

        output_path = ...
            fullfile( ...
                output_folder, ...
                ['experiment_2_two_arm_pmd_', ...
                 'spectral_correlations_regime_map.png']);

        export_plot( ...
            output_path, ...
            @(parent) build_experiment_2_regime_map( ...
                parent, ...
                data, ...
                style, ...
                palette, ...
                false), ...
            style);

    end

end


function tl = ...
        build_experiment_2_regime_map( ...
            parent, data, style, palette, show_title)
% BUILD_EXPERIMENT_2_REGIME_MAP  Build the Experiment 2 regime-map figure.
%
% Input:
%   parent     - Parent figure or tab container.
%   data       - Ordered Experiment 2 map data.
%   style      - Centralized plot-style structure.
%   palette    - Centralized plot palette.
%   show_title - Logical flag controlling the global figure title.
%
% Output:
%   tl - Tiled-layout handle.

    if nargin < 5
        show_title = false;
    end


    % =========================
    % Layout
    % =========================

    tl = ...
        tiledlayout( ...
            parent, ...
            1, 2, ...
            'TileSpacing', style.layout.tile_spacing, ...
            'Padding', style.layout.padding);


    % =========================
    % Analytical contour levels
    % =========================

    concurrence_contours = ...
        [0.10, 0.25, 0.50, 0.75, 0.90];


    % =========================
    % Panel 1: Concurrence
    % =========================

    ax = ...
        nexttile(tl);

    plot_regime_heatmap( ...
        ax, ...
        data.xi, ...
        data.correlation_values, ...
        data.concurrence_num, ...
        [0, 1], ...
        '$C$', ...
        'Entanglement survival', ...
        style);

    if numel(data.xi) >= 2 && ...
            numel(data.correlation_values) >= 2

        hold(ax, 'on');

        contour( ...
            ax, ...
            data.xi, ...
            data.correlation_values, ...
            data.concurrence_th, ...
            concurrence_contours, ...
            'LineWidth', style.lines.width_secondary, ...
            'Color', palette.black, ...
            'HandleVisibility', 'off');

    end


    % =========================
    % Panel 2: Correlation gain
    % =========================

    ax = ...
        nexttile(tl);

    maximum_gain = ...
        max(abs(data.concurrence_gain), [], 'all');

    if maximum_gain <= eps
        maximum_gain = ...
            1;
    end

    plot_regime_heatmap( ...
        ax, ...
        data.xi, ...
        data.correlation_values, ...
        data.concurrence_gain, ...
        [-maximum_gain, maximum_gain], ...
        '$\Delta C = C(\xi,r)-C(\xi,0)$', ...
        'Spectral-correlation effect', ...
        style);

    hold(ax, 'on');

    yline( ...
        ax, ...
        0, ...
        '--', ...
        'Color', palette.black, ...
        'LineWidth', style.lines.width_secondary, ...
        'HandleVisibility', 'off');


    % =========================
    % Global title
    % =========================

    if show_title

        title( ...
            tl, ...
            'Experiment 2 — Two-Arm PMD Spectral-Correlation Regimes', ...
            'FontSize', style.title.font_size, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

    end

end


function plot_regime_heatmap( ...
        ax, ...
        xi, ...
        correlation_values, ...
        map_values, ...
        color_limits, ...
        colorbar_label, ...
        panel_title, ...
        style)
% PLOT_REGIME_HEATMAP  Plot one Experiment 2 two-dimensional parameter map.

    imagesc( ...
        ax, ...
        xi, ...
        correlation_values, ...
        map_values);

    set( ...
        ax, ...
        'YDir', ...
        'normal');

    colormap( ...
        ax, ...
        style.heatmap.colormap);

    clim( ...
        ax, ...
        color_limits);

    cb = ...
        colorbar(ax);

    cb.TickLabelInterpreter = ...
        style.axes.tick_label_interpreter;

    cb.FontSize = ...
        style.axes.font_size;

    cb.Label.String = ...
        colorbar_label;

    cb.Label.Interpreter = ...
        style.labels.interpreter;

    cb.Label.FontSize = ...
        style.labels.font_size_axis;


    % =========================
    % Axis labels
    % =========================

    xlabel( ...
        ax, ...
        '$\xi=\sigma_\omega\tau$', ...
        'Interpreter', style.labels.interpreter, ...
        'FontSize', style.labels.font_size_axis);

    ylabel( ...
        ax, ...
        '$r$', ...
        'Interpreter', style.labels.interpreter, ...
        'FontSize', style.labels.font_size_axis);

    title( ...
        ax, ...
        panel_title, ...
        'FontSize', style.title.font_size_small, ...
        'FontWeight', style.title.font_weight, ...
        'Interpreter', style.title.interpreter);

    set( ...
        ax, ...
        'FontSize', style.axes.font_size, ...
        'LineWidth', style.axes.line_width, ...
        'TickLabelInterpreter', style.axes.tick_label_interpreter, ...
        'Layer', style.axes.layer, ...
        'Box', style.axes.box);

end


function validate_regime_map( ...
        map_values, expected_size, map_label)
% VALIDATE_REGIME_MAP  Validate one Experiment 2 two-dimensional map.

    if ~isnumeric(map_values)
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'InvalidMapType'], ...
            '%s must be numeric.', ...
            map_label);
    end

    if ~isequal(size(map_values), expected_size)
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'InvalidMapSize'], ...
            ['%s must have size N_r x N_DGD = %d x %d.'], ...
            map_label, ...
            expected_size(1), ...
            expected_size(2));
    end

    if any(~isfinite(map_values), 'all')
        error( ...
            ['plot_experiment_2_two_arm_pmd_spectral_correlations_regime_map:', ...
             'InvalidMapValues'], ...
            '%s must contain only finite values.', ...
            map_label);
    end

end