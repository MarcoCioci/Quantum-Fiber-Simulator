function fig = plot_experiment_3_statistical_segmented_fiber_summary( ...
        results_experiment_3, do_save)
% PLOT_EXPERIMENT_3_STATISTICAL_SEGMENTED_FIBER_SUMMARY
% Plot the principal statistical and quantum results of Experiment 3.
%
% Objective:
%   Visualize:
%
%       1. RMS total DGD versus the isotropic random-walk prediction;
%       2. concurrence versus effective normalized PMD strength;
%       3. fixed-fiber concurrence statistics versus ensemble concurrence;
%       4. fixed-fiber CHSH statistics versus ensemble CHSH maximum.
%
% Input:
%   results_experiment_3 - Output structure returned by
%                          run_experiment_3_statistical_segmented_fiber.
%
%   do_save              - Logical scalar controlling figure export.
%
% Output:
%   fig - Experiment 3 figure handle.

    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 2
        error( ...
            ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
             'InvalidNumInputs'], ...
            ['Expected exactly 2 input arguments: ', ...
             'results_experiment_3 and do_save.']);
    end

    if ~isstruct(results_experiment_3)
        error( ...
            ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
             'InvalidResults'], ...
            'results_experiment_3 must be a structure.');
    end

    if ~(islogical(do_save) && isscalar(do_save))
        error( ...
            ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    check_required_fields( ...
        results_experiment_3, ...
        {'parameters', 'realizations', 'ensemble', ...
         'statistics', 'analytical'}, ...
        ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
         'MissingMainField']);

    check_required_fields( ...
        results_experiment_3.parameters, ...
        {'num_segments_values'}, ...
        ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
         'MissingParameterField']);

    check_required_fields( ...
        results_experiment_3.realizations, ...
        {'normalized_pmd_strength', 'concurrence', 'chsh_max'}, ...
        ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
         'MissingRealizationField']);

    check_required_fields( ...
        results_experiment_3.ensemble, ...
        {'concurrence', 'chsh_max'}, ...
        ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
         'MissingEnsembleField']);

    check_required_fields( ...
        results_experiment_3.statistics, ...
        {'rms_total_dgd', 'concurrence', 'chsh_max'}, ...
        ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
         'MissingStatisticsField']);

    check_required_fields( ...
        results_experiment_3.analytical, ...
        {'rms_total_dgd'}, ...
        ['plot_experiment_3_statistical_segmented_fiber_summary:', ...
         'MissingAnalyticalField']);


    % =========================
    % Extract data
    % =========================

    num_segments_values = ...
        results_experiment_3.parameters.num_segments_values(:).';

    rms_dgd_numerical = ...
        results_experiment_3.statistics.rms_total_dgd(:).';

    rms_dgd_analytical = ...
        results_experiment_3.analytical.rms_total_dgd(:).';

    xi_realizations = ...
        results_experiment_3.realizations.normalized_pmd_strength;

    concurrence_realizations = ...
        results_experiment_3.realizations.concurrence;

    concurrence_mean = ...
        results_experiment_3.statistics.concurrence.mean(:).';

    concurrence_q10 = ...
        results_experiment_3.statistics.concurrence.q10(:).';

    concurrence_q90 = ...
        results_experiment_3.statistics.concurrence.q90(:).';

    concurrence_ensemble = ...
        results_experiment_3.ensemble.concurrence(:).';

    chsh_mean = ...
        results_experiment_3.statistics.chsh_max.mean(:).';

    chsh_q10 = ...
        results_experiment_3.statistics.chsh_max.q10(:).';

    chsh_q90 = ...
        results_experiment_3.statistics.chsh_max.q90(:).';

    chsh_ensemble = ...
        results_experiment_3.ensemble.chsh_max(:).';


    % =========================
    % Plot style
    % =========================

    style = get_plot_style();

    palette = get_plot_palette();


    % =========================
    % Derived quantities
    % =========================

    x_limits_segments = ...
        [min(num_segments_values), max(num_segments_values)];

    if x_limits_segments(1) == x_limits_segments(2)
        x_limits_segments = ...
            x_limits_segments + [-0.5, 0.5];
    end

    xi_all = xi_realizations(:);

    concurrence_all = concurrence_realizations(:);

    xi_max = max(xi_all);

    xi_benchmark = ...
        linspace(0, max(0.1, 1.05 * xi_max), 400);

    concurrence_benchmark = ...
        exp(-0.5 * xi_benchmark .^ 2);

    dgd_scale_ps = 1e12;


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = ...
        get_experiment_figure_tab( ...
            style.figure.experiment_3_id, ...
            'Summary', ...
            'Experiment 3 - Statistical Segmented Fiber', ...
            style);

    build_plot(tab, false);

    set( ...
        fig, ...
        'Visible', ...
        style.figure.visible_after_build);


    % =========================
    % Save
    % =========================

    if do_save

        output_folder = [ ...
            '/home/marcocioci/HPC/THESIS-Quantum-Communications/', ...
            'Quantum-Fiber-Simulator/images/experiment_3'];

        if ~exist(output_folder, 'dir')
            mkdir(output_folder);
        end

        output_path = ...
            fullfile( ...
                output_folder, ...
                'experiment_3_statistical_segmented_fiber_summary.png');

        export_plot( ...
            output_path, ...
            @(parent) build_plot(parent, false), ...
            style);

    end


    % =========================
    % Local plot builder
    % =========================

    function layout = build_plot(parent_container, show_title)

        if nargin < 2
            show_title = false;
        end

        layout = tiledlayout( ...
            parent_container, ...
            2, ...
            2, ...
            'TileSpacing', 'compact', ...
            'Padding', 'compact');


        % =====================================================
        % Panel 1: RMS DGD random-walk scaling
        % =====================================================

        ax = nexttile(layout);

        hold(ax, 'on');
        grid(ax, style.axes.grid);
        box(ax, style.axes.box);

        plot( ...
            ax, ...
            num_segments_values, ...
            dgd_scale_ps * rms_dgd_analytical, ...
            '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.analytical, ...
            'DisplayName', ...
            '$\Delta\tau_{\mathrm{seg}}\sqrt{N}$');

        plot( ...
            ax, ...
            num_segments_values, ...
            dgd_scale_ps * rms_dgd_numerical, ...
            'o', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.numerical, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', ...
            'Monte Carlo RMS');

        xlabel( ...
            ax, ...
            '$N$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel( ...
            ax, ...
            'RMS DGD [ps]', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title( ...
            ax, ...
            'Statistical PMD accumulation', ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

        xlim(ax, x_limits_segments);

        apply_axes_style(ax, style);

        legend( ...
            ax, ...
            'Location', 'best', ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);


        % =====================================================
        % Panel 2: concurrence vs effective DGD
        % =====================================================

        ax = nexttile(layout);

        hold(ax, 'on');
        grid(ax, style.axes.grid);
        box(ax, style.axes.box);

        plot( ...
            ax, ...
            xi_all, ...
            concurrence_all, ...
            '.', ...
            'Color', palette.samples, ...
            'MarkerSize', 7, ...
            'DisplayName', ...
            'Segmented-fiber realizations');

        plot( ...
            ax, ...
            xi_benchmark, ...
            concurrence_benchmark, ...
            '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.analytical, ...
            'DisplayName', ...
            '$e^{-\xi^2/2}$ single-segment benchmark');

        xlabel( ...
            ax, ...
            '$\xi_{\mathrm{eff}}=\sigma_\omega\tau_{\mathrm{DGD}}$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel( ...
            ax, ...
            '$C$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title( ...
            ax, ...
            'Entanglement versus effective PMD', ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

        xlim( ...
            ax, ...
            [0, max(0.1, 1.05 * xi_max)]);

        ylim(ax, [-0.05, 1.05]);

        apply_axes_style(ax, style);

        legend( ...
            ax, ...
            'Location', 'best', ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);


        % =====================================================
        % Panel 3: concurrence statistics
        % =====================================================

        ax = nexttile(layout);

        hold(ax, 'on');
        grid(ax, style.axes.grid);
        box(ax, style.axes.box);

        fill( ...
            ax, ...
            [num_segments_values, fliplr(num_segments_values)], ...
            [concurrence_q10, fliplr(concurrence_q90)], ...
            palette.gray_light, ...
            'EdgeColor', 'none', ...
            'DisplayName', '10-90\% fixed-fiber interval');

        plot( ...
            ax, ...
            num_segments_values, ...
            concurrence_mean, ...
            '-o', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.metric_C, ...
            'MarkerFaceColor', palette.metric_C, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'DisplayName', ...
            'Mean fixed-fiber concurrence');

        plot( ...
            ax, ...
            num_segments_values, ...
            concurrence_ensemble, ...
            '--s', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.metric_F, ...
            'MarkerFaceColor', palette.metric_F, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'DisplayName', ...
            '$C(\overline{\rho})$');

        xlabel( ...
            ax, ...
            '$N$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel( ...
            ax, ...
            '$C$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title( ...
            ax, ...
            'Fixed fibers versus realization averaging', ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

        xlim(ax, x_limits_segments);
        ylim(ax, [-0.05, 1.05]);

        apply_axes_style(ax, style);

        legend( ...
            ax, ...
            'Location', 'best', ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);


        % =====================================================
        % Panel 4: CHSH statistics
        % =====================================================

        ax = nexttile(layout);

        hold(ax, 'on');
        grid(ax, style.axes.grid);
        box(ax, style.axes.box);

        fill( ...
            ax, ...
            [num_segments_values, fliplr(num_segments_values)], ...
            [chsh_q10, fliplr(chsh_q90)], ...
            palette.gray_light, ...
            'EdgeColor', 'none', ...
            'DisplayName', '10-90\% fixed-fiber interval');

        plot( ...
            ax, ...
            num_segments_values, ...
            chsh_mean, ...
            '-o', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.cyan, ...
            'MarkerFaceColor', palette.cyan, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'DisplayName', ...
            'Mean fixed-fiber $S_{\max}$');

        plot( ...
            ax, ...
            num_segments_values, ...
            chsh_ensemble, ...
            '--s', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.purple, ...
            'MarkerFaceColor', palette.purple, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'DisplayName', ...
            '$S_{\max}(\overline{\rho})$');

        yline( ...
            ax, ...
            2, ...
            '--', ...
            'Color', palette.gray_dark, ...
            'LineWidth', 1.2, ...
            'DisplayName', ...
            'Classical CHSH bound');

        xlabel( ...
            ax, ...
            '$N$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel( ...
            ax, ...
            '$S_{\max}$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title( ...
            ax, ...
            'Bell-nonlocality statistics', ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

        xlim(ax, x_limits_segments);
        ylim(ax, [0, 2 * sqrt(2) + 0.15]);

        apply_axes_style(ax, style);

        legend( ...
            ax, ...
            'Location', 'best', ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);


        % =========================
        % Global title
        % =========================

        if show_title

            title( ...
                layout, ...
                'Experiment 3 - Statistical Segmented Fiber', ...
                'FontSize', style.title.font_size, ...
                'FontWeight', style.title.font_weight, ...
                'Interpreter', style.title.interpreter);

        end

    end

end


function apply_axes_style(ax, style)
% APPLY_AXES_STYLE  Apply the common thesis formatting to one axes object.

    set( ...
        ax, ...
        'FontSize', style.axes.font_size, ...
        'LineWidth', style.axes.line_width, ...
        'TickLabelInterpreter', style.axes.tick_label_interpreter, ...
        'Layer', style.axes.layer);

end