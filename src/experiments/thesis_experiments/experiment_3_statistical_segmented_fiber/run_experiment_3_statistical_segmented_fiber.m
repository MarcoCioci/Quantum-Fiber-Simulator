function results_experiment_3 = ...
        run_experiment_3_statistical_segmented_fiber(do_plot, do_save)
% RUN_EXPERIMENT_3_STATISTICAL_SEGMENTED_FIBER
% Study statistical PMD accumulation in a segmented birefringent fiber.
%
% Objective:
%   Investigate how independently and isotropically oriented birefringent
%   segments accumulate into a statistical PMD response and how the
%   resulting frequency-dependent polarization transformation affects a
%   polarization-entangled Bell state.
%
%   The input state is
%
%       |Ψ⁺⟩ = (|01⟩ + |10⟩) / sqrt(2).
%
%   Arm A contains N birefringent segments. Every segment has
%
%       carrier differential phase = 0,
%       DGD = segment_dgd,
%       isotropically sampled birefringence axis.
%
%   Arm B is ideal.
%
%   For every fixed fiber realization:
%
%       1. random segment axes are generated;
%       2. the complete PMD vector and DGD are extracted;
%       3. the frequency-resolved Bell state is propagated;
%       4. frequency is traced out;
%       5. state metrics and correlation observables are evaluated.
%
%   The experiment then evaluates statistics over the population of fixed
%   fiber realizations.
%
%   An additional density-operator average
%
%       ρ_ensemble = (1 / R) sum_r ρ_r
%
%   is also calculated. This represents a physically different situation
%   in which different fiber realizations are unresolved during the
%   observation interval.
%
% Input:
%   do_plot - Logical scalar controlling summary plotting.
%
%   do_save - Logical scalar controlling figure export.
%
% Output:
%   results_experiment_3 - Structure containing experiment parameters,
%                          individual fiber realizations, fixed-fiber
%                          quantum-state results, ensemble-averaged states,
%                          statistical summaries, analytical controls, and
%                          validation errors.
%
% Notes:
%   All physical and numerical parameters defining Experiment 3 are stored
%   internally in the experiment configuration section. The external
%   caller therefore controls only plotting and figure export.
%
%   The source spectrum is chosen as an uncorrelated symmetric Gaussian:
%
%       sigma_sum = sigma_difference = sqrt(2) * sigma_omega.
%
%   Setting every carrier differential phase to zero makes U_j(0) = I.
%   Consequently, the first-order PMD vector at the carrier reduces to the
%   vectorial accumulation of the local segment contributions, while the
%   complete finite-bandwidth propagation still retains noncommuting
%   higher-order effects.
%
%   The validated PMD propagation pipeline is reused:
%
%       pmd_frequency_resolved_states
%               ->
%       pmd_spectral_average_state.
%
%   No experiment-specific replacement of the PMD propagation model is
%   introduced.


    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 2
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidNumInputs'], ...
            'Expected exactly 2 input arguments: do_plot and do_save.');
    end

    if ~(islogical(do_plot) && isscalar(do_plot))
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidDoPlot'], ...
            'do_plot must be a logical scalar.');
    end

    if ~(islogical(do_save) && isscalar(do_save))
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    if do_save && ~do_plot
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'SaveWithoutPlot'], ...
            ['do_save cannot be true when do_plot is false because ', ...
             'figure export is handled by the plotting pipeline.']);
    end


    % =========================
    % Experiment configuration
    % =========================

    % Number of birefringent segments used in the statistical sweep.
    %
    % N = 1 provides the analytically controlled single-segment limit,
    % while increasing N probes the transition toward a distributed
    % randomly birefringent fiber.
    num_segments_values = ...
        [1, 2, 4, 8, 16, 32];

    % Number of independent statistical fiber realizations generated for
    % every value of N.
    num_realizations = 100;

    % Differential group delay associated with each individual segment.
    segment_dgd = 2.0e-12;              % [s]

    % Marginal spectral standard deviation of each photon.
    sigma_omega = 2 * pi * 25e9;        % [rad/s]

    % Number of discretization nodes used for each frequency arm.
    %
    % An odd number ensures that Omega = 0 belongs exactly to the grid.
    num_frequency_points = 41;

    % Spectral domain:
    %
    %     Omega in [-K sigma_omega, +K sigma_omega].
    max_offset_factor = 6.0;

    % Centered finite-difference step used to extract the complete
    % first-order PMD vector from the segmented fiber operator.
    derivative_step = 1.0e8;            % [rad/s]

    % Fixed seed for reproducibility of all random fiber realizations.
    random_seed = 12345;


    % =========================
    % Configuration checks
    % =========================

    if ~isnumeric(num_segments_values) || ...
            ~isreal(num_segments_values) || ...
            ~isvector(num_segments_values) || ...
            isempty(num_segments_values)
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidSegmentCounts'], ...
            'num_segments_values must be a non-empty real numeric vector.');
    end

    if any(~isfinite(num_segments_values), 'all') || ...
            any(num_segments_values < 1, 'all') || ...
            any(num_segments_values ~= floor(num_segments_values), 'all')
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidSegmentCounts'], ...
            'num_segments_values must contain positive finite integers.');
    end

    if numel(unique(num_segments_values)) ~= numel(num_segments_values)
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'DuplicateSegmentCounts'], ...
            'num_segments_values must not contain duplicate values.');
    end

    if ~any(num_segments_values == 1)
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'MissingSingleSegmentCase'], ...
            ['num_segments_values must include N = 1 for the ', ...
             'single-segment analytical validation.']);
    end

    if ~isnumeric(num_realizations) || ...
            ~isscalar(num_realizations) || ...
            ~isreal(num_realizations) || ...
            ~isfinite(num_realizations) || ...
            num_realizations < 2 || ...
            num_realizations ~= floor(num_realizations)
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidNumRealizations'], ...
            'num_realizations must be an integer greater than or equal to 2.');
    end

    if ~isnumeric(segment_dgd) || ...
            ~isscalar(segment_dgd) || ...
            ~isreal(segment_dgd) || ...
            ~isfinite(segment_dgd) || ...
            segment_dgd <= 0
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidSegmentDGD'], ...
            'segment_dgd must be a positive finite real scalar.');
    end

    if ~isnumeric(sigma_omega) || ...
            ~isscalar(sigma_omega) || ...
            ~isreal(sigma_omega) || ...
            ~isfinite(sigma_omega) || ...
            sigma_omega <= 0
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidSigmaOmega'], ...
            'sigma_omega must be a positive finite real scalar.');
    end

    if ~isnumeric(num_frequency_points) || ...
            ~isscalar(num_frequency_points) || ...
            ~isreal(num_frequency_points) || ...
            ~isfinite(num_frequency_points) || ...
            num_frequency_points < 3 || ...
            num_frequency_points ~= floor(num_frequency_points)
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidNumFrequencyPoints'], ...
            ['num_frequency_points must be an integer greater than or ', ...
             'equal to 3.']);
    end

    if mod(num_frequency_points, 2) == 0
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'EvenNumFrequencyPoints'], ...
            ['num_frequency_points must be odd so that Omega = 0 ', ...
             'is sampled exactly.']);
    end

    if ~isnumeric(max_offset_factor) || ...
            ~isscalar(max_offset_factor) || ...
            ~isreal(max_offset_factor) || ...
            ~isfinite(max_offset_factor) || ...
            max_offset_factor <= 0
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidMaxOffsetFactor'], ...
            'max_offset_factor must be a positive finite real scalar.');
    end

    if ~isnumeric(derivative_step) || ...
            ~isscalar(derivative_step) || ...
            ~isreal(derivative_step) || ...
            ~isfinite(derivative_step) || ...
            derivative_step <= 0
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidDerivativeStep'], ...
            'derivative_step must be a positive finite real scalar.');
    end

    if ~isnumeric(random_seed) || ...
            ~isscalar(random_seed) || ...
            ~isreal(random_seed) || ...
            ~isfinite(random_seed) || ...
            random_seed < 0 || ...
            random_seed ~= floor(random_seed) || ...
            random_seed > 2^32 - 1
        error( ...
            ['run_experiment_3_statistical_segmented_fiber:', ...
             'InvalidRandomSeed'], ...
            ['random_seed must be an integer in the interval ', ...
             '[0, 2^32 - 1].']);
    end


    % =========================
    % Derived configuration
    % =========================

    num_segments_values = ...
        num_segments_values(:).';

    num_segment_cases = ...
        numel(num_segments_values);

    sigma_sum = ...
        sqrt(2) * sigma_omega;

    sigma_difference = ...
        sqrt(2) * sigma_omega;

    max_frequency_offset = ...
        max_offset_factor * sigma_omega;


    % =========================
    % Reproducible RNG state
    % =========================

    previous_rng_state = rng;

    rng_cleanup = onCleanup( ...
        @() rng(previous_rng_state));

    rng(random_seed, 'twister');


    % =========================
    % Input polarization state
    % =========================

    psi_input = ...
        bell_state('psi_plus');

    rho_input = ...
        state_to_density_matrix(psi_input);


    % =========================
    % Spectrum
    % =========================

    [omega_offsets, delta_omega] = ...
        pmd_frequency_grid( ...
            num_frequency_points, ...
            max_frequency_offset);

    spectral_weights = ...
        pmd_joint_spectral_weights( ...
            omega_offsets, ...
            omega_offsets, ...
            sigma_sum, ...
            sigma_difference);


    % =========================
    % Ideal arm B
    % =========================

    phases_B = 0;

    dgds_B = 0;

    axes_B = ...
        [0, 0, 1];


    % =========================
    % Analytical controls
    % =========================

    analytics = ...
        analytical_values_experiment_3_statistical_segmented_fiber( ...
            num_segments_values, ...
            segment_dgd, ...
            sigma_omega);


    % =========================
    % Preallocation
    % =========================

    axes_realizations = ...
        cell(num_segment_cases, num_realizations);

    pmd_vector = zeros( ...
        num_segment_cases, ...
        num_realizations, ...
        3);

    total_dgd = zeros( ...
        num_segment_cases, ...
        num_realizations);

    normalized_pmd_strength = zeros( ...
        num_segment_cases, ...
        num_realizations);

    rho_output = complex(zeros( ...
        4, ...
        4, ...
        num_segment_cases, ...
        num_realizations));

    correlation_tensor = zeros( ...
        3, ...
        3, ...
        num_segment_cases, ...
        num_realizations);

    correlation_xx = zeros( ...
        num_segment_cases, ...
        num_realizations);

    correlation_yy = zeros( ...
        num_segment_cases, ...
        num_realizations);

    correlation_zz = zeros( ...
        num_segment_cases, ...
        num_realizations);

    purity = zeros( ...
        num_segment_cases, ...
        num_realizations);

    purity_A = zeros( ...
        num_segment_cases, ...
        num_realizations);

    purity_B = zeros( ...
        num_segment_cases, ...
        num_realizations);

    fidelity = zeros( ...
        num_segment_cases, ...
        num_realizations);

    concurrence = zeros( ...
        num_segment_cases, ...
        num_realizations);

    tangle = zeros( ...
        num_segment_cases, ...
        num_realizations);

    entanglement_of_formation = zeros( ...
        num_segment_cases, ...
        num_realizations);

    chsh_max = zeros( ...
        num_segment_cases, ...
        num_realizations);

    trace_error = zeros( ...
        num_segment_cases, ...
        num_realizations);

    hermiticity_error = zeros( ...
        num_segment_cases, ...
        num_realizations);

    minimum_eigenvalue = zeros( ...
        num_segment_cases, ...
        num_realizations);


    % =========================
    % Ensemble-state allocation
    % =========================

    rho_ensemble = complex(zeros( ...
        4, ...
        4, ...
        num_segment_cases));

    ensemble_purity = ...
        zeros(num_segment_cases, 1);

    ensemble_purity_A = ...
        zeros(num_segment_cases, 1);

    ensemble_purity_B = ...
        zeros(num_segment_cases, 1);

    ensemble_fidelity = ...
        zeros(num_segment_cases, 1);

    ensemble_concurrence = ...
        zeros(num_segment_cases, 1);

    ensemble_tangle = ...
        zeros(num_segment_cases, 1);

    ensemble_entanglement_of_formation = ...
        zeros(num_segment_cases, 1);

    ensemble_chsh_max = ...
        zeros(num_segment_cases, 1);

    ensemble_correlation_tensor = zeros( ...
        3, ...
        3, ...
        num_segment_cases);

    ensemble_correlation_xx = ...
        zeros(num_segment_cases, 1);

    ensemble_correlation_yy = ...
        zeros(num_segment_cases, 1);

    ensemble_correlation_zz = ...
        zeros(num_segment_cases, 1);


    % =========================
    % Console header
    % =========================

    fprintf('\n');
    fprintf('============================================\n');
    fprintf(' Experiment 3 - Statistical Segmented Fiber\n');
    fprintf('============================================\n');

    fprintf( ...
        'Segment-count cases:       %d\n', ...
        num_segment_cases);

    fprintf( ...
        'Realizations / case:       %d\n', ...
        num_realizations);

    fprintf( ...
        'Frequency nodes / arm:     %d\n', ...
        num_frequency_points);

    fprintf( ...
        'Marginal sigma_omega:      %.3e rad/s\n', ...
        sigma_omega);

    fprintf( ...
        'Segment DGD:               %.3e s\n', ...
        segment_dgd);

    fprintf( ...
        'Spectral window:           +/- %.1f sigma_omega\n', ...
        max_offset_factor);

    fprintf( ...
        'Derivative step:           %.3e rad/s\n', ...
        derivative_step);

    fprintf( ...
        'Random seed:               %d\n', ...
        random_seed);


    % =========================
    % Main statistical sweep
    % =========================

    for i_case = 1:num_segment_cases

        num_segments = ...
            num_segments_values(i_case);

        phases_A = ...
            zeros(num_segments, 1);

        dgds_A = ...
            segment_dgd * ones(num_segments, 1);

        rho_accumulator = ...
            complex(zeros(4, 4));

        fprintf( ...
            '\nSegment case %d/%d: N = %d\n', ...
            i_case, ...
            num_segment_cases, ...
            num_segments);


        % =========================
        % Fiber realizations
        % =========================

        for i_realization = 1:num_realizations

            % =========================
            % Random segment axes
            % =========================

            axes_A = ...
                sample_isotropic_axes(num_segments);

            axes_realizations{i_case, i_realization} = ...
                axes_A;


            % =========================
            % Complete-fiber PMD vector
            % =========================

            [pmd_vector_current, total_dgd_current] = ...
                pmd_fiber_pmd_vector( ...
                    0, ...
                    derivative_step, ...
                    phases_A, ...
                    dgds_A, ...
                    axes_A);

            pmd_vector(i_case, i_realization, :) = ...
                reshape( ...
                    pmd_vector_current, ...
                    1, ...
                    1, ...
                    3);

            total_dgd(i_case, i_realization) = ...
                total_dgd_current;

            normalized_pmd_strength(i_case, i_realization) = ...
                sigma_omega * total_dgd_current;


            % =========================
            % Frequency-resolved propagation
            % =========================

            frequency_states = ...
                pmd_frequency_resolved_states( ...
                    rho_input, ...
                    omega_offsets, ...
                    omega_offsets, ...
                    phases_A, ...
                    dgds_A, ...
                    axes_A, ...
                    phases_B, ...
                    dgds_B, ...
                    axes_B);


            % =========================
            % Spectral trace
            % =========================

            rho_raw = ...
                pmd_spectral_average_state( ...
                    frequency_states, ...
                    spectral_weights);


            % =========================
            % Physical-state diagnostics
            % =========================

            trace_error(i_case, i_realization) = ...
                abs(trace(rho_raw) - 1);

            hermiticity_error(i_case, i_realization) = ...
                norm( ...
                    rho_raw - rho_raw', ...
                    'fro');

            rho_current = ...
                (rho_raw + rho_raw') / 2;

            eigenvalues_current = ...
                eig(rho_current);

            minimum_eigenvalue(i_case, i_realization) = ...
                min(real(eigenvalues_current));

            if trace_error(i_case, i_realization) > 1e-8
                error( ...
                    ['run_experiment_3_statistical_segmented_fiber:', ...
                     'TraceFailure'], ...
                    ['Reduced state trace error exceeded tolerance for ', ...
                     'N = %d, realization = %d.'], ...
                    num_segments, ...
                    i_realization);
            end

            if hermiticity_error(i_case, i_realization) > 1e-8
                error( ...
                    ['run_experiment_3_statistical_segmented_fiber:', ...
                     'HermiticityFailure'], ...
                    ['Reduced state Hermiticity error exceeded tolerance ', ...
                     'for N = %d, realization = %d.'], ...
                    num_segments, ...
                    i_realization);
            end

            if minimum_eigenvalue(i_case, i_realization) < -1e-8
                error( ...
                    ['run_experiment_3_statistical_segmented_fiber:', ...
                     'PositivityFailure'], ...
                    ['Reduced state is not positive semidefinite within ', ...
                     'tolerance for N = %d, realization = %d.'], ...
                    num_segments, ...
                    i_realization);
            end


            % =========================
            % Reduced states
            % =========================

            rho_A_current = ...
                partial_trace_B(rho_current);

            rho_B_current = ...
                partial_trace_A(rho_current);


            % =========================
            % Correlation tensor
            % =========================

            T_current = ...
                compute_correlation_tensor(rho_current);

            correlations_current = ...
                compute_diagonal_correlations(rho_current);

            correlation_tensor(:, :, i_case, i_realization) = ...
                real(T_current);

            correlation_xx(i_case, i_realization) = ...
                real(correlations_current.c_xx);

            correlation_yy(i_case, i_realization) = ...
                real(correlations_current.c_yy);

            correlation_zz(i_case, i_realization) = ...
                real(correlations_current.c_zz);


            % =========================
            % State metrics
            % =========================

            purity(i_case, i_realization) = ...
                real(compute_purity(rho_current));

            purity_A(i_case, i_realization) = ...
                real(compute_purity(rho_A_current));

            purity_B(i_case, i_realization) = ...
                real(compute_purity(rho_B_current));

            fidelity(i_case, i_realization) = ...
                real(compute_fidelity( ...
                    rho_current, ...
                    psi_input));

            concurrence(i_case, i_realization) = ...
                real(compute_concurrence(rho_current));

            tangle(i_case, i_realization) = ...
                real(compute_tangle(rho_current));

            entanglement_of_formation(i_case, i_realization) = ...
                real(compute_entanglement_of_formation( ...
                    rho_current));

            chsh_max(i_case, i_realization) = ...
                real(compute_chsh_max_from_tensor( ...
                    T_current));


            % =========================
            % Store realization state
            % =========================

            rho_output(:, :, i_case, i_realization) = ...
                rho_current;

            rho_accumulator = ...
                rho_accumulator + rho_current;

        end


        % =========================
        % Realization-averaged state
        % =========================

        rho_ensemble_current = ...
            rho_accumulator / num_realizations;

        rho_ensemble_current = ...
            (rho_ensemble_current + rho_ensemble_current') / 2;

        rho_ensemble(:, :, i_case) = ...
            rho_ensemble_current;


        % =========================
        % Ensemble reduced states
        % =========================

        rho_A_ensemble = ...
            partial_trace_B(rho_ensemble_current);

        rho_B_ensemble = ...
            partial_trace_A(rho_ensemble_current);


        % =========================
        % Ensemble observables
        % =========================

        T_ensemble = ...
            compute_correlation_tensor(rho_ensemble_current);

        correlations_ensemble = ...
            compute_diagonal_correlations(rho_ensemble_current);

        ensemble_correlation_tensor(:, :, i_case) = ...
            real(T_ensemble);

        ensemble_correlation_xx(i_case) = ...
            real(correlations_ensemble.c_xx);

        ensemble_correlation_yy(i_case) = ...
            real(correlations_ensemble.c_yy);

        ensemble_correlation_zz(i_case) = ...
            real(correlations_ensemble.c_zz);


        % =========================
        % Ensemble state metrics
        % =========================

        ensemble_purity(i_case) = ...
            real(compute_purity(rho_ensemble_current));

        ensemble_purity_A(i_case) = ...
            real(compute_purity(rho_A_ensemble));

        ensemble_purity_B(i_case) = ...
            real(compute_purity(rho_B_ensemble));

        ensemble_fidelity(i_case) = ...
            real(compute_fidelity( ...
                rho_ensemble_current, ...
                psi_input));

        ensemble_concurrence(i_case) = ...
            real(compute_concurrence( ...
                rho_ensemble_current));

        ensemble_tangle(i_case) = ...
            real(compute_tangle( ...
                rho_ensemble_current));

        ensemble_entanglement_of_formation(i_case) = ...
            real(compute_entanglement_of_formation( ...
                rho_ensemble_current));

        ensemble_chsh_max(i_case) = ...
            real(compute_chsh_max_from_tensor( ...
                T_ensemble));


        % =========================
        % Progress summary
        % =========================

        rms_dgd_current = ...
            sqrt(mean(total_dgd(i_case, :) .^ 2));

        fprintf( ...
            ['  RMS DGD = %.3e s | expected %.3e s | ', ...
             'mean C = %.4f | ensemble C = %.4f\n'], ...
            rms_dgd_current, ...
            analytics.rms_total_dgd(i_case), ...
            mean(concurrence(i_case, :)), ...
            ensemble_concurrence(i_case));

    end


    % =========================
    % Statistical summaries
    % =========================

    statistics = struct();

    statistics.total_dgd = ...
        summarize_samples(total_dgd);

    statistics.normalized_pmd_strength = ...
        summarize_samples(normalized_pmd_strength);

    statistics.purity = ...
        summarize_samples(purity);

    statistics.fidelity = ...
        summarize_samples(fidelity);

    statistics.concurrence = ...
        summarize_samples(concurrence);

    statistics.tangle = ...
        summarize_samples(tangle);

    statistics.entanglement_of_formation = ...
        summarize_samples(entanglement_of_formation);

    statistics.chsh_max = ...
        summarize_samples(chsh_max);

    statistics.rms_total_dgd = ...
        sqrt(mean(total_dgd .^ 2, 2));

    statistics.pmd_vector_mean = ...
        reshape( ...
            mean(pmd_vector, 2), ...
            num_segment_cases, ...
            3);

    statistics.pmd_vector_std = ...
        reshape( ...
            std(pmd_vector, 0, 2), ...
            num_segment_cases, ...
            3);

    statistics.pmd_vector_standard_error = ...
        statistics.pmd_vector_std / ...
        sqrt(num_realizations);

    statistics.pmd_vector_rms = ...
        reshape( ...
            sqrt(mean(pmd_vector .^ 2, 2)), ...
            num_segment_cases, ...
            3);


    % =========================
    % Statistical validation
    % =========================

    validation = struct();

    validation.random_walk_rms_dgd = ...
        analytics.rms_total_dgd(:);

    validation.random_walk_rms_dgd_relative_error = ...
        abs( ...
            statistics.rms_total_dgd - ...
