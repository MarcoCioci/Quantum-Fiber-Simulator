function axes = sample_isotropic_axes(num_axes)
% SAMPLE_ISOTROPIC_AXES  Generate isotropically distributed unit vectors.
%
% Objective:
%   Sample independent directions uniformly on the unit sphere by
%   normalizing three-dimensional standard Gaussian vectors.
%
% Input:
%   num_axes - Number of axes to generate.
%
% Output:
%   axes - num_axes-by-3 matrix containing unit vectors.

    axes = ...
        randn(num_axes, 3);

    axis_norms = ...
        vecnorm(axes, 2, 2);

    null_axes = ...
        axis_norms == 0;

    while any(null_axes)

        axes(null_axes, :) = ...
            randn(sum(null_axes), 3);

        axis_norms = ...
            vecnorm(axes, 2, 2);

        null_axes = ...
            axis_norms == 0;

    end

    axes = ...
        axes ./ axis_norms;

end


function summary = summarize_samples(values)
% SUMMARIZE_SAMPLES  Compute row-wise Monte Carlo sample statistics.
%
% Objective:
%   Compute the principal statistical descriptors across independent fiber
%   realizations for each segment-count case.
%
% Input:
%   values - Matrix whose rows correspond to segment-count cases and whose
%            columns correspond to independent realizations.
%
% Output:
%   summary - Structure containing mean, standard deviation, standard
%             error, 10th percentile, median, and 90th percentile.

    num_samples = ...
        size(values, 2);

    summary = struct();

    summary.mean = ...
        mean(values, 2);

    summary.std = ...
        std(values, 0, 2);

    summary.standard_error = ...
        summary.std / sqrt(num_samples);

    summary.q10 = ...
        sample_quantile_rows( ...
            values, ...
            0.10);

    summary.median = ...
        sample_quantile_rows( ...
            values, ...
            0.50);

    summary.q90 = ...
        sample_quantile_rows( ...
            values, ...
            0.90);

end


function quantile_values = sample_quantile_rows(values, probability)
% SAMPLE_QUANTILE_ROWS  Compute row-wise quantiles without extra toolboxes.
%
% Objective:
%   Evaluate a linearly interpolated sample quantile independently for
%   every row of an input matrix without requiring Statistics and Machine
%   Learning Toolbox.
%
% Input:
%   values      - Numeric matrix containing sample values.
%   probability - Quantile probability in the interval [0,1].
%
% Output:
%   quantile_values - Column vector containing one quantile per row.

    sorted_values = ...
        sort(values, 2);

    num_samples = ...
        size(sorted_values, 2);

    position = ...
        1 + ...
        (num_samples - 1) * probability;

    lower_index = ...
        floor(position);

    upper_index = ...
        ceil(position);

    interpolation_weight = ...
        position - lower_index;

    quantile_values = ...
        (1 - interpolation_weight) * ...
        sorted_values(:, lower_index) + ...
        interpolation_weight * ...
        sorted_values(:, upper_index);

end