function quality = ...
        analyze_experiment_5_pmd_compensation_quality( ...
            relative_dgd_error_values, ...
            misalignment_angle_values, ...
            concurrence, ...
            concurrence_threshold)
% ANALYZE_EXPERIMENT_5_PMD_COMPENSATION_QUALITY
% Extract concurrence-threshold robustness quantities from Experiment 5.
%
% Objective:
%   Convert the concurrence map into an operational entanglement-quality
%   region defined by
%
%       C >= C_threshold.
%
%   The function extracts:
%
%       1. the binary quality mask;
%       2. concurrence at the nominal compensation point;
%       3. the best point in the sampled map;
%       4. the contiguous DGD-error interval around epsilon_tau = 0 for
%          which the threshold is satisfied at perfect axis alignment;
%       5. the maximum contiguous axis misalignment for which the threshold
%          is satisfied at nominal DGD compensation.
%
% Input:
%   relative_dgd_error_values - Strictly increasing vector of epsilon_tau.
%   misalignment_angle_values - Strictly increasing vector of alpha [rad],
%                               starting at alpha = 0.
%   concurrence               - N_alpha-by-N_error concurrence map.
%   concurrence_threshold     - Operational threshold in (0, 1).
%
% Output:
%   quality - Structure containing threshold mask and extracted tolerance
%             quantities.
%
% Notes:
%   The threshold crossings are linearly interpolated between neighboring
%   grid points. Therefore, the reported tolerance estimates are more
%   informative than returning only the last grid point above threshold.
%
%   If the threshold remains satisfied up to a scan boundary, the
%   corresponding clipped flag is set to true. In that case the reported
%   bound is only a lower bound on the actual tolerance.

    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 4
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'InvalidNumInputs'], ...
            ['Expected exactly 4 input arguments: ', ...
             'relative_dgd_error_values, misalignment_angle_values, ', ...
             'concurrence, concurrence_threshold.']);
    end

    if ~isnumeric(relative_dgd_error_values) || ...
            ~isreal(relative_dgd_error_values) || ...
            ~isvector(relative_dgd_error_values) || ...
            isempty(relative_dgd_error_values) || ...
            any(~isfinite(relative_dgd_error_values), 'all')
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'InvalidDGDErrorValues'], ...
            ['relative_dgd_error_values must be a non-empty finite ', ...
             'real numeric vector.']);
    end

    if any(diff(relative_dgd_error_values) <= 0)
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'UnsortedDGDErrorValues'], ...
            'relative_dgd_error_values must be strictly increasing.');
    end

    if ~isnumeric(misalignment_angle_values) || ...
            ~isreal(misalignment_angle_values) || ...
            ~isvector(misalignment_angle_values) || ...
            isempty(misalignment_angle_values) || ...
            any(~isfinite(misalignment_angle_values), 'all')
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'InvalidAngleValues'], ...
            ['misalignment_angle_values must be a non-empty finite ', ...
             'real numeric vector.']);
    end

    if any(diff(misalignment_angle_values) <= 0)
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'UnsortedAngleValues'], ...
            'misalignment_angle_values must be strictly increasing.');
    end

    num_angles = ...
        numel(misalignment_angle_values);

    num_dgd_errors = ...
        numel(relative_dgd_error_values);

    if ~isnumeric(concurrence) || ...
            ~isreal(concurrence) || ...
            ~isequal(size(concurrence), [num_angles, num_dgd_errors]) || ...
            any(~isfinite(concurrence), 'all')
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'InvalidConcurrenceMap'], ...
            ['concurrence must be a finite real matrix with size ', ...
             'N_alpha-by-N_error.']);
    end

    if any(concurrence < -1e-10, 'all') || ...
            any(concurrence > 1 + 1e-10, 'all')
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'InvalidConcurrenceRange'], ...
            'concurrence values must lie in [0, 1] within tolerance.');
    end

    if ~isnumeric(concurrence_threshold) || ...
            ~isscalar(concurrence_threshold) || ...
            ~isreal(concurrence_threshold) || ...
            ~isfinite(concurrence_threshold) || ...
            concurrence_threshold <= 0 || ...
            concurrence_threshold >= 1
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'InvalidConcurrenceThreshold'], ...
            'concurrence_threshold must satisfy 0 < C_threshold < 1.');
    end


    % =========================
    % Nominal indices
    % =========================

    [~, nominal_dgd_index] = ...
        min(abs(relative_dgd_error_values));

    [~, aligned_angle_index] = ...
        min(abs(misalignment_angle_values));

    nominal_dgd_error = ...
        relative_dgd_error_values(nominal_dgd_index);

    nominal_angle = ...
        misalignment_angle_values(aligned_angle_index);

    if abs(nominal_dgd_error) > 1e-12
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'MissingNominalDGDPoint'], ...
            'The DGD-error grid must contain epsilon_tau = 0.');
    end

    if abs(nominal_angle) > 1e-12
        error( ...
            ['analyze_experiment_5_pmd_compensation_quality:', ...
             'MissingAlignedPoint'], ...
            'The angle grid must contain alpha = 0.');
    end


    % =========================
    % Quality mask
    % =========================

    quality_mask = ...
        concurrence >= concurrence_threshold;

    nominal_concurrence = ...
        concurrence(aligned_angle_index, nominal_dgd_index);

    nominal_passes_threshold = ...
        quality_mask(aligned_angle_index, nominal_dgd_index);


    % =========================
    % Best sampled point
    % =========================

    [best_concurrence, best_linear_index] = ...
        max(concurrence, [], 'all', 'linear');

    [best_angle_index, best_dgd_index] = ...
        ind2sub(size(concurrence), best_linear_index);

    best_relative_dgd_error = ...
        relative_dgd_error_values(best_dgd_index);

    best_misalignment_angle = ...
        misalignment_angle_values(best_angle_index);


    % =========================
    % Default tolerance outputs
    % =========================

    dgd_error_threshold_interval = ...
        [NaN, NaN];

    dgd_lower_bound_clipped = ...
        false;

    dgd_upper_bound_clipped = ...
        false;

    max_misalignment_angle = ...
        NaN;

    angle_upper_bound_clipped = ...
        false;


    % =========================
    % DGD tolerance at alpha = 0
    % =========================

    if nominal_passes_threshold

        aligned_slice = ...
            concurrence(aligned_angle_index, :);

        aligned_mask = ...
            quality_mask(aligned_angle_index, :);

        left_index = ...
            nominal_dgd_index;

        while left_index > 1 && aligned_mask(left_index - 1)
            left_index = left_index - 1;
        end

        if left_index == 1 && aligned_mask(1)

            dgd_lower_bound = ...
                relative_dgd_error_values(1);

            dgd_lower_bound_clipped = ...
                true;

        else

            dgd_lower_bound = ...
                threshold_crossing( ...
                    relative_dgd_error_values(left_index - 1), ...
                    aligned_slice(left_index - 1), ...
                    relative_dgd_error_values(left_index), ...
                    aligned_slice(left_index), ...
                    concurrence_threshold);

        end

        right_index = ...
            nominal_dgd_index;

        while right_index < num_dgd_errors && ...
                aligned_mask(right_index + 1)
            right_index = right_index + 1;
        end

        if right_index == num_dgd_errors && aligned_mask(end)

            dgd_upper_bound = ...
                relative_dgd_error_values(end);

            dgd_upper_bound_clipped = ...
                true;

        else

            dgd_upper_bound = ...
                threshold_crossing( ...
                    relative_dgd_error_values(right_index), ...
                    aligned_slice(right_index), ...
                    relative_dgd_error_values(right_index + 1), ...
                    aligned_slice(right_index + 1), ...
                    concurrence_threshold);

        end

        dgd_error_threshold_interval = ...
            [dgd_lower_bound, dgd_upper_bound];


        % =========================
        % Angular tolerance at epsilon_tau = 0
        % =========================

        angle_slice = ...
            concurrence(:, nominal_dgd_index);

        angle_mask = ...
            quality_mask(:, nominal_dgd_index);

        last_angle_index = ...
            aligned_angle_index;

        while last_angle_index < num_angles && ...
                angle_mask(last_angle_index + 1)
            last_angle_index = last_angle_index + 1;
        end

        if last_angle_index == num_angles && angle_mask(end)

            max_misalignment_angle = ...
                misalignment_angle_values(end);

            angle_upper_bound_clipped = ...
                true;

        else

            max_misalignment_angle = ...
                threshold_crossing( ...
                    misalignment_angle_values(last_angle_index), ...
                    angle_slice(last_angle_index), ...
                    misalignment_angle_values(last_angle_index + 1), ...
                    angle_slice(last_angle_index + 1), ...
                    concurrence_threshold);

        end

    end


    % =========================
    % Output
    % =========================

    quality = struct();

    quality.concurrence_threshold = ...
        concurrence_threshold;

    quality.quality_mask = ...
        quality_mask;

    quality.quality_grid_fraction = ...
        mean(quality_mask, 'all');

    quality.nominal_dgd_index = ...
        nominal_dgd_index;

    quality.aligned_angle_index = ...
        aligned_angle_index;

    quality.nominal_concurrence = ...
        nominal_concurrence;

    quality.nominal_passes_threshold = ...
        nominal_passes_threshold;

    quality.nominal_margin = ...
        nominal_concurrence - concurrence_threshold;

    quality.best_concurrence = ...
        best_concurrence;

    quality.best_relative_dgd_error = ...
        best_relative_dgd_error;

    quality.best_misalignment_angle = ...
        best_misalignment_angle;

    quality.dgd_error_threshold_interval = ...
        dgd_error_threshold_interval;

    quality.dgd_lower_bound_clipped = ...
        dgd_lower_bound_clipped;

    quality.dgd_upper_bound_clipped = ...
        dgd_upper_bound_clipped;

    quality.max_misalignment_angle = ...
        max_misalignment_angle;

    quality.angle_upper_bound_clipped = ...
        angle_upper_bound_clipped;

end


function x_crossing = ...
        threshold_crossing(x_1, y_1, x_2, y_2, threshold)
% THRESHOLD_CROSSING  Linearly interpolate a threshold crossing.

    delta_y = ...
        y_2 - y_1;

    if abs(delta_y) < eps(max(abs([y_1, y_2, threshold, 1])))
        x_crossing = ...
            0.5 * (x_1 + x_2);

        return;
    end

    interpolation_fraction = ...
        (threshold - y_1) / delta_y;

    interpolation_fraction = ...
        min(max(interpolation_fraction, 0), 1);

    x_crossing = ...
        x_1 + interpolation_fraction * (x_2 - x_1);

end
