function fig = ...
        plot_experiment_5_pmd_compensation_robustness( ...
            results_experiment_5, do_save)
% PLOT_EXPERIMENT_5_PMD_COMPENSATION_ROBUSTNESS
% Plot the concurrence robustness map and threshold sections.
%
% Objective:
%   Visualize:
%
%       1. concurrence C(epsilon_tau, alpha);
%       2. the operational boundary C = C_threshold;
%       3. the aligned DGD-error section, including the continuous Gaussian
%          analytical benchmark;
%       4. the angular-misalignment section at nominal DGD compensation.
%
% Input:
%   results_experiment_5 - Structure produced by
%                          run_experiment_5_pmd_compensation_robustness.
%   do_save             - Logical scalar controlling figure export.
%
% Output:
%   fig - Handle to the Experiment 5 figure.
%
% Notes:
%   The plotting function follows the shared project pipeline:
%
%       results
%          ->
%       get_plot_style / get_plot_palette
%          ->
%       get_experiment_figure_tab
%          ->
%       build_plot(parent)
%          ->
%       export_plot.
%
%   The threshold contour is an operational quality boundary, not the
%   separability boundary C = 0.

    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 2
        error( ...
            ['plot_experiment_5_pmd_compensation_robustness:', ...
             'InvalidNumInputs'], ...
            ['Expected exactly 2 input arguments: ', ...
             'results_experiment_5 and do_save.']);
    end

    if ~isstruct(results_experiment_5)
        error( ...
            ['plot_experiment_5_pmd_compensation_robustness:', ...
             'InvalidResults'], ...
            'results_experiment_5 must be a structure.');
    end

    if ~(islogical(do_save) && isscalar(do_save))
        error( ...
            ['plot_experiment_5_pmd_compensation_robustness:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    required_fields = { ...
        'parameters', ...
        'concurrence', ...
        'analytical', ...
        'quality'};

    check_required_fields( ...
        results_experiment_5, ...
        required_fields, ...
        ['plot_experiment_5_pmd_compensation_robustness:', ...
         'MissingField']);

    required_parameter_fields = { ...
        'concurrence_threshold', ...
        'relative_dgd_error_values', ...
        'misalignment_angle_values'};

    check_required_fields( ...
        results_experiment_5.parameters, ...
        required_parameter_fields, ...
        ['plot_experiment_5_pmd_compensation_robustness:', ...
         'MissingParameterField']);

    required_analytical_fields = { ...
        'concurrence'};

    check_required_fields( ...
        results_experiment_5.analytical, ...
        required_analytical_fields, ...
        ['plot_experiment_5_pmd_compensation_robustness:', ...
         'MissingAnalyticalField']);

    required_quality_fields = { ...
        'aligned_angle_index', ...
        'nominal_dgd_index', ...
        'best_relative_dgd_error', ...
        'best_misalignment_angle'};

    check_required_fields( ...
        results_experiment_5.quality, ...
        required_quality_fields, ...
        ['plot_experiment_5_pmd_compensation_robustness:', ...
         'MissingQualityField']);


    % =========================
    % Extract data
    % =========================

    relative_dgd_error_values = ...
        results_experiment_5.parameters.relative_dgd_error_values(:).';

    misalignment_angle_values = ...
        results_experiment_5.parameters.misalignment_angle_values(:).';

    concurrence_threshold = ...
        results_experiment_5.parameters.concurrence_threshold;

    concurrence = ...
        real(results_experiment_5.concurrence);

    analytical_concurrence = ...
        real(results_experiment_5.analytical.concurrence(:).');

    num_angles = ...
        numel(misalignment_angle_values);

    num_dgd_errors = ...
        numel(relative_dgd_error_values);

    if ~isequal(size(concurrence), [num_angles, num_dgd_errors])
        error( ...
            ['plot_experiment_5_pmd_compensation_robustness:', ...
             'InvalidConcurrenceSize'], ...
            ['concurrence must have size N_alpha-by-N_error, matching ', ...
             'the parameter grids.']);
    end

    if numel(analytical_concurrence) ~= num_dgd_errors
        error( ...
            ['plot_experiment_5_pmd_compensation_robustness:', ...
             'InvalidAnalyticalSize'], ...
            ['analytical.concurrence must contain one value for each ', ...
             'relative DGD error.']);
    end

    if any(~isfinite(concurrence), 'all') || ...
            any(~isfinite(analytical_concurrence), 'all')
        error( ...
            ['plot_experiment_5_pmd_compensation_robustness:', ...
             'InvalidValues'], ...
            'All concurrence values must be finite.');
    end

    aligned_angle_index = ...
        results_experiment_5.quality.aligned_angle_index;

    nominal_dgd_index = ...
        results_experiment_5.quality.nominal_dgd_index;

    dgd_error_percent = ...
        100 * relative_dgd_error_values;

    misalignment_angle_degrees = ...
        rad2deg(misalignment_angle_values);

    aligned_concurrence = ...
        concurrence(aligned_angle_index, :);

    nominal_dgd_concurrence = ...
        concurrence(:, nominal_dgd_index);


    % =========================
    % Plot style
    % =========================

    palette = ...
        get_plot_palette();

    style = ...
        get_plot_style();


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = ...
        get_experiment_figure_tab( ...
            style.figure.experiment_5_id, ...
            'Compensation robustness', ...
            'Experiment 5 - PMD Compensation Robustness', ...
            style);

    build_plot(tab, false);

    set(fig, ...
        'Visible', ...
        style.figure.visible_after_build);


    % =========================
    % Save
    % =========================

    if do_save

        output_path = ...
            fullfile( ...
                'images', ...
                'experiment_5', ...
                'experiment_5_pmd_compensation_robustness.png');

        export_plot( ...
            output_path, ...
            @(parent) build_plot(parent, false), ...
            style);

    end


    % =========================
    % Local plot builder
    % =========================

    function layout = build_plot(parent_container, show_title)

        if nargin < 2
            show_title = false;
        end

        layout = ...
            tiledlayout( ...
                parent_container, ...
                3, ...
                1, ...
                'TileSpacing', ...
                style.layout.tile_spacing, ...
                'Padding', ...
                style.layout.padding);


        % =========================
        % Panel 1: concurrence map
        % =========================

        ax = ...
            nexttile(layout);

        imagesc( ...
            ax, ...
            dgd_error_percent, ...
            misalignment_angle_degrees, ...
            concurrence);

        set(ax, ...
            'YDir', 'normal');

        if isfield(style, 'heatmap') && ...
                isfield(style.heatmap, 'colormap')
            colormap( ...
                ax, ...
                style.heatmap.colormap);
        end

        clim(ax, [0, 1]);

        cb = ...
            colorbar(ax);

        cb.Label.String = ...
            'Concurrence $C$';

        cb.Label.Interpreter = ...
            'latex';

        hold(ax, 'on');

        [contour_matrix, contour_handle] = ...
            contour( ...
                ax, ...
                dgd_error_percent, ...
                misalignment_angle_degrees, ...
                concurrence, ...
                [concurrence_threshold, concurrence_threshold], ...
                '--', ...
                'LineWidth', ...
                1.8, ...
                'Color', ...
                palette.black);

        if ~isempty(contour_matrix)
            clabel( ...
                contour_matrix, ...
                contour_handle, ...
                'Interpreter', ...
                'latex', ...
                'FontSize', ...
                style.labels.font_size);
        end

        plot( ...
            ax, ...
            0, ...
            0, ...
            'o', ...
            'MarkerSize', ...
            7, ...
            'MarkerFaceColor', ...
            palette.metric_C, ...
            'MarkerEdgeColor', ...
            palette.black);

        plot( ...
            ax, ...
            100 * results_experiment_5.quality.best_relative_dgd_error, ...
            rad2deg(results_experiment_5.quality.best_misalignment_angle), ...
            'x', ...
            'MarkerSize', ...
            9, ...
            'LineWidth', ...
            1.8, ...
            'Color', ...
            palette.black);

        xlabel( ...
            ax, ...
            'Relative compensation-DGD error $100\epsilon_\tau$ [\%]', ...
            'Interpreter', ...
            'latex');

        ylabel( ...
            ax, ...
            'Compensator-axis misalignment $\alpha$ [deg]', ...
            'Interpreter', ...
            'latex');

        title( ...
            ax, ...
            sprintf( ...
                'Concurrence robustness map; quality boundary $C=%.2f$', ...
                concurrence_threshold), ...
            'Interpreter', ...
            'latex');

        set_common_axes_style(ax);


        % =========================
        % Panel 2: DGD robustness
        % =========================

        ax = ...
            nexttile(layout);

        hold(ax, 'on');

        plot( ...
            ax, ...
            dgd_error_percent, ...
            analytical_concurrence, ...
            '-', ...
            'LineWidth', ...
            1.8, ...
            'Color', ...
            palette.analytical);

        plot( ...
            ax, ...
            dgd_error_percent, ...
            aligned_concurrence, ...
            'o', ...
            'MarkerSize', ...
            4, ...
            'MarkerFaceColor', ...
            palette.numerical, ...
            'MarkerEdgeColor', ...
            palette.numerical);

        yline( ...
            ax, ...
            concurrence_threshold, ...
            '--', ...
            'LineWidth', ...
            1.5, ...
            'Color', ...
            palette.gray_dark);

        xline( ...
            ax, ...
            0, ...
            ':', ...
            'LineWidth', ...
            1.2, ...
            'Color', ...
            palette.gray_mid);

        xlabel( ...
            ax, ...
            'Relative compensation-DGD error $100\epsilon_\tau$ [\%]', ...
            'Interpreter', ...
            'latex');

        ylabel( ...
            ax, ...
            'Concurrence $C$', ...
            'Interpreter', ...
            'latex');

        title( ...
            ax, ...
            'DGD-setting robustness at perfect axis alignment', ...
            'Interpreter', ...
            'latex');

        ylim(ax, [0, 1.05]);

        legend( ...
            ax, ...
            { ...
                'continuous Gaussian benchmark', ...
                'numerical spectral trace', ...
                sprintf('quality threshold C = %.2f', ...
                    concurrence_threshold), ...
                'nominal DGD setting' ...
            }, ...
            'Location', ...
            'southoutside', ...
            'Orientation', ...
            'horizontal');

        set_common_axes_style(ax);


        % =========================
        % Panel 3: axis robustness
        % =========================

        ax = ...
            nexttile(layout);

        hold(ax, 'on');

        plot( ...
            ax, ...
            misalignment_angle_degrees, ...
            nominal_dgd_concurrence, ...
            '-o', ...
            'LineWidth', ...
            1.6, ...
            'MarkerSize', ...
            4, ...
            'Color', ...
            palette.metric_C, ...
            'MarkerFaceColor', ...
            palette.metric_C, ...
            'MarkerEdgeColor', ...
            palette.metric_C);

        yline( ...
            ax, ...
            concurrence_threshold, ...
            '--', ...
            'LineWidth', ...
            1.5, ...
            'Color', ...
            palette.gray_dark);

        xlabel( ...
            ax, ...
            'Compensator-axis misalignment $\alpha$ [deg]', ...
            'Interpreter', ...
            'latex');

        ylabel( ...
            ax, ...
            'Concurrence $C$', ...
            'Interpreter', ...
            'latex');

        title( ...
            ax, ...
            'Axis-orientation robustness at nominal compensation DGD', ...
            'Interpreter', ...
            'latex');

        ylim(ax, [0, 1.05]);

        legend( ...
            ax, ...
            { ...
                'numerical concurrence', ...
                sprintf('quality threshold C = %.2f', ...
                    concurrence_threshold) ...
            }, ...
            'Location', ...
            'southoutside', ...
            'Orientation', ...
            'horizontal');

        set_common_axes_style(ax);


        % =========================
        % Global title
        % =========================

        if show_title
            title( ...
                layout, ...
                'Experiment 5 - PMD Compensation Robustness', ...
                'FontSize', ...
                style.title.font_size, ...
                'FontWeight', ...
                style.title.font_weight, ...
                'Interpreter', ...
                style.title.interpreter);
        end

    end


    function set_common_axes_style(ax)

        grid(ax, style.axes.grid);
        box(ax, style.axes.box);

        set( ...
            ax, ...
            'FontSize', ...
            style.axes.font_size, ...
            'LineWidth', ...
            style.axes.line_width, ...
            'TickLabelInterpreter', ...
            style.axes.tick_label_interpreter, ...
            'Layer', ...
            style.axes.layer);

    end

end
