function analytics = analytical_values_experiment_1_single_segment_pmd( ...
        dgd_values, sigma_omega_values)
% ANALYTICAL_VALUES_EXPERIMENT_1_SINGLE_SEGMENT_PMD
% Analytical predictions for single-segment PMD acting on one photon of a
% polarization-entangled Bell pair.
%
% Objective:
%   Evaluate the closed-form reduced polarization state and the associated
%   state metrics for Experiment 1:
%
%       Single-Segment PMD and the Bandwidth--DGD Regime.
%
%   The analytical model considers the input Bell state
%
%       |Psi+> = (|01> + |10>) / sqrt(2),
%
%   with a single birefringent segment acting on photon A and ideal
%   propagation in arm B.
%
%   The segment is chosen with
%
%       delta_phase = 0,
%       n = z_hat,
%
%   so that its frequency-dependent polarization operator is
%
%       U_A(Omega)
%       =
%       exp[
%           +i/2 * Omega * delta_tau * sigma_z
%       ].
%
%   The physical differential group delay is
%
%       DGD = |delta_tau|.
%
%   Photon A is assumed to have a zero-mean Gaussian marginal angular-
%   frequency distribution
%
%       p(Omega_A)
%       proportional to
%       exp[-Omega_A^2 / (2 * sigma_omega^2)].
%
%   After tracing over frequency, the polarization coherence is reduced by
%
%       g =
%       exp[-0.5 * (sigma_omega * DGD)^2].
%
%   Introducing the dimensionless PMD strength
%
%       xi = sigma_omega * DGD,
%
%   the reduced polarization state is
%
%       rho_out =
%       1/2 * [
%           |01><01| + |10><10|
%           + g |01><10| + g |10><01|
%       ].
%
%   The corresponding closed-form metrics are
%
%       purity      = (1 + g^2) / 2,
%
%       fidelity    = (1 + g) / 2,
%
%       concurrence = g,
%
%       tangle      = g^2,
%
%       S_max       = 2 * sqrt(1 + g^2).
%
% Input:
%   dgd_values         - Non-empty vector of physical differential group
%                        delays
%
%                            DGD = |delta_tau|
%
%                        [s]. Values must be finite and non-negative.
%
%   sigma_omega_values - Non-empty vector of marginal angular-frequency
%                        standard deviations sigma_omega [rad/s].
%                        Values must be finite and non-negative.
%
% Output:
%   analytics - Structure containing the analytical predictions.
%
%       analytics.dgd_values
%           1-by-N_DGD row vector of DGD values [s].
%
%       analytics.sigma_omega_values
%           N_sigma-by-1 column vector of marginal spectral standard
%           deviations [rad/s].
%
%       analytics.sigma_sum_values
%       analytics.sigma_difference_values
%           JSI parameters corresponding to the symmetric uncorrelated
%           Gaussian source used by the numerical implementation:
%
%               sigma_sum = sigma_difference
%                         = sqrt(2) * sigma_omega.
%
%       analytics.normalized_pmd_strength
%           N_sigma-by-N_DGD matrix containing
%
%               xi = sigma_omega * DGD.
%
%       analytics.coherence_factor
%           N_sigma-by-N_DGD matrix containing
%
%               g = exp(-xi^2 / 2).
%
%       analytics.rho_output
%           4-by-4-by-N_sigma-by-N_DGD array of analytical reduced
%           polarization density matrices.
%
%       analytics.purity
%       analytics.fidelity
%       analytics.concurrence
%       analytics.tangle
%       analytics.entanglement_of_formation
%       analytics.chsh_max
%           N_sigma-by-N_DGD matrices containing the corresponding
%           analytical state metrics.
%
%       analytics.correlation_tensor
%           3-by-3-by-N_sigma-by-N_DGD array containing the analytical
%           Pauli correlation tensor.
%
%       analytics.correlations
%           Structure containing the non-zero aligned correlations
%
%               T_xx = g,
%               T_yy = g,
%               T_zz = -1.
%
% Notes:
%   This analytical reference deliberately isolates PMD-induced
%   polarization-frequency decoherence. The carrier-frequency differential
%   phase is set to zero so that fidelity degradation reflects spectral
%   decoherence rather than a deterministic local polarization rotation.
%
%   The numerical JSI generated by pmd_joint_spectral_weights is
%   uncorrelated and symmetric when
%
%       sigma_sum = sigma_difference = sqrt(2) * sigma_omega.
%
%   Under this choice, the marginal distribution of both photons has
%   standard deviation sigma_omega.
%
%   The analytical expressions correspond to an ideal continuous Gaussian
%   spectrum with infinite support. Numerical results obtained on a finite
%   spectral grid converge to these values as the spectral resolution and
%   integration window are increased.
%
%   The quantity xi = sigma_omega * DGD is dimensionless and is the natural
%   control parameter for the bandwidth--DGD regime studied in Experiment 1.

    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 2
        error( ...
            'analytical_values_experiment_1_single_segment_pmd:InvalidNumInputs', ...
            ['Expected exactly 2 input arguments: dgd_values and ', ...
             'sigma_omega_values.']);
    end

    if ~isnumeric(dgd_values) || ...
            ~isreal(dgd_values) || ...
            ~isvector(dgd_values) || ...
            isempty(dgd_values)
        error( ...
            'analytical_values_experiment_1_single_segment_pmd:InvalidDGDValues', ...
            'dgd_values must be a non-empty real numeric vector.');
    end

    if any(~isfinite(dgd_values), 'all')
        error( ...
            'analytical_values_experiment_1_single_segment_pmd:InvalidDGDValues', ...
            'dgd_values must contain only finite values.');
    end

    if any(dgd_values < 0, 'all')
        error( ...
            'analytical_values_experiment_1_single_segment_pmd:NegativeDGD', ...
            'dgd_values must contain only non-negative values.');
    end

    if ~isnumeric(sigma_omega_values) || ...
            ~isreal(sigma_omega_values) || ...
            ~isvector(sigma_omega_values) || ...
            isempty(sigma_omega_values)
        error( ...
            ['analytical_values_experiment_1_single_segment_pmd:', ...
             'InvalidSigmaOmegaValues'], ...
            'sigma_omega_values must be a non-empty real numeric vector.');
    end

    if any(~isfinite(sigma_omega_values), 'all')
        error( ...
            ['analytical_values_experiment_1_single_segment_pmd:', ...
             'InvalidSigmaOmegaValues'], ...
            'sigma_omega_values must contain only finite values.');
    end

    if any(sigma_omega_values < 0, 'all')
        error( ...
            ['analytical_values_experiment_1_single_segment_pmd:', ...
             'NegativeSigmaOmega'], ...
            'sigma_omega_values must contain only non-negative values.');
    end


    % =========================
    % Input normalization
    % =========================

    % DGD values are stored as a row vector.
    dgd_values = dgd_values(:).';

    % Spectral standard deviations are stored as a column vector.
    sigma_omega_values = sigma_omega_values(:);

    num_dgd_values = numel(dgd_values);
    num_sigma_values = numel(sigma_omega_values);


    % =========================
    % Gaussian source parameters
    % =========================

    % For the symmetric uncorrelated Gaussian JSI used in Experiment 1,
    %
    %   sigma_sum = sigma_difference = sqrt(2) * sigma_omega.
    %
    % This produces marginal Gaussian distributions with standard
    % deviation sigma_omega in both arms.

    sigma_sum_values = sqrt(2) * sigma_omega_values;
    sigma_difference_values = sqrt(2) * sigma_omega_values;


    % =========================
    % PMD coherence factor
    % =========================

    % Dimensionless competition between spectral bandwidth and DGD:
    %
    %   xi = sigma_omega * DGD.
    %
    % The outer product generates the full bandwidth--DGD parameter map.

    normalized_pmd_strength = ...
        sigma_omega_values * dgd_values;

    % Gaussian characteristic function:
    %
    %   g = <exp(i Omega delta_tau)>
    %     = exp[-0.5 * sigma_omega^2 * delta_tau^2].

    coherence_factor = ...
        exp(-0.5 * normalized_pmd_strength.^2);


    % =========================
    % Analytical density matrices
    % =========================

    rho_output = complex(zeros( ...
        4, 4, num_sigma_values, num_dgd_values));

    for i_sigma = 1:num_sigma_values

        for i_dgd = 1:num_dgd_values

            g = coherence_factor(i_sigma, i_dgd);

            % Computational basis ordering:
            %
            %   |00>, |01>, |10>, |11>.
            %
            % For the input |Psi+> state after the spectral trace:
            %
            %       [ 0    0    0    0 ]
            %       [ 0   1/2  g/2   0 ]
            % rho = [ 0   g/2  1/2   0 ]
            %       [ 0    0    0    0 ].

            rho_current = complex(zeros(4, 4));

            rho_current(2, 2) = 0.5;
            rho_current(3, 3) = 0.5;

            rho_current(2, 3) = 0.5 * g;
            rho_current(3, 2) = 0.5 * g;

            rho_output(:, :, i_sigma, i_dgd) = rho_current;

        end

    end


    % =========================
    % Analytical state metrics
    % =========================

    concurrence = coherence_factor;

    purity = ...
        0.5 * (1 + coherence_factor.^2);

    fidelity = ...
        0.5 * (1 + coherence_factor);

    tangle = ...
        concurrence.^2;

    chsh_max = ...
        2 * sqrt(1 + concurrence.^2);


    % =========================
    % Entanglement of formation
    % =========================

    % For a two-qubit state,
    %
    %   E_F =
    %   h_2[
    %       (1 + sqrt(1 - C^2)) / 2
    %   ],
    %
    % where h_2 is the binary entropy.

    eof_probability = ...
        0.5 * (1 + sqrt(max(0, 1 - concurrence.^2)));

    complementary_probability = ...
        1 - eof_probability;

    entanglement_of_formation = ...
        zeros(size(concurrence));

    mask_probability = eof_probability > 0;

    entanglement_of_formation(mask_probability) = ...
        entanglement_of_formation(mask_probability) ...
        - eof_probability(mask_probability) .* ...
        log2(eof_probability(mask_probability));

    mask_complementary = complementary_probability > 0;

    entanglement_of_formation(mask_complementary) = ...
        entanglement_of_formation(mask_complementary) ...
        - complementary_probability(mask_complementary) .* ...
        log2(complementary_probability(mask_complementary));


    % =========================
    % Analytical correlation tensor
    % =========================

    % For the reduced state considered here,
    %
    %       T =
    %       [ g   0   0
    %         0   g   0
    %         0   0  -1 ].
    %
    % The z correlation remains perfectly anticorrelated, while the
    % transverse x and y correlations decay with the spectral coherence.

    correlation_tensor = zeros( ...
        3, 3, num_sigma_values, num_dgd_values);

    for i_sigma = 1:num_sigma_values

        for i_dgd = 1:num_dgd_values

            g = coherence_factor(i_sigma, i_dgd);

            correlation_tensor(:, :, i_sigma, i_dgd) = ...
                [ ...
                    g,  0,  0; ...
                    0,  g,  0; ...
                    0,  0, -1 ...
                ];

        end

    end


    % =========================
    % Output structure
    % =========================

    analytics = struct();

    analytics.dgd_values = ...
        dgd_values;

    analytics.sigma_omega_values = ...
        sigma_omega_values;

    analytics.sigma_sum_values = ...
        sigma_sum_values;

    analytics.sigma_difference_values = ...
        sigma_difference_values;

    analytics.normalized_pmd_strength = ...
        normalized_pmd_strength;

    analytics.coherence_factor = ...
        coherence_factor;

    analytics.rho_output = ...
        rho_output;

    analytics.purity = ...
        purity;

    analytics.fidelity = ...
        fidelity;

    analytics.concurrence = ...
        concurrence;

    analytics.tangle = ...
        tangle;

    analytics.entanglement_of_formation = ...
        entanglement_of_formation;

    analytics.chsh_max = ...
        chsh_max;

    analytics.correlation_tensor = ...
        correlation_tensor;

    analytics.correlations = struct();

    analytics.correlations.xx = ...
        coherence_factor;

    analytics.correlations.yy = ...
        coherence_factor;

    analytics.correlations.zz = ...
        -ones(size(coherence_factor));

end