function fig = plot_experiment_1_single_segment_pmd_regime_map( ...
        results_experiment_1, do_save)
% PLOT_EXPERIMENT_1_SINGLE_SEGMENT_PMD_REGIME_MAP
% Plot bandwidth--DGD regime maps for single-segment PMD.
%
% Objective:
%   Visualize the dependence of the reduced polarization state on the two
%   principal physical parameters investigated in Experiment 1:
%
%       DGD
%
%   and
%
%       sigma_omega.
%
%   Four two-dimensional maps are shown:
%
%       1) concurrence C,
%       2) global purity gamma,
%       3) Bell-state fidelity F_{Psi+},
%       4) maximal CHSH parameter S_max.
%
%   The horizontal axis represents the physical differential group delay
%   in picoseconds:
%
%       DGD [ps].
%
%   The vertical axis represents the marginal spectral standard deviation
%   converted from angular frequency to ordinary frequency:
%
%       sigma_f = sigma_omega / (2*pi) [GHz].
%
%   The dimensionless PMD strength
%
%       xi = sigma_omega * DGD
%
%   determines the analytical behavior of the single-segment model.
%   Whenever xi = 1 lies inside the simulated parameter region, its contour
%   is superimposed on each panel.
%
% Input:
%   results_experiment_1 - Structure produced by
%                          run_experiment_1_single_segment_pmd.
%
%   do_save              - Optional logical scalar. If true, export the
%                          regime-map figure.
%                          Default: false.
%
% Output:
%   fig                  - Handle to the Experiment 1 figure window.
%
% Notes:
%   This figure is intended to display the physical parameter regimes of
%   Experiment 1. Numerical-versus-analytical errors are deliberately not
%   included here and are treated separately in the numerical-validation
%   and summary analysis.
%
%   The result matrices follow the convention
%
%       row    -> sigma_omega,
%       column -> DGD.
%
%   The same local build_plot function is used for both the interactive
%   experiment tab and the standalone exported figure.

    % =========================
    % Default input handling
    % =========================

    if nargin < 1 || nargin > 2
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidNumInputs'], ...
            'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = false;
    end


    % =========================
    % Robustness checks
    % =========================

    if ~islogical(do_save) || ~isscalar(do_save)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    if ~isstruct(results_experiment_1)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidInputType'], ...
            'results_experiment_1 must be a structure.');
    end

    check_required_fields( ...
        results_experiment_1, ...
        {'parameters', 'numerical'}, ...
        ['plot_experiment_1_single_segment_pmd_regime_map:', ...
         'MissingMainField']);

    if ~isstruct(results_experiment_1.parameters)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidParametersStructure'], ...
            'results_experiment_1.parameters must be a structure.');
    end

    if ~isstruct(results_experiment_1.numerical)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidNumericalStructure'], ...
            'results_experiment_1.numerical must be a structure.');
    end

    check_required_fields( ...
        results_experiment_1.parameters, ...
        { ...
            'dgd_values', ...
            'sigma_omega_values', ...
            'normalized_pmd_strength' ...
        }, ...
        ['plot_experiment_1_single_segment_pmd_regime_map:', ...
         'MissingParameterField']);

    check_required_fields( ...
        results_experiment_1.numerical, ...
        { ...
            'purity', ...
            'fidelity', ...
            'concurrence', ...
            'chsh_max' ...
        }, ...
        ['plot_experiment_1_single_segment_pmd_regime_map:', ...
         'MissingNumericalField']);


    % =========================
    % Extract data
    % =========================

    dgd_values = ...
        results_experiment_1.parameters.dgd_values(:).';

    sigma_omega_values = ...
        results_experiment_1.parameters.sigma_omega_values(:);

    normalized_pmd_strength = ...
        results_experiment_1.parameters.normalized_pmd_strength;

    purity = ...
        results_experiment_1.numerical.purity;

    fidelity = ...
        results_experiment_1.numerical.fidelity;

    concurrence = ...
        results_experiment_1.numerical.concurrence;

    chsh_max = ...
        results_experiment_1.numerical.chsh_max;


    % =========================
    % Parameter validation
    % =========================

    if ~isnumeric(dgd_values) || ...
            ~isreal(dgd_values) || ...
            isempty(dgd_values) || ...
            any(~isfinite(dgd_values), 'all')
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidDGDValues'], ...
            'dgd_values must contain finite real numeric values.');
    end

    if any(dgd_values < 0, 'all')
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'NegativeDGDValues'], ...
            'dgd_values must be non-negative.');
    end

    if ~isnumeric(sigma_omega_values) || ...
            ~isreal(sigma_omega_values) || ...
            isempty(sigma_omega_values) || ...
            any(~isfinite(sigma_omega_values), 'all')
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidSigmaOmegaValues'], ...
            ['sigma_omega_values must contain finite real numeric ', ...
             'values.']);
    end

    if any(sigma_omega_values <= 0, 'all')
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidSigmaOmegaRange'], ...
            'sigma_omega_values must contain only positive values.');
    end

    num_dgd_values = ...
        numel(dgd_values);

    num_sigma_values = ...
        numel(sigma_omega_values);

    if num_dgd_values < 2 || num_sigma_values < 2
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InsufficientMapResolution'], ...
            ['The regime map requires at least two DGD values and ', ...
             'two sigma_omega values.']);
    end

    if any(diff(dgd_values) <= 0)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'NonIncreasingDGDGrid'], ...
            'dgd_values must be strictly increasing.');
    end

    if any(diff(sigma_omega_values) <= 0)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'NonIncreasingSigmaOmegaGrid'], ...
            'sigma_omega_values must be strictly increasing.');
    end


    % =========================
    % Map validation
    % =========================

    expected_map_size = ...
        [num_sigma_values, num_dgd_values];

    map_names = { ...
        'normalized_pmd_strength', ...
        'purity', ...
        'fidelity', ...
        'concurrence', ...
        'chsh_max' ...
    };

    map_values = { ...
        normalized_pmd_strength, ...
        purity, ...
        fidelity, ...
        concurrence, ...
        chsh_max ...
    };

    for map_idx = 1:numel(map_values)

        current_map = map_values{map_idx};

        if ~isnumeric(current_map) || ...
                ~isreal(current_map) || ...
                ~isequal(size(current_map), expected_map_size)
            error( ...
                ['plot_experiment_1_single_segment_pmd_regime_map:', ...
                 'InvalidMapSize'], ...
                ['Field "%s" must be a real numeric ', ...
                 'N_sigma-by-N_DGD matrix.'], ...
                map_names{map_idx});
        end

        if any(~isfinite(current_map), 'all')
            error( ...
                ['plot_experiment_1_single_segment_pmd_regime_map:', ...
                 'InvalidMapValues'], ...
                'Field "%s" must contain only finite values.', ...
                map_names{map_idx});
        end

    end


    % =========================
    % Physical plotting units
    % =========================

    % Differential group delay:
    %
    %   seconds -> picoseconds.

    dgd_ps = ...
        dgd_values * 1e12;

    % Marginal spectral standard deviation:
    %
    %   sigma_f = sigma_omega / (2*pi)
    %
    % and
    %
    %   Hz -> GHz.

    sigma_frequency_ghz = ...
        sigma_omega_values / (2 * pi * 1e9);


    % =========================
    % Plot style
    % =========================

    style = get_plot_style();
    palette = get_plot_palette();


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = get_experiment_figure_tab( ...
        style.figure.experiment_1_id, ...
        'Bandwidth-DGD regime map', ...
        'Experiment 1 — Single-Segment PMD', ...
        style);

    build_plot(tab, false);

    set(fig, ...
        'Visible', ...
        style.figure.visible_after_build);


    % =========================
    % Save (conditional)
    % =========================

    if do_save

        % Determine project root dynamically from this function location:
        %
        % project_root/
        %   src/
        %     experiments/
        %       thesis_experiments/
        %         experiment_1_single_segment_pmd/
        %           current_file.m

        experiment_folder = ...
            fileparts(mfilename('fullpath'));

        thesis_experiments_folder = ...
            fileparts(experiment_folder);

        experiments_folder = ...
            fileparts(thesis_experiments_folder);

        src_folder = ...
            fileparts(experiments_folder);

        project_root = ...
            fileparts(src_folder);

        output_folder = ...
            fullfile( ...
                project_root, ...
                'images', ...
                'experiment_1');

        if ~isfolder(output_folder)
            mkdir(output_folder);
        end

        output_path = ...
            fullfile( ...
                output_folder, ...
                'experiment_1_single_segment_pmd_regime_map.png');

        export_plot( ...
            output_path, ...
            @(parent) build_plot(parent, false), ...
            style);

    end


    % =========================
    % Local plot builder
    % =========================

    function tl = build_plot(parent_container, show_title)
    % BUILD_PLOT  Construct the complete bandwidth--DGD regime map.
    %
    % Input:
    %   parent_container - Figure or tab receiving the tiled layout.
    %   show_title       - Logical flag controlling the global title.
    %
    % Output:
    %   tl               - Tiled-layout handle.

        if nargin < 2
            show_title = false;
        end

        tl = tiledlayout( ...
            parent_container, ...
            2, ...
            2, ...
            'TileSpacing', style.layout.tile_spacing, ...
            'Padding', style.layout.padding);


        % =====================================================
        % Panel 1: concurrence
        % =====================================================

        ax = nexttile(tl);

        plot_regime_panel( ...
            ax, ...
            concurrence, ...
            'Concurrence', ...
            '$C$', ...
            [0, 1]);


        % =====================================================
        % Panel 2: global purity
        % =====================================================

        ax = nexttile(tl);

        plot_regime_panel( ...
            ax, ...
            purity, ...
            'Global purity', ...
            '$\gamma(\rho_{AB})$', ...
            [0.5, 1]);


        % =====================================================
        % Panel 3: Bell-state fidelity
        % =====================================================

        ax = nexttile(tl);

        plot_regime_panel( ...
            ax, ...
            fidelity, ...
            'Bell-state fidelity', ...
            '$F_{\Psi^+}$', ...
            [0.5, 1]);


        % =====================================================
        % Panel 4: maximal CHSH value
        % =====================================================

        ax = nexttile(tl);

        plot_regime_panel( ...
            ax, ...
            chsh_max, ...
            'Maximal CHSH parameter', ...
            '$S_{\max}$', ...
            [2, 2 * sqrt(2)]);


        % =========================
        % Global title
        % =========================

        if show_title

            title( ...
                tl, ...
                ['Experiment 1 — Single-Segment PMD | ', ...
                 'Bandwidth--DGD regime'], ...
                'FontSize', style.title.font_size, ...
                'FontWeight', style.title.font_weight, ...
                'Interpreter', style.title.interpreter);

        end

    end


    % =========================
    % Local panel builder
    % =========================

    function plot_regime_panel( ...
            ax, metric_map, panel_title, colorbar_label, color_limits)
    % PLOT_REGIME_PANEL  Plot one bandwidth--DGD physical regime map.
    %
    % Input:
    %   ax             - Target axes handle.
    %   metric_map     - N_sigma-by-N_DGD metric matrix.
    %   panel_title    - Panel title.
    %   colorbar_label - LaTeX colorbar label.
    %   color_limits   - Two-element color-axis range.
    %
    % Output:
    %   None

        % =========================
        % Heat map
        % =========================

        imagesc( ...
            ax, ...
            dgd_ps, ...
            sigma_frequency_ghz, ...
            metric_map);

        set(ax, ...
            'YDir', 'normal');

        colormap( ...
            ax, ...
            style.heatmap.colormap);

        clim( ...
            ax, ...
            color_limits);

        hold(ax, 'on');


        % =========================
        % Dimensionless xi = 1 contour
        % =========================

        xi_min = ...
            min(normalized_pmd_strength, [], 'all');

        xi_max = ...
            max(normalized_pmd_strength, [], 'all');

        if xi_min <= 1 && xi_max >= 1

            contour( ...
                ax, ...
                dgd_ps, ...
                sigma_frequency_ghz, ...
                normalized_pmd_strength, ...
                [1, 1], ...
                '--', ...
                'LineWidth', style.lines.width_secondary, ...
                'Color', palette.black);

        end


        % =========================
        % Axes
        % =========================

        xlabel( ...
            ax, ...
            '$\mathrm{DGD}\;[\mathrm{ps}]$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel( ...
            ax, ...
            '$\sigma_f\;[\mathrm{GHz}]$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title( ...
            ax, ...
            panel_title, ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

        xlim( ...
            ax, ...
            [min(dgd_ps), max(dgd_ps)]);

        ylim( ...
            ax, ...
            [ ...
                min(sigma_frequency_ghz), ...
                max(sigma_frequency_ghz) ...
            ]);

        grid( ...
            ax, ...
            style.axes.grid);

        box( ...
            ax, ...
            style.axes.box);

        set( ...
            ax, ...
            'FontSize', style.axes.font_size, ...
            'LineWidth', style.axes.line_width, ...
            'TickLabelInterpreter', ...
                style.axes.tick_label_interpreter, ...
            'Layer', style.axes.layer);


        % =========================
        % Colorbar
        % =========================

        cb = colorbar(ax);

        cb.TickLabelInterpreter = ...
            style.axes.tick_label_interpreter;

        cb.FontSize = ...
            style.labels.font_size;

        cb.Label.String = ...
            colorbar_label;

        cb.Label.Interpreter = ...
            style.labels.interpreter;

        cb.Label.FontSize = ...
            style.labels.font_size_axis;

    end

end