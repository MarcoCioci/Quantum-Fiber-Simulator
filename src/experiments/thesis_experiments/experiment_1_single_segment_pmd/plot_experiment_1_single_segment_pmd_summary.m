function fig = plot_experiment_1_single_segment_pmd_regime_map( ...
        results_experiment_1, do_save)
% PLOT_EXPERIMENT_1_SINGLE_SEGMENT_PMD_REGIME_MAP
% Plot bandwidth--DGD regime maps for single-segment PMD.
%
% Objective:
%   Visualize the physical parameter dependence of the reduced
%   polarization state generated in Experiment 1.
%
%   The horizontal axis is the physical differential group delay
%
%       DGD [ps],
%
%   while the vertical axis is the marginal photon spectral standard
%   deviation expressed as ordinary-frequency bandwidth
%
%       sigma_f = sigma_omega / (2*pi) [GHz].
%
%   Four quantities are displayed:
%
%       1) concurrence C,
%       2) global purity gamma,
%       3) Bell-state fidelity F,
%       4) maximal CHSH parameter S_max.
%
%   The dimensionless PMD strength
%
%       xi = sigma_omega * DGD
%
%   governs the analytical single-segment model. When the sampled parameter
%   range contains xi = 1, the corresponding contour is superimposed as a
%   dashed line to identify the transition region in which the PMD delay
%   becomes comparable with the inverse spectral bandwidth.
%
% Input:
%   results_experiment_1 - Structure produced by
%                          run_experiment_1_single_segment_pmd.
%
%   do_save              - Optional logical scalar. If true, export the
%                          regime-map figure as a PNG file.
%                          Default: false.
%
% Output:
%   fig                  - Handle to the Experiment 1 figure window.
%
% Notes:
%   The plotted quantities are the numerical results of the complete
%   frequency-resolved propagation and spectral trace.
%
%   Analytical-versus-numerical agreement is intentionally not shown in
%   this figure. That comparison belongs to the numerical validation and
%   Experiment 1 summary plots, whereas this figure is intended to expose
%   the physical bandwidth--DGD parameter regimes.
%
%   Matrix convention:
%
%       row    -> sigma_omega,
%       column -> DGD.
%
%   The same local plot builder is used both for the interactive tab and
%   for the standalone exported figure.

    % =========================
    % Default input handling
    % =========================

    if nargin < 1 || nargin > 2
        error( ...
            'plot_experiment_1_single_segment_pmd_regime_map:InvalidNumInputs', ...
            'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = false;
    end


    % =========================
    % Robustness checks
    % =========================

    if ~islogical(do_save) || ~isscalar(do_save)
        error( ...
            'plot_experiment_1_single_segment_pmd_regime_map:InvalidDoSave', ...
            'do_save must be a logical scalar.');
    end

    if ~isstruct(results_experiment_1)
        error( ...
            'plot_experiment_1_single_segment_pmd_regime_map:InvalidInputType', ...
            'results_experiment_1 must be a structure.');
    end

    check_required_fields( ...
        results_experiment_1, ...
        {'parameters', 'numerical'}, ...
        'plot_experiment_1_single_segment_pmd_regime_map:MissingMainField');

    if ~isstruct(results_experiment_1.parameters)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidParametersStructure'], ...
            'results_experiment_1.parameters must be a structure.');
    end

    if ~isstruct(results_experiment_1.numerical)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidNumericalStructure'], ...
            'results_experiment_1.numerical must be a structure.');
    end

    check_required_fields( ...
        results_experiment_1.parameters, ...
        { ...
            'dgd_values', ...
            'sigma_omega_values', ...
            'normalized_pmd_strength' ...
        }, ...
        ['plot_experiment_1_single_segment_pmd_regime_map:', ...
         'MissingParameterField']);

    check_required_fields( ...
        results_experiment_1.numerical, ...
        { ...
            'purity', ...
            'fidelity', ...
            'concurrence', ...
            'chsh_max' ...
        }, ...
        ['plot_experiment_1_single_segment_pmd_regime_map:', ...
         'MissingNumericalField']);


    % =========================
    % Extract data
    % =========================

    dgd_values = ...
        results_experiment_1.parameters.dgd_values(:).';

    sigma_omega_values = ...
        results_experiment_1.parameters.sigma_omega_values(:);

    normalized_pmd_strength = ...
        results_experiment_1.parameters.normalized_pmd_strength;

    purity = ...
        results_experiment_1.numerical.purity;

    fidelity = ...
        results_experiment_1.numerical.fidelity;

    concurrence = ...
        results_experiment_1.numerical.concurrence;

    chsh_max = ...
        results_experiment_1.numerical.chsh_max;


    % =========================
    % Data validation
    % =========================

    if ~isnumeric(dgd_values) || ...
            ~isreal(dgd_values) || ...
            isempty(dgd_values) || ...
            any(~isfinite(dgd_values), 'all')
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidDGDValues'], ...
            'DGD values must be finite real numeric values.');
    end

    if any(dgd_values < 0, 'all')
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'NegativeDGDValues'], ...
            'DGD values must be non-negative.');
    end

    if ~isnumeric(sigma_omega_values) || ...
            ~isreal(sigma_omega_values) || ...
            isempty(sigma_omega_values) || ...
            any(~isfinite(sigma_omega_values), 'all')
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidSigmaOmegaValues'], ...
            'sigma_omega_values must contain finite real numeric values.');
    end

    if any(sigma_omega_values <= 0, 'all')
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InvalidSigmaOmegaRange'], ...
            'sigma_omega_values must contain only strictly positive values.');
    end

    num_dgd_values = ...
        numel(dgd_values);

    num_sigma_values = ...
        numel(sigma_omega_values);

    if num_dgd_values < 2 || num_sigma_values < 2
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'InsufficientMapResolution'], ...
            ['A regime map requires at least two DGD values and two ', ...
             'sigma_omega values.']);
    end

    expected_map_size = ...
        [num_sigma_values, num_dgd_values];

    map_names = { ...
        'normalized_pmd_strength', ...
        'purity', ...
        'fidelity', ...
        'concurrence', ...
        'chsh_max' ...
    };

    map_values = { ...
        normalized_pmd_strength, ...
        purity, ...
        fidelity, ...
        concurrence, ...
        chsh_max ...
    };

    for i_map = 1:numel(map_values)

        current_map = map_values{i_map};

        if ~isnumeric(current_map) || ...
                ~isreal(current_map) || ...
                ~isequal(size(current_map), expected_map_size)
            error( ...
                ['plot_experiment_1_single_segment_pmd_regime_map:', ...
                 'InvalidMapSize'], ...
                ['%s must be a real numeric N_sigma-by-N_DGD matrix.'], ...
                map_names{i_map});
        end

        if any(~isfinite(current_map), 'all')
            error( ...
                ['plot_experiment_1_single_segment_pmd_regime_map:', ...
                 'InvalidMapValues'], ...
                '%s must contain only finite values.', ...
                map_names{i_map});
        end

    end


    % =========================
    % Physical plotting units
    % =========================

    % Convert DGD from seconds to picoseconds.

    dgd_ps = ...
        dgd_values * 1e12;

    % Convert angular-frequency standard deviation sigma_omega [rad/s]
    % into ordinary-frequency standard deviation sigma_f [GHz]:
    %
    %   sigma_f = sigma_omega / (2*pi).

    sigma_frequency_ghz = ...
        sigma_omega_values / (2 * pi * 1e9);


    % =========================
    % Axis validation
    % =========================

    if any(diff(dgd_ps) <= 0)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'NonIncreasingDGDGrid'], ...
            'dgd_values must be strictly increasing for the regime map.');
    end

    if any(diff(sigma_frequency_ghz) <= 0)
        error( ...
            ['plot_experiment_1_single_segment_pmd_regime_map:', ...
             'NonIncreasingBandwidthGrid'], ...
            ['sigma_omega_values must be strictly increasing for the ', ...
             'regime map.']);
    end


    % =========================
    % Plot style
    % =========================

    style = get_plot_style();
    palette = get_plot_palette();


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = get_experiment_figure_tab( ...
        style.figure.experiment_1_id, ...
        'Bandwidth-DGD regime map', ...
        'Experiment 1 — Single-Segment PMD', ...
        style);

    build_plot(tab, false);

    set(fig, ...
        'Visible', style.figure.visible_after_build);


    % =========================
    % Save (conditional)
    % =========================

    if do_save

        % Determine the project root from the location of this function:
        %
        %   project_root/
        %       src/
        %           experiments/
        %               thesis_experiments/
        %                   experiment_1_single_segment_pmd/
        %                       this_file.m

        experiment_folder = ...
            fileparts(mfilename('fullpath'));

        thesis_experiments_folder = ...
            fileparts(experiment_folder);

        experiments_folder = ...
            fileparts(thesis_experiments_folder);

        src_folder = ...
            fileparts(experiments_folder);

        project_root = ...
            fileparts(src_folder);

        output_folder = ...
            fullfile(project_root, 'images', 'experiment_1');

        output_path = ...
            fullfile( ...
                output_folder, ...
                'experiment_1_single_segment_pmd_regime_map.png');

        export_plot( ...
            output_path, ...
            @(parent) build_plot(parent, false), ...
            style);

    end


    % =========================
    % Local plot builder
    % =========================

    function layout = build_plot(parent_container, show_title)
    % BUILD_PLOT  Construct the complete Experiment 1 regime-map figure.
    %
    % Objective:
    %   Build the four-panel bandwidth--DGD map inside an arbitrary parent
    %   container so that exactly the same plotting code is used for the
    %   interactive figure and standalone export.
    %
    % Input:
    %   parent_container - Figure or tab receiving the tiled layout.
    %   show_title       - Logical flag controlling the global title.
    %
    % Output:
    %   layout           - Tiled-layout handle.

        if nargin < 2
            show_title = false;
        end

        layout = tiledlayout( ...
            parent_container, ...
            2, ...
            2, ...
            'TileSpacing', style.layout.tile_spacing, ...
            'Padding', style.layout.padding);


        % =====================================================
        % Panel 1: concurrence
        % =====================================================

        ax = nexttile(layout);

        plot_regime_panel( ...
            ax, ...
            concurrence, ...
            '$C$', ...
            'Concurrence', ...
            [0, 1]);


        % =====================================================
        % Panel 2: purity
        % =====================================================

        ax = nexttile(layout);

        plot_regime_panel( ...
            ax, ...
            purity, ...
            '$\gamma = \mathrm{Tr}(\rho^2)$', ...
            'Global purity', ...
            [0.5, 1]);


        % =====================================================
        % Panel 3: Bell-state fidelity
        % =====================================================

        ax = nexttile(layout);

        plot_regime_panel( ...
            ax, ...
            fidelity, ...
            '$F_{\Psi^+}$', ...
            'Bell-state fidelity', ...
            [0.5, 1]);


        % =====================================================
        % Panel 4: maximal CHSH parameter
        % =====================================================

        ax = nexttile(layout);

        plot_regime_panel( ...
            ax, ...
            chsh_max, ...
            '$S_{\max}$', ...
            'Maximal CHSH parameter', ...
            [2, 2 * sqrt(2)]);


        % =========================
        % Global title
        % =========================

        if show_title

            title( ...
                layout, ...
                ['Experiment 1 — Single-Segment PMD: ', ...
                 'Bandwidth--DGD Regime'], ...
                'FontSize', style.title.font_size, ...
                'FontWeight', style.title.font_weight, ...
                'Interpreter', style.title.interpreter);

        end

    end


    % =========================
    % Local panel builder
    % =========================

    function plot_regime_panel( ...
            ax, metric_map, colorbar_label, panel_title, color_limits)
    % PLOT_REGIME_PANEL  Plot one physical bandwidth--DGD metric map.
    %
    % Objective:
    %   Plot one N_sigma-by-N_DGD metric as a two-dimensional map and,
    %   when present in the parameter range, superimpose the xi = 1
    %   contour.
    %
    % Input:
    %   ax             - Target axes.
    %   metric_map     - N_sigma-by-N_DGD numerical metric matrix.
    %   colorbar_label - LaTeX colorbar label.
    %   panel_title    - Panel title.
    %   color_limits   - Two-element color-axis limits.
    %
    % Output:
    %   None

        imagesc( ...
            ax, ...
            dgd_ps, ...
            sigma_frequency_ghz, ...
            metric_map);

        set(ax, ...
            'YDir', 'normal', ...
            'FontSize', style.axes.font_size, ...
            'LineWidth', style.axes.line_width, ...
            'Box', style.axes.box, ...
            'Layer', style.axes.layer, ...
            'TickLabelInterpreter', ...
                style.axes.tick_label_interpreter);

        hold(ax, 'on');

        colormap(ax, parula(256));

        clim(ax, color_limits);

        xlim(ax, ...
            [min(dgd_ps), max(dgd_ps)]);

        ylim(ax, ...
            [min(sigma_frequency_ghz), ...
             max(sigma_frequency_ghz)]);


        % =========================
        % xi = 1 reference contour
        % =========================

        xi_min = ...
            min(normalized_pmd_strength, [], 'all');

        xi_max = ...
            max(normalized_pmd_strength, [], 'all');

        if xi_min <= 1 && xi_max >= 1

            contour( ...
                ax, ...
                dgd_ps, ...
                sigma_frequency_ghz, ...
                normalized_pmd_strength, ...
                [1, 1], ...
                '--', ...
                'LineWidth', 1.6, ...
                'Color', palette.black);

        end


        % =========================
        % Axes labels
        % =========================

        xlabel( ...
            ax, ...
            '$\mathrm{DGD}\;[\mathrm{ps}]$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel( ...
            ax, ...
            '$\sigma_f=\sigma_\omega/(2\pi)\;[\mathrm{GHz}]$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title( ...
            ax, ...
            panel_title, ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);


        % =========================
        % Colorbar
        % =========================

        cb = colorbar(ax);

        cb.TickLabelInterpreter = ...
            style.axes.tick_label_interpreter;

        cb.FontSize = ...
            style.labels.font_size;

        cb.Label.String = ...
            colorbar_label;

        cb.Label.Interpreter = ...
            style.labels.interpreter;

        cb.Label.FontSize = ...
            style.labels.font_size_axis;

    end

end