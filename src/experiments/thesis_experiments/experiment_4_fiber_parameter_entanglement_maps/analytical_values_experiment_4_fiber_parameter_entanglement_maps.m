function analytics = ...
        analytical_values_experiment_4_fiber_parameter_entanglement_maps( ...
            fiber_length_values_km, ...
            pmd_coefficient_values_ps_sqrt_km, ...
            sigma_omega, ...
            concurrence_quality_threshold)
% ANALYTICAL_VALUES_EXPERIMENT_4_FIBER_PARAMETER_ENTANGLEMENT_MAPS
% Build first-order statistical references for Experiment 4.
%
% Objective:
%   Provide an analytically transparent random-walk reference for the
%   engineering parameter maps.
%
%   The fiber-level RMS DGD is modeled as
%
%       tau_RMS = D_PMD * sqrt(L).
%
%   In the many-segment isotropic first-order limit, the PMD-vector
%   components are approximated as independent zero-mean Gaussian random
%   variables with equal variance tau_RMS^2 / 3. The DGD magnitude is then
%   Maxwell distributed.
%
%   For a fixed first-order DGD magnitude tau and a Gaussian photon
%   marginal spectrum with standard deviation sigma_omega, the concurrence
%   is
%
%       C(tau) = exp[-0.5 * sigma_omega^2 * tau^2].
%
%   Averaging over the Maxwell distribution gives
%
%       E[C]
%       =
%       (1 + sigma_omega^2 * tau_RMS^2 / 3)^(-3/2).
%
% Input:
%   fiber_length_values_km - Fiber lengths [km], non-negative vector.
%   pmd_coefficient_values_ps_sqrt_km
%                          - PMD coefficients [ps / sqrt(km)].
%   sigma_omega            - Marginal angular-frequency standard deviation
%                            [rad/s].
%   concurrence_quality_threshold
%                          - Operational concurrence-quality threshold.
%
% Output:
%   analytics - Structure containing RMS DGD, normalized PMD strength,
%               first-order mean concurrence, first-order threshold
%               survival probability, and critical-length prediction.
%
% Notes:
%   These are first-order statistical references, not exact predictions for
%   the complete noncommuting finite-bandwidth segmented model. Deviations
%   are therefore physically informative rather than automatically treated
%   as numerical errors.

    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 4
        error( ...
            ['analytical_values_experiment_4_fiber_parameter_', ...
             'entanglement_maps:InvalidNumInputs'], ...
            ['Expected exactly 4 input arguments: fiber lengths, ', ...
             'PMD coefficients, sigma_omega, and concurrence threshold.']);
    end

    if ~isnumeric(fiber_length_values_km) || ...
            ~isreal(fiber_length_values_km) || ...
            ~isvector(fiber_length_values_km) || ...
            isempty(fiber_length_values_km) || ...
            any(~isfinite(fiber_length_values_km), 'all') || ...
            any(fiber_length_values_km < 0, 'all')
        error( ...
            ['analytical_values_experiment_4_fiber_parameter_', ...
             'entanglement_maps:InvalidFiberLengths'], ...
            ['fiber_length_values_km must contain finite ', ...
             'non-negative values.']);
    end

    if ~isnumeric(pmd_coefficient_values_ps_sqrt_km) || ...
            ~isreal(pmd_coefficient_values_ps_sqrt_km) || ...
            ~isvector(pmd_coefficient_values_ps_sqrt_km) || ...
            isempty(pmd_coefficient_values_ps_sqrt_km) || ...
            any(~isfinite( ...
                pmd_coefficient_values_ps_sqrt_km), 'all') || ...
            any(pmd_coefficient_values_ps_sqrt_km < 0, 'all')
        error( ...
            ['analytical_values_experiment_4_fiber_parameter_', ...
             'entanglement_maps:InvalidPMDCoefficients'], ...
            ['pmd_coefficient_values_ps_sqrt_km must contain finite ', ...
             'non-negative values.']);
    end

    if ~isnumeric(sigma_omega) || ...
            ~isscalar(sigma_omega) || ...
            ~isreal(sigma_omega) || ...
            ~isfinite(sigma_omega) || ...
            sigma_omega <= 0
        error( ...
            ['analytical_values_experiment_4_fiber_parameter_', ...
             'entanglement_maps:InvalidSigmaOmega'], ...
            'sigma_omega must be a positive finite real scalar.');
    end

    if ~isnumeric(concurrence_quality_threshold) || ...
            ~isscalar(concurrence_quality_threshold) || ...
            ~isreal(concurrence_quality_threshold) || ...
            ~isfinite(concurrence_quality_threshold) || ...
            concurrence_quality_threshold <= 0 || ...
            concurrence_quality_threshold > 1
        error( ...
            ['analytical_values_experiment_4_fiber_parameter_', ...
             'entanglement_maps:InvalidConcurrenceThreshold'], ...
            'The concurrence threshold must satisfy 0 < C_quality <= 1.');
    end


    % =========================
    % Input normalization
    % =========================

    fiber_length_values_km = ...
        fiber_length_values_km(:).';

    pmd_coefficient_values_ps_sqrt_km = ...
        pmd_coefficient_values_ps_sqrt_km(:);


    % =========================
    % Fiber-level RMS DGD
    % =========================

    pmd_coefficient_s_sqrt_km = ...
        1e-12 * ...
        pmd_coefficient_values_ps_sqrt_km;

    rms_total_dgd_s = ...
        pmd_coefficient_s_sqrt_km * ...
        sqrt(fiber_length_values_km);

    xi_rms = ...
        sigma_omega * ...
        rms_total_dgd_s;


    % =========================
    % Mean concurrence reference
    % =========================

    mean_concurrence_first_order = ...
        (1 + xi_rms .^ 2 / 3) .^ (-3/2);


    % =========================
    % Threshold probability
    % =========================

    % C(tau) >= C_quality implies tau <= tau_quality.

    if concurrence_quality_threshold == 1
        tau_quality_s = 0;
    else
        tau_quality_s = ...
            sqrt( ...
                -2 * log(concurrence_quality_threshold)) / ...
            sigma_omega;
    end

    quality_probability_first_order = ...
        ones(size(rms_total_dgd_s));

    nonzero_rms = ...
        rms_total_dgd_s > 0;

    maxwell_scale = ...
        rms_total_dgd_s(nonzero_rms) / sqrt(3);

    normalized_threshold = ...
        tau_quality_s ./ maxwell_scale;

    quality_probability_first_order(nonzero_rms) = ...
        erf(normalized_threshold / sqrt(2)) - ...
        sqrt(2 / pi) .* ...
        normalized_threshold .* ...
        exp(-0.5 * normalized_threshold .^ 2);

    quality_probability_first_order = ...
        min( ...
            max(quality_probability_first_order, 0), ...
            1);


    % =========================
    % Critical-length reference
    % =========================

    num_pmd_values = ...
        numel(pmd_coefficient_values_ps_sqrt_km);

    critical_length_mean_concurrence_km = ...
        inf(num_pmd_values, 1);

    threshold_factor = ...
        3 * ...
        ( ...
            concurrence_quality_threshold ^ (-2/3) - ...
            1);

    for i_pmd = 1:num_pmd_values

        pmd_coefficient_current_s_sqrt_km = ...
            pmd_coefficient_s_sqrt_km(i_pmd);

        if pmd_coefficient_current_s_sqrt_km == 0
            continue;
        end

        critical_length_mean_concurrence_km(i_pmd) = ...
            threshold_factor / ...
            ( ...
                sigma_omega ^ 2 * ...
                pmd_coefficient_current_s_sqrt_km ^ 2);

    end


    % =========================
    % Store results
    % =========================

    analytics = struct();

    analytics.fiber_length_values_km = ...
        fiber_length_values_km;

    analytics.pmd_coefficient_values_ps_sqrt_km = ...
        pmd_coefficient_values_ps_sqrt_km;

    analytics.sigma_omega = ...
        sigma_omega;

    analytics.concurrence_quality_threshold = ...
        concurrence_quality_threshold;

    analytics.rms_total_dgd_s = ...
        rms_total_dgd_s;

    analytics.rms_total_dgd_ps = ...
        1e12 * rms_total_dgd_s;

    analytics.xi_rms = ...
        xi_rms;

    analytics.mean_concurrence_first_order = ...
        mean_concurrence_first_order;

    analytics.tau_quality_s = ...
        tau_quality_s;

    analytics.quality_probability_first_order = ...
        quality_probability_first_order;

    analytics.critical_length_mean_concurrence_km = ...
        critical_length_mean_concurrence_km;

end
