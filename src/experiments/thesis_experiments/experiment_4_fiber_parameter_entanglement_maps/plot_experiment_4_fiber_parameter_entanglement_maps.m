function fig = plot_experiment_4_fiber_parameter_entanglement_maps( ...
        results_experiment_4, do_save)
% PLOT_EXPERIMENT_4_FIBER_PARAMETER_ENTANGLEMENT_MAPS
% Plot Experiment 4 concurrence and entanglement-quality maps.
%
% Objective:
%   Visualize:
%
%       1. mean concurrence over fiber length and PMD coefficient;
%       2. probability that one fiber realization satisfies C >= C_quality;
%       3. threshold crossing length versus PMD coefficient.
%
% Input:
%   results_experiment_4 - Validated Experiment 4 result structure.
%   do_save              - Logical scalar controlling figure export.
%
% Output:
%   fig - Handle to the Experiment 4 figure window.
%
% Notes:
%   The operational concurrence threshold is shown explicitly on all
%   relevant plots. It is a quality target, not the C = 0 separability
%   boundary.
%
%   Each tab is rebuilt independently during export through export_plot,
%   following the repository plotting pipeline.

    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 2
        error( ...
            ['plot_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidNumInputs'], ...
            ['Expected exactly 2 input arguments: ', ...
             'results_experiment_4 and do_save.']);
    end

    if ~isstruct(results_experiment_4)
        error( ...
            ['plot_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidResultsType'], ...
            'results_experiment_4 must be a structure.');
    end

    if ~(islogical(do_save) && isscalar(do_save))
        error( ...
            ['plot_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end

    required_fields = { ...
        'parameters', ...
        'maps', ...
        'quality', ...
        'analytical'};

    for i_field = 1:numel(required_fields)

        field_name = ...
            required_fields{i_field};

        if ~isfield(results_experiment_4, field_name)
            error( ...
                ['plot_experiment_4_fiber_parameter_entanglement_maps:', ...
                 'MissingField'], ...
                'Missing required field "%s".', ...
                field_name);
        end

    end

    parameters = ...
        results_experiment_4.parameters;

    maps = ...
        results_experiment_4.maps;

    quality = ...
        results_experiment_4.quality;

    analytical = ...
        results_experiment_4.analytical;

    required_parameter_fields = { ...
        'fiber_length_values_km', ...
        'pmd_coefficient_values_ps_sqrt_km', ...
        'concurrence_quality_threshold'};

    required_map_fields = { ...
        'mean_concurrence'};

    required_quality_fields = { ...
        'realization_pass_probability', ...
        'critical_length_from_mean_km'};

    required_analytical_fields = { ...
        'mean_concurrence_first_order', ...
        'quality_probability_first_order', ...
        'critical_length_mean_concurrence_km'};

    check_fields( ...
        parameters, ...
        required_parameter_fields, ...
        'parameters');

    check_fields( ...
        maps, ...
        required_map_fields, ...
        'maps');

    check_fields( ...
        quality, ...
        required_quality_fields, ...
        'quality');

    check_fields( ...
        analytical, ...
        required_analytical_fields, ...
        'analytical');


    % =========================
    % Data extraction
    % =========================

    fiber_length_values_km = ...
        parameters.fiber_length_values_km(:).';

    pmd_coefficient_values_ps_sqrt_km = ...
        parameters.pmd_coefficient_values_ps_sqrt_km(:);

    concurrence_threshold = ...
        parameters.concurrence_quality_threshold;

    mean_concurrence = ...
        maps.mean_concurrence;

    quality_probability = ...
        quality.realization_pass_probability;

    mean_concurrence_first_order = ...
        analytical.mean_concurrence_first_order;

    quality_probability_first_order = ...
        analytical.quality_probability_first_order;

    critical_length_numerical_km = ...
        quality.critical_length_from_mean_km(:);

    critical_length_first_order_km = ...
        analytical.critical_length_mean_concurrence_km(:);

    expected_map_size = ...
        [ ...
            numel(pmd_coefficient_values_ps_sqrt_km), ...
            numel(fiber_length_values_km) ...
        ];

    validate_map( ...
        mean_concurrence, ...
        expected_map_size, ...
        'maps.mean_concurrence');

    validate_map( ...
        quality_probability, ...
        expected_map_size, ...
        'quality.realization_pass_probability');

    validate_map( ...
        mean_concurrence_first_order, ...
        expected_map_size, ...
        'analytical.mean_concurrence_first_order');

    validate_map( ...
        quality_probability_first_order, ...
        expected_map_size, ...
        'analytical.quality_probability_first_order');


    % =========================
    % Plot style
    % =========================

    palette = ...
        get_plot_palette();

    style = ...
        get_plot_style();

    experiment_figure_id = 104;

    if isfield(style, 'figure') && ...
            isfield(style.figure, 'experiment_4_id')
        experiment_figure_id = ...
            style.figure.experiment_4_id;
    end

    figure_visible_after_build = 'on';

    if isfield(style, 'figure') && ...
            isfield(style.figure, 'visible_after_build')
        figure_visible_after_build = ...
            style.figure.visible_after_build;
    end

    tile_spacing = 'compact';
    padding = 'compact';

    if isfield(style, 'layout') && ...
            isfield(style.layout, 'tile_spacing')
        tile_spacing = ...
            style.layout.tile_spacing;
    end

    if isfield(style, 'layout') && ...
            isfield(style.layout, 'padding')
        padding = ...
            style.layout.padding;
    end

    line_width = 2.0;

    if isfield(style, 'lines') && ...
            isfield(style.lines, 'width_main')
        line_width = ...
            style.lines.width_main;
    end

    axes_font_size = 15;

    if isfield(style, 'axes') && ...
            isfield(style.axes, 'font_size')
        axes_font_size = ...
            style.axes.font_size;
    end

    label_font_size = 18;

    if isfield(style, 'labels') && ...
            isfield(style.labels, 'font_size_axis')
        label_font_size = ...
            style.labels.font_size_axis;
    end

    tick_interpreter = 'latex';

    if isfield(style, 'axes') && ...
            isfield(style.axes, 'tick_label_interpreter')
        tick_interpreter = ...
            style.axes.tick_label_interpreter;
    end


    % =========================
    % Mean-concurrence tab
    % =========================

    [fig, tab_concurrence] = ...
        get_experiment_figure_tab( ...
            experiment_figure_id, ...
            'Mean concurrence', ...
            'Experiment 4 - Fiber Parameter Entanglement Maps', ...
            style);

    build_mean_concurrence_plot( ...
        tab_concurrence, ...
        false);

    set( ...
        fig, ...
        'Visible', ...
        figure_visible_after_build);


    % =========================
    % Quality-probability tab
    % =========================

    [fig, tab_probability] = ...
        get_experiment_figure_tab( ...
            experiment_figure_id, ...
            'Quality probability', ...
            'Experiment 4 - Fiber Parameter Entanglement Maps', ...
            style);

    build_quality_probability_plot( ...
        tab_probability, ...
        false);

    set( ...
        fig, ...
        'Visible', ...
        figure_visible_after_build);


    % =========================
    % Critical-length tab
    % =========================

    [fig, tab_critical] = ...
        get_experiment_figure_tab( ...
            experiment_figure_id, ...
            'Threshold length', ...
            'Experiment 4 - Fiber Parameter Entanglement Maps', ...
            style);

    build_critical_length_plot( ...
        tab_critical, ...
        false);

    set( ...
        fig, ...
        'Visible', ...
        figure_visible_after_build);


    % =========================
    % Save
    % =========================

    if do_save

        output_folder = ...
            fullfile( ...
                pwd, ...
                'images', ...
                'experiment_4');

        export_plot( ...
            fullfile( ...
                output_folder, ...
                'experiment_4_mean_concurrence_map.png'), ...
            @(parent) build_mean_concurrence_plot( ...
                parent, ...
                false), ...
            style);

        export_plot( ...
            fullfile( ...
                output_folder, ...
                'experiment_4_quality_probability_map.png'), ...
            @(parent) build_quality_probability_plot( ...
                parent, ...
                false), ...
            style);

        export_plot( ...
            fullfile( ...
                output_folder, ...
                'experiment_4_threshold_length.png'), ...
            @(parent) build_critical_length_plot( ...
                parent, ...
                false), ...
            style);

    end


    % =========================
    % Local plot builders
    % =========================

    function tl = build_mean_concurrence_plot( ...
            parent_container, show_title)

        tl = ...
            tiledlayout( ...
                parent_container, ...
                1, ...
                2, ...
                'TileSpacing', ...
                tile_spacing, ...
                'Padding', ...
                padding);

        ax_numeric = ...
            nexttile(tl);

        draw_map( ...
            ax_numeric, ...
            mean_concurrence, ...
            '$\overline{C}$', ...
            [0, 1]);

        hold(ax_numeric, 'on');

        draw_threshold_contour( ...
            ax_numeric, ...
            mean_concurrence, ...
            concurrence_threshold, ...
            palette.metric_C, ...
            line_width);

        draw_critical_length_overlay( ...
            ax_numeric, ...
            critical_length_first_order_km, ...
            pmd_coefficient_values_ps_sqrt_km, ...
            palette.gray_dark, ...
            line_width);

        title( ...
            ax_numeric, ...
            'Numerical mean concurrence', ...
            'Interpreter', ...
            'none');

        ax_analytical = ...
            nexttile(tl);

        draw_map( ...
            ax_analytical, ...
            mean_concurrence_first_order, ...
            '$\mathbb{E}[C]_{\mathrm{FO}}$', ...
            [0, 1]);

        hold(ax_analytical, 'on');

        draw_threshold_contour( ...
            ax_analytical, ...
            mean_concurrence_first_order, ...
            concurrence_threshold, ...
            palette.metric_C, ...
            line_width);

        title( ...
            ax_analytical, ...
            'First-order random-walk reference', ...
            'Interpreter', ...
            'none');

        if show_title
            title( ...
                tl, ...
                sprintf( ...
                    'Experiment 4 - Concurrence maps | C_{quality} = %.2f', ...
                    concurrence_threshold), ...
                'Interpreter', ...
                'tex');
        end

    end


    function tl = build_quality_probability_plot( ...
            parent_container, show_title)

        tl = ...
            tiledlayout( ...
                parent_container, ...
                1, ...
                2, ...
                'TileSpacing', ...
                tile_spacing, ...
                'Padding', ...
                padding);

        ax_numeric = ...
            nexttile(tl);

        draw_map( ...
            ax_numeric, ...
            quality_probability, ...
            '$P(C \geq C_{\mathrm{quality}})$', ...
            [0, 1]);

        hold(ax_numeric, 'on');

        draw_threshold_contour( ...
            ax_numeric, ...
            quality_probability, ...
            0.5, ...
            palette.gray_dark, ...
            line_width);

        title( ...
            ax_numeric, ...
            'Numerical quality-survival probability', ...
            'Interpreter', ...
            'none');

        ax_analytical = ...
            nexttile(tl);

        draw_map( ...
            ax_analytical, ...
            quality_probability_first_order, ...
            '$P_{\mathrm{FO}}(C \geq C_{\mathrm{quality}})$', ...
            [0, 1]);

        hold(ax_analytical, 'on');

        draw_threshold_contour( ...
            ax_analytical, ...
            quality_probability_first_order, ...
            0.5, ...
            palette.gray_dark, ...
            line_width);

        title( ...
            ax_analytical, ...
            'First-order random-walk reference', ...
            'Interpreter', ...
            'none');

        if show_title
            title( ...
                tl, ...
                sprintf( ...
                    'Experiment 4 - Quality probability | C_{quality} = %.2f', ...
                    concurrence_threshold), ...
                'Interpreter', ...
                'tex');
        end

    end


    function tl = build_critical_length_plot( ...
            parent_container, show_title)

        tl = ...
            tiledlayout( ...
                parent_container, ...
                1, ...
                1, ...
                'TileSpacing', ...
                tile_spacing, ...
                'Padding', ...
                padding);

        ax = ...
            nexttile(tl);

        hold(ax, 'on');
        grid(ax, 'on');
        box(ax, 'on');

        finite_numerical = ...
            isfinite(critical_length_numerical_km);

        finite_first_order = ...
            isfinite(critical_length_first_order_km);

        plot( ...
            ax, ...
            pmd_coefficient_values_ps_sqrt_km(finite_numerical), ...
            critical_length_numerical_km(finite_numerical), ...
            'o-', ...
            'Color', ...
            palette.metric_C, ...
            'MarkerFaceColor', ...
            palette.metric_C, ...
            'LineWidth', ...
            line_width, ...
            'DisplayName', ...
            'Numerical mean-C crossing');

        plot( ...
            ax, ...
            pmd_coefficient_values_ps_sqrt_km(finite_first_order), ...
            critical_length_first_order_km(finite_first_order), ...
            '--', ...
            'Color', ...
            palette.gray_dark, ...
            'LineWidth', ...
            line_width, ...
            'DisplayName', ...
            'First-order reference');

        xlabel( ...
            ax, ...
            '$D_{\mathrm{PMD}}$ [ps/$\sqrt{\mathrm{km}}$]', ...
            'Interpreter', ...
            'latex', ...
            'FontSize', ...
            label_font_size);

        ylabel( ...
            ax, ...
            '$L_{\mathrm{crit}}$ [km]', ...
            'Interpreter', ...
            'latex', ...
            'FontSize', ...
            label_font_size);

        set( ...
            ax, ...
            'FontSize', ...
            axes_font_size, ...
            'TickLabelInterpreter', ...
            tick_interpreter);

        xlim( ...
            ax, ...
            [ ...
                min(pmd_coefficient_values_ps_sqrt_km), ...
                max(pmd_coefficient_values_ps_sqrt_km) ...
            ]);

        ylim( ...
            ax, ...
            [ ...
                0, ...
                max(fiber_length_values_km) ...
            ]);

        legend( ...
            ax, ...
            'Location', ...
            'northeast', ...
            'Interpreter', ...
            'none');

        title( ...
            ax, ...
            sprintf( ...
                'Operational threshold: C_{quality} = %.2f', ...
                concurrence_threshold), ...
            'Interpreter', ...
            'tex');

        if show_title
            title( ...
                tl, ...
                'Experiment 4 - Critical fiber length', ...
                'Interpreter', ...
                'none');
        end

    end


    function draw_map( ...
            ax, map_values, colorbar_label, color_limits)

        imagesc( ...
            ax, ...
            fiber_length_values_km, ...
            pmd_coefficient_values_ps_sqrt_km, ...
            map_values);

        set( ...
            ax, ...
            'YDir', ...
            'normal', ...
            'FontSize', ...
            axes_font_size, ...
            'TickLabelInterpreter', ...
            tick_interpreter);

        xlabel( ...
            ax, ...
            '$L$ [km]', ...
            'Interpreter', ...
            'latex', ...
            'FontSize', ...
            label_font_size);

        ylabel( ...
            ax, ...
            '$D_{\mathrm{PMD}}$ [ps/$\sqrt{\mathrm{km}}$]', ...
            'Interpreter', ...
            'latex', ...
            'FontSize', ...
            label_font_size);

        clim( ...
            ax, ...
            color_limits);

        if isfield(style, 'heatmap') && ...
                isfield(style.heatmap, 'colormap')
            colormap( ...
                ax, ...
                style.heatmap.colormap);
        else
            colormap( ...
                ax, ...
                parula(256));
        end

        cb = ...
            colorbar(ax);

        cb.Label.String = ...
            colorbar_label;

        cb.Label.Interpreter = ...
            'latex';

        cb.TickLabelInterpreter = ...
            tick_interpreter;

    end


    function draw_threshold_contour( ...
            ax, map_values, contour_level, ...
            contour_color, contour_line_width)

        map_minimum = ...
            min(map_values, [], 'all');

        map_maximum = ...
            max(map_values, [], 'all');

        if contour_level < map_minimum || ...
                contour_level > map_maximum
            return;
        end

        contour( ...
            ax, ...
            fiber_length_values_km, ...
            pmd_coefficient_values_ps_sqrt_km, ...
            map_values, ...
            [contour_level, contour_level], ...
            'Color', ...
            contour_color, ...
            'LineWidth', ...
            contour_line_width);

    end


    function draw_critical_length_overlay( ...
            ax, critical_length_km, pmd_values, ...
            line_color, overlay_line_width)

        finite_values = ...
            isfinite(critical_length_km) & ...
            critical_length_km >= ...
            min(fiber_length_values_km) & ...
            critical_length_km <= ...
            max(fiber_length_values_km);

        if ~any(finite_values)
            return;
        end

        plot( ...
            ax, ...
            critical_length_km(finite_values), ...
            pmd_values(finite_values), ...
            '--', ...
            'Color', ...
            line_color, ...
            'LineWidth', ...
            overlay_line_width);

    end

end


function check_fields(input_struct, required_fields, structure_name)
% CHECK_FIELDS  Verify required plot-input fields.

    for i_field = 1:numel(required_fields)

        field_name = ...
            required_fields{i_field};

        if ~isfield(input_struct, field_name)
            error( ...
                ['plot_experiment_4_fiber_parameter_entanglement_maps:', ...
                 'MissingNestedField'], ...
                'Missing required field "%s.%s".', ...
                structure_name, ...
                field_name);
        end

    end

end


function validate_map(map_values, expected_size, map_name)
% VALIDATE_MAP  Validate one Experiment 4 map before plotting.

    if ~isnumeric(map_values) || ...
            ~isequal(size(map_values), expected_size)
        error( ...
            ['plot_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidMapSize'], ...
            '%s must have size %d-by-%d.', ...
            map_name, ...
            expected_size(1), ...
            expected_size(2));
    end

    if any(~isfinite(map_values), 'all')
        error( ...
            ['plot_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidMapValues'], ...
            '%s must contain only finite values.', ...
            map_name);
    end

end
