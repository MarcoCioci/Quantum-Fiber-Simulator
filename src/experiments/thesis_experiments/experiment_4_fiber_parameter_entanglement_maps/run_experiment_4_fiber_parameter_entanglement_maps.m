function results_experiment_4 = run_experiment_4_fiber_parameter_entanglement_maps( ...
        do_plot, do_save)
% RUN_EXPERIMENT_4_FIBER_PARAMETER_ENTANGLEMENT_MAPS
% Build engineering entanglement-quality maps for a statistical PMD fiber.
%
% Objective:
%   Map the degradation of polarization entanglement as a function of
%   physically interpretable fiber parameters:
%
%       fiber length L [km]
%       PMD coefficient D_PMD [ps / sqrt(km)].
%
%   The input state is
%
%       |Psi+> = (|01> + |10>) / sqrt(2).
%
%   Arm A is represented by a segmented birefringent fiber with independent
%   isotropic segment axes. Arm B is ideal. For each map point, the segment
%   DGD is selected so that the random-walk RMS total DGD satisfies
%
%       tau_RMS = D_PMD * sqrt(L),
%
%   after unit conversion from ps to s.
%
%   The primary output is the mean concurrence map. The experiment also
%   introduces an operational entanglement-quality threshold C_quality and
%   evaluates:
%
%       mean(C) >= C_quality,
%
%   together with the Monte Carlo survival probability
%
%       P(C >= C_quality).
%
% Input:
%   do_plot - Logical scalar controlling Experiment 4 plotting.
%   do_save - Logical scalar controlling figure export.
%
% Output:
%   results_experiment_4 - Structure containing physical and numerical
%                          parameters, Monte Carlo samples, statistical
%                          maps, threshold analysis, first-order analytical
%                          references, and numerical validation diagnostics.
%
% Notes:
%   All physical and numerical parameter choices intentionally reside in
%   this runner. main.m should only select Boolean execution/plot/save
%   switches.
%
%   C_quality is an engineering/operational quality criterion. It is not
%   the mathematical separability boundary. For two qubits, C > 0 denotes
%   entanglement, whereas C_quality selects a stronger target quality.
%
%   The same random segment-axis realizations are reused over the complete
%   parameter grid (common random numbers). This reduces Monte Carlo noise
%   when neighboring map points are compared.
%
%   Because arm B is ideal, the spectral trace can be evaluated exactly
%   from the marginal spectral weights of arm A:
%
%       rho_out
%       =
%       sum_k w_A(k)
%       [U_A(Omega_k) kron I] rho_in [U_A(Omega_k) kron I]^dagger.
%
%   A full two-dimensional reference evaluation with
%
%       pmd_frequency_resolved_states
%               ->
%       pmd_spectral_average_state
%
%   is performed at one map point to verify the optimized single-arm
%   evaluator against the already validated PMD pipeline.

    % =========================
    % Robustness checks
    % =========================

    if nargin ~= 2
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidNumInputs'], ...
            'Expected exactly 2 input arguments: do_plot and do_save.');
    end

    if ~(islogical(do_plot) && isscalar(do_plot))
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidDoPlot'], ...
            'do_plot must be a logical scalar.');
    end

    if ~(islogical(do_save) && isscalar(do_save))
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidDoSave'], ...
            'do_save must be a logical scalar.');
    end


    % =========================
    % Experiment parameters
    % =========================

    % Physical parameter map.
    %
    % These ranges are intentionally defined here rather than in main.m.
    % Change them here when the final thesis parameter range is selected.

    fiber_length_values_km = ...
        linspace(0, 250, 16);

    pmd_coefficient_values_ps_sqrt_km = ...
        linspace(0, 1.0, 17);

    % Source marginal angular-frequency standard deviation [rad/s].
    sigma_omega = 1.0e11;

    % Statistical segmented-fiber representation.
    num_segments = 20;
    num_realizations = 40;

    % Spectral discretization.
    num_frequency_points = 41;
    max_offset_factor = 6.0;

    % Reproducibility.
    random_seed = 104;

    % Operational entanglement-quality threshold.
    %
    % IMPORTANT:
    %   This value is a provisional engineering target, not a fundamental
    %   entanglement/separability threshold. It is kept as one explicit
    %   runner parameter so it can be changed after the thesis-level
    %   definition of "acceptable entanglement quality" is finalized.
    concurrence_quality_threshold = 0.80;

    validate_configuration( ...
        fiber_length_values_km, ...
        pmd_coefficient_values_ps_sqrt_km, ...
        sigma_omega, ...
        num_segments, ...
        num_realizations, ...
        num_frequency_points, ...
        max_offset_factor, ...
        random_seed, ...
        concurrence_quality_threshold);


    % =========================
    % Input normalization
    % =========================

    fiber_length_values_km = ...
        fiber_length_values_km(:).';

    pmd_coefficient_values_ps_sqrt_km = ...
        pmd_coefficient_values_ps_sqrt_km(:);

    num_length_values = ...
        numel(fiber_length_values_km);

    num_pmd_values = ...
        numel(pmd_coefficient_values_ps_sqrt_km);


    % =========================
    % Reproducible RNG state
    % =========================

    previous_rng_state = rng;

    rng_cleanup = onCleanup( ...
        @() rng(previous_rng_state));

    rng(random_seed, 'twister');


    % =========================
    % Input polarization state
    % =========================

    psi_input = ...
        bell_state('psi_plus');

    rho_input = ...
        state_to_density_matrix(psi_input);

    identity_B = eye(2);


    % =========================
    % Spectrum
    % =========================

    sigma_sum = ...
        sqrt(2) * sigma_omega;

    sigma_difference = ...
        sqrt(2) * sigma_omega;

    max_frequency_offset = ...
        max_offset_factor * sigma_omega;

    [omega_offsets, delta_omega] = ...
        pmd_frequency_grid( ...
            num_frequency_points, ...
            max_frequency_offset);

    spectral_weights = ...
        pmd_joint_spectral_weights( ...
            omega_offsets, ...
            omega_offsets, ...
            sigma_sum, ...
            sigma_difference);

    marginal_weights_A = ...
        sum(spectral_weights, 2);

    marginal_weights_A = ...
        marginal_weights_A / sum(marginal_weights_A);


    % =========================
    % Ideal arm B
    % =========================

    phases_B = 0;
    dgds_B = 0;
    axes_B = [0, 0, 1];


    % =========================
    % Common fiber realizations
    % =========================

    axes_realizations = ...
        zeros(num_segments, 3, num_realizations);

    random_walk_axis_sum_norm = ...
        zeros(1, num_realizations);

    for i_realization = 1:num_realizations

        axes_current = ...
            sample_isotropic_axes(num_segments);

        axes_realizations(:, :, i_realization) = ...
            axes_current;

        random_walk_axis_sum_norm(i_realization) = ...
            norm(sum(axes_current, 1));

    end


    % =========================
    % Analytical references
    % =========================

    analytics = ...
        analytical_values_experiment_4_fiber_parameter_entanglement_maps( ...
            fiber_length_values_km, ...
            pmd_coefficient_values_ps_sqrt_km, ...
            sigma_omega, ...
            concurrence_quality_threshold);


    % =========================
    % Preallocation
    % =========================

    map_size = ...
        [num_pmd_values, num_length_values];

    sample_size = ...
        [num_pmd_values, num_length_values, num_realizations];

    concurrence_samples = ...
        zeros(sample_size);

    purity_samples = ...
        zeros(sample_size);

    fidelity_samples = ...
        zeros(sample_size);

    chsh_max_samples = ...
        zeros(sample_size);

    total_dgd_samples = ...
        zeros(sample_size);

    trace_error = ...
        zeros(sample_size);

    hermiticity_error = ...
        zeros(sample_size);

    minimum_eigenvalue = ...
        zeros(sample_size);

    segment_dgd_map = ...
        zeros(map_size);

    target_rms_dgd_map = ...
        analytics.rms_total_dgd_s;


    % =========================
    % Console header
    % =========================

    fprintf('\n');
    fprintf('====================================================\n');
    fprintf(' Experiment 4 - Fiber Parameter Entanglement Maps\n');
    fprintf('====================================================\n');

    fprintf( ...
        'Fiber-length points:        %d\n', ...
        num_length_values);

    fprintf( ...
        'PMD-coefficient points:     %d\n', ...
        num_pmd_values);

    fprintf( ...
        'Segments / realization:     %d\n', ...
        num_segments);

    fprintf( ...
        'Realizations / map point:   %d\n', ...
        num_realizations);

    fprintf( ...
        'Frequency nodes / arm:      %d\n', ...
        num_frequency_points);

    fprintf( ...
        'Marginal sigma_omega:       %.3e rad/s\n', ...
        sigma_omega);

    fprintf( ...
        'Spectral window:            +/- %.1f sigma_omega\n', ...
        max_offset_factor);

    fprintf( ...
        'Concurrence quality C_thr:  %.3f\n', ...
        concurrence_quality_threshold);

    fprintf( ...
        'Random seed:                %d\n', ...
        random_seed);


    % =========================
    % Main parameter sweep
    % =========================

    phases_A = ...
        zeros(num_segments, 1);

    for i_pmd = 1:num_pmd_values

        pmd_coefficient_current = ...
            pmd_coefficient_values_ps_sqrt_km(i_pmd);

        fprintf( ...
            '\nPMD case %d/%d: D_PMD = %.4f ps/sqrt(km)\n', ...
            i_pmd, ...
            num_pmd_values, ...
            pmd_coefficient_current);

        for i_length = 1:num_length_values

            fiber_length_current_km = ...
                fiber_length_values_km(i_length);

            target_rms_dgd_current = ...
                target_rms_dgd_map(i_pmd, i_length);

            segment_dgd_current = ...
                target_rms_dgd_current / sqrt(num_segments);

            segment_dgd_map(i_pmd, i_length) = ...
                segment_dgd_current;

            % The ideal limit is evaluated directly. This avoids unnecessary
            % numerical propagation when L = 0 or D_PMD = 0.
            if target_rms_dgd_current == 0

                concurrence_samples(i_pmd, i_length, :) = 1;
                purity_samples(i_pmd, i_length, :) = 1;
                fidelity_samples(i_pmd, i_length, :) = 1;
                chsh_max_samples(i_pmd, i_length, :) = 2 * sqrt(2);
                total_dgd_samples(i_pmd, i_length, :) = 0;

                continue;

            end

            dgds_A = ...
                segment_dgd_current * ones(num_segments, 1);

            for i_realization = 1:num_realizations

                axes_A = ...
                    axes_realizations(:, :, i_realization);


                % =========================
                % First-order total DGD
                % =========================

                % With zero carrier phases, every segment is the identity
                % at Omega = 0. The first-order PMD vector is therefore the
                % vectorial sum of the segment contributions.

                total_dgd_current = ...
                    segment_dgd_current * ...
                    random_walk_axis_sum_norm(i_realization);

                total_dgd_samples( ...
                    i_pmd, ...
                    i_length, ...
                    i_realization) = ...
                    total_dgd_current;


                % =========================
                % Reduced spectral trace
                % =========================

                rho_raw = ...
                    single_arm_spectral_average( ...
                        rho_input, ...
                        omega_offsets, ...
                        marginal_weights_A, ...
                        phases_A, ...
                        dgds_A, ...
                        axes_A, ...
                        identity_B);


                % =========================
                % Physical-state diagnostics
                % =========================

                trace_error( ...
                    i_pmd, ...
                    i_length, ...
                    i_realization) = ...
                    abs(trace(rho_raw) - 1);

                hermiticity_error( ...
                    i_pmd, ...
                    i_length, ...
                    i_realization) = ...
                    norm(rho_raw - rho_raw', 'fro');

                rho_current = ...
                    (rho_raw + rho_raw') / 2;

                eigenvalues_current = ...
                    eig(rho_current);

                minimum_eigenvalue( ...
                    i_pmd, ...
                    i_length, ...
                    i_realization) = ...
                    min(real(eigenvalues_current));

                validate_density_state( ...
                    rho_raw, ...
                    rho_current, ...
                    i_pmd, ...
                    i_length, ...
                    i_realization);


                % =========================
                % State metrics
                % =========================

                purity_samples( ...
                    i_pmd, ...
                    i_length, ...
                    i_realization) = ...
                    real(compute_purity(rho_current));

                fidelity_samples( ...
                    i_pmd, ...
                    i_length, ...
                    i_realization) = ...
                    real(compute_fidelity( ...
                        rho_current, ...
                        psi_input));

                concurrence_samples( ...
                    i_pmd, ...
                    i_length, ...
                    i_realization) = ...
                    real(compute_concurrence(rho_current));

                correlation_tensor_current = ...
                    compute_correlation_tensor(rho_current);

                chsh_max_samples( ...
                    i_pmd, ...
                    i_length, ...
                    i_realization) = ...
                    real(compute_chsh_max_from_tensor( ...
                        correlation_tensor_current));

            end

        end

    end


    % =========================
    % Statistical maps
    % =========================

    maps = struct();

    maps.mean_concurrence = ...
        mean(concurrence_samples, 3);

    maps.std_concurrence = ...
        std(concurrence_samples, 0, 3);

    maps.standard_error_concurrence = ...
        maps.std_concurrence / sqrt(num_realizations);

    maps.mean_purity = ...
        mean(purity_samples, 3);

    maps.mean_fidelity = ...
        mean(fidelity_samples, 3);

    maps.mean_chsh_max = ...
        mean(chsh_max_samples, 3);

    maps.rms_total_dgd_s = ...
        sqrt(mean(total_dgd_samples .^ 2, 3));

    maps.rms_total_dgd_ps = ...
        1e12 * maps.rms_total_dgd_s;


    % =========================
    % Entanglement-quality analysis
    % =========================

    quality = struct();

    quality.concurrence_threshold = ...
        concurrence_quality_threshold;

    quality.mean_concurrence_pass = ...
        maps.mean_concurrence >= ...
        concurrence_quality_threshold;

    quality.realization_pass_probability = ...
        mean( ...
            concurrence_samples >= ...
            concurrence_quality_threshold, ...
            3);

    quality.realization_fail_probability = ...
        1 - quality.realization_pass_probability;

    quality.critical_length_from_mean_km = ...
        estimate_threshold_crossings( ...
            fiber_length_values_km, ...
            pmd_coefficient_values_ps_sqrt_km, ...
            maps.mean_concurrence, ...
            concurrence_quality_threshold);

    quality.critical_length_first_order_km = ...
        analytics.critical_length_mean_concurrence_km;

    quality.map_fraction_passing_mean_threshold = ...
        mean(quality.mean_concurrence_pass, 'all');


    % =========================
    % Random-walk validation
    % =========================

    validation = struct();

    validation.target_rms_total_dgd_s = ...
        target_rms_dgd_map;

    validation.numerical_rms_total_dgd_s = ...
        maps.rms_total_dgd_s;

    nonzero_target = ...
        target_rms_dgd_map > 0;

    rms_dgd_relative_error = ...
        zeros(map_size);

    rms_dgd_relative_error(nonzero_target) = ...
        abs( ...
            maps.rms_total_dgd_s(nonzero_target) - ...
            target_rms_dgd_map(nonzero_target)) ./ ...
        target_rms_dgd_map(nonzero_target);

    validation.rms_total_dgd_relative_error = ...
        rms_dgd_relative_error;

    if any(nonzero_target, 'all')
        validation.max_rms_total_dgd_relative_error = ...
            max(rms_dgd_relative_error(nonzero_target));
    else
        validation.max_rms_total_dgd_relative_error = 0;
    end

    validation.max_trace_error = ...
        max(trace_error, [], 'all');

    validation.max_hermiticity_error = ...
        max(hermiticity_error, [], 'all');

    validation.minimum_density_eigenvalue = ...
        min(minimum_eigenvalue, [], 'all');

    validation.max_abs_mean_concurrence_first_order_error = ...
        max( ...
            abs( ...
                maps.mean_concurrence - ...
                analytics.mean_concurrence_first_order), ...
            [], ...
            'all');

    validation.max_abs_quality_probability_first_order_error = ...
        max( ...
            abs( ...
                quality.realization_pass_probability - ...
                analytics.quality_probability_first_order), ...
            [], ...
            'all');


    % =========================
    % Explicit-pipeline cross-check
    % =========================

    crosscheck_pmd_index = ...
        num_pmd_values;

    crosscheck_length_index = ...
        num_length_values;

    crosscheck_realization_index = 1;

    crosscheck_segment_dgd = ...
        segment_dgd_map( ...
            crosscheck_pmd_index, ...
            crosscheck_length_index);

    crosscheck_dgds_A = ...
        crosscheck_segment_dgd * ...
        ones(num_segments, 1);

    crosscheck_axes_A = ...
        axes_realizations( ...
            :, ...
            :, ...
            crosscheck_realization_index);

    rho_crosscheck_reduced = ...
        single_arm_spectral_average( ...
            rho_input, ...
            omega_offsets, ...
            marginal_weights_A, ...
            phases_A, ...
            crosscheck_dgds_A, ...
            crosscheck_axes_A, ...
            identity_B);

    frequency_states_crosscheck = ...
        pmd_frequency_resolved_states( ...
            rho_input, ...
            omega_offsets, ...
            omega_offsets, ...
            phases_A, ...
            crosscheck_dgds_A, ...
            crosscheck_axes_A, ...
            phases_B, ...
            dgds_B, ...
            axes_B);

    rho_crosscheck_explicit = ...
        pmd_spectral_average_state( ...
            frequency_states_crosscheck, ...
            spectral_weights);

    rho_crosscheck_reduced = ...
        (rho_crosscheck_reduced + ...
         rho_crosscheck_reduced') / 2;

    rho_crosscheck_explicit = ...
        (rho_crosscheck_explicit + ...
         rho_crosscheck_explicit') / 2;

    validation.reduced_vs_explicit_state_fro_error = ...
        norm( ...
            rho_crosscheck_reduced - ...
            rho_crosscheck_explicit, ...
            'fro');

    validation.reduced_vs_explicit_concurrence_error = ...
        abs( ...
            compute_concurrence(rho_crosscheck_reduced) - ...
            compute_concurrence(rho_crosscheck_explicit));


    % =========================
    % Store results
    % =========================

    results_experiment_4 = struct();

    results_experiment_4.experiment_name = ...
        'Experiment 4 - Fiber Parameter Entanglement Maps';

    results_experiment_4.reference_state_label = ...
        'Psi+';

    results_experiment_4.model_name = ...
        'single_arm_statistical_segmented_pmd_engineering_map';

    results_experiment_4.rho_input = ...
        rho_input;


    % =========================
    % Parameters
    % =========================

    results_experiment_4.parameters = struct();

    results_experiment_4.parameters.fiber_length_values_km = ...
        fiber_length_values_km;

    results_experiment_4.parameters.pmd_coefficient_values_ps_sqrt_km = ...
        pmd_coefficient_values_ps_sqrt_km;

    results_experiment_4.parameters.sigma_omega = ...
        sigma_omega;

    results_experiment_4.parameters.num_segments = ...
        num_segments;

    results_experiment_4.parameters.num_realizations = ...
        num_realizations;

    results_experiment_4.parameters.num_frequency_points = ...
        num_frequency_points;

    results_experiment_4.parameters.max_offset_factor = ...
        max_offset_factor;

    results_experiment_4.parameters.random_seed = ...
        random_seed;

    results_experiment_4.parameters.concurrence_quality_threshold = ...
        concurrence_quality_threshold;

    results_experiment_4.parameters.axis_distribution = ...
        'independent_isotropic';

    results_experiment_4.parameters.carrier_phase_model = ...
        'zero';

    results_experiment_4.parameters.arm_B_model = ...
        'ideal';

    results_experiment_4.parameters.segment_dgd_map_s = ...
        segment_dgd_map;


    % =========================
    % Spectrum
    % =========================

    results_experiment_4.spectrum = struct();

    results_experiment_4.spectrum.omega_offsets = ...
        omega_offsets;

    results_experiment_4.spectrum.delta_omega = ...
        delta_omega;

    results_experiment_4.spectrum.max_frequency_offset = ...
        max_frequency_offset;

    results_experiment_4.spectrum.sigma_sum = ...
        sigma_sum;

    results_experiment_4.spectrum.sigma_difference = ...
        sigma_difference;

    results_experiment_4.spectrum.spectral_weights = ...
        spectral_weights;

    results_experiment_4.spectrum.marginal_weights_A = ...
        marginal_weights_A;


    % =========================
    % Monte Carlo data
    % =========================

    results_experiment_4.realizations = struct();

    results_experiment_4.realizations.axes = ...
        axes_realizations;

    results_experiment_4.realizations.concurrence = ...
        concurrence_samples;

    results_experiment_4.realizations.purity = ...
        purity_samples;

    results_experiment_4.realizations.fidelity = ...
        fidelity_samples;

    results_experiment_4.realizations.chsh_max = ...
        chsh_max_samples;

    results_experiment_4.realizations.total_dgd_s = ...
        total_dgd_samples;


    % =========================
    % Maps and analysis
    % =========================

    results_experiment_4.maps = ...
        maps;

    results_experiment_4.quality = ...
        quality;

    results_experiment_4.analytical = ...
        analytics;

    results_experiment_4.validation = ...
        validation;


    % =========================
    % Console analysis summary
    % =========================

    fprintf('\n====================================================\n');
    fprintf(' Experiment 4 Entanglement-Quality Summary\n');
    fprintf('====================================================\n');

    fprintf( ...
        'Operational threshold C_thr:            %.3f\n', ...
        concurrence_quality_threshold);

    fprintf( ...
        'Map fraction with mean C >= C_thr:      %.3f\n', ...
        quality.map_fraction_passing_mean_threshold);

    fprintf( ...
        'Max random-walk RMS-DGD relative error: %.3e\n', ...
        validation.max_rms_total_dgd_relative_error);

    fprintf( ...
        'Max trace error:                        %.3e\n', ...
        validation.max_trace_error);

    fprintf( ...
        'Max Hermiticity error:                  %.3e\n', ...
        validation.max_hermiticity_error);

    fprintf( ...
        'Minimum density eigenvalue:             %.3e\n', ...
        validation.minimum_density_eigenvalue);

    fprintf( ...
        'Reduced/full spectral state error:      %.3e\n', ...
        validation.reduced_vs_explicit_state_fro_error);

    fprintf( ...
        'Reduced/full concurrence error:         %.3e\n', ...
        validation.reduced_vs_explicit_concurrence_error);


    % =========================
    % Plotting
    % =========================

    if do_plot
        plot_experiment_4_fiber_parameter_entanglement_maps( ...
            results_experiment_4, ...
            do_save);
    end

end


function rho_average = single_arm_spectral_average( ...
        rho_input, omega_offsets, marginal_weights_A, ...
        phases_A, dgds_A, axes_A, identity_B)
% SINGLE_ARM_SPECTRAL_AVERAGE
% Evaluate the exact spectral trace when only arm A has PMD.
%
% Objective:
%   Avoid constructing the full N_omega-by-N_omega spectral-state tensor
%   when arm B is the identity. The result is mathematically equivalent to
%   summing the full joint spectrum because the arm-B unitary is constant.
%
% Input:
%   rho_input          - 4x4 input density matrix.
%   omega_offsets      - Angular-frequency offsets for arm A [rad/s].
%   marginal_weights_A - Normalized spectral marginal weights for arm A.
%   phases_A           - Segment carrier phases [rad].
%   dgds_A             - Segment DGDs [s].
%   axes_A             - Segment birefringence axes.
%   identity_B         - 2x2 identity matrix for arm B.
%
% Output:
%   rho_average - Spectrally averaged 4x4 polarization density matrix.

    rho_average = ...
        complex(zeros(4, 4));

    num_frequency_points = ...
        numel(omega_offsets);

    for i_frequency = 1:num_frequency_points

        U_A = ...
            pmd_fiber_unitary( ...
                omega_offsets(i_frequency), ...
                phases_A, ...
                dgds_A, ...
                axes_A);

        rho_frequency = ...
            apply_unitary( ...
                U_A, ...
                identity_B, ...
                rho_input);

        rho_average = ...
            rho_average + ...
            marginal_weights_A(i_frequency) * ...
            rho_frequency;

    end

end


function axes = sample_isotropic_axes(num_axes)
% SAMPLE_ISOTROPIC_AXES  Generate isotropically distributed unit vectors.
%
% Objective:
%   Sample independent directions uniformly on the unit sphere by
%   normalizing three-dimensional standard Gaussian vectors.
%
% Input:
%   num_axes - Number of axes to generate.
%
% Output:
%   axes - num_axes-by-3 matrix containing unit vectors.

    axes = ...
        randn(num_axes, 3);

    axis_norms = ...
        vecnorm(axes, 2, 2);

    null_axes = ...
        axis_norms == 0;

    while any(null_axes)

        axes(null_axes, :) = ...
            randn(sum(null_axes), 3);

        axis_norms = ...
            vecnorm(axes, 2, 2);

        null_axes = ...
            axis_norms == 0;

    end

    axes = ...
        axes ./ axis_norms;

end


function critical_length_km = estimate_threshold_crossings( ...
        fiber_length_values_km, pmd_coefficient_values, ...
        mean_concurrence_map, concurrence_threshold)
% ESTIMATE_THRESHOLD_CROSSINGS
% Estimate the first mean-concurrence threshold crossing for each PMD row.
%
% Objective:
%   Return the fiber length at which the sampled mean concurrence first
%   drops below the operational quality threshold. Linear interpolation is
%   used between adjacent length samples.
%
% Input:
%   fiber_length_values_km - Increasing fiber-length vector [km].
%   pmd_coefficient_values - PMD-coefficient vector.
%   mean_concurrence_map   - N_PMD-by-N_L mean concurrence map.
%   concurrence_threshold  - Operational concurrence threshold.
%
% Output:
%   critical_length_km - N_PMD-by-1 crossing lengths [km].
%                        Inf means no crossing inside the sampled range.

    num_pmd_values = ...
        numel(pmd_coefficient_values);

    critical_length_km = ...
        inf(num_pmd_values, 1);

    for i_pmd = 1:num_pmd_values

        concurrence_row = ...
            mean_concurrence_map(i_pmd, :);

        crossing_index = ...
            find( ...
                concurrence_row < concurrence_threshold, ...
                1, ...
                'first');

        if isempty(crossing_index)
            continue;
        end

        if crossing_index == 1
            critical_length_km(i_pmd) = ...
                fiber_length_values_km(1);
            continue;
        end

        x_1 = ...
            fiber_length_values_km(crossing_index - 1);

        x_2 = ...
            fiber_length_values_km(crossing_index);

        y_1 = ...
            concurrence_row(crossing_index - 1);

        y_2 = ...
            concurrence_row(crossing_index);

        if abs(y_2 - y_1) < eps
            critical_length_km(i_pmd) = x_2;
        else
            interpolation_fraction = ...
                (concurrence_threshold - y_1) / ...
                (y_2 - y_1);

            critical_length_km(i_pmd) = ...
                x_1 + ...
                interpolation_fraction * ...
                (x_2 - x_1);
        end

    end

end


function validate_density_state( ...
        rho_raw, rho_current, ...
        i_pmd, i_length, i_realization)
% VALIDATE_DENSITY_STATE  Enforce physical-state numerical tolerances.

    tolerance = 1e-8;

    trace_error = ...
        abs(trace(rho_raw) - 1);

    hermiticity_error = ...
        norm(rho_raw - rho_raw', 'fro');

    minimum_eigenvalue = ...
        min(real(eig(rho_current)));

    if trace_error > tolerance
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'TraceFailure'], ...
            ['Reduced state trace error exceeded tolerance at ', ...
             'PMD index %d, length index %d, realization %d.'], ...
            i_pmd, ...
            i_length, ...
            i_realization);
    end

    if hermiticity_error > tolerance
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'HermiticityFailure'], ...
            ['Reduced state Hermiticity error exceeded tolerance at ', ...
             'PMD index %d, length index %d, realization %d.'], ...
            i_pmd, ...
            i_length, ...
            i_realization);
    end

    if minimum_eigenvalue < -tolerance
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'PositivityFailure'], ...
            ['Reduced state is not positive semidefinite within ', ...
             'tolerance at PMD index %d, length index %d, ', ...
             'realization %d.'], ...
            i_pmd, ...
            i_length, ...
            i_realization);
    end

end


function validate_configuration( ...
        fiber_length_values_km, ...
        pmd_coefficient_values_ps_sqrt_km, ...
        sigma_omega, ...
        num_segments, ...
        num_realizations, ...
        num_frequency_points, ...
        max_offset_factor, ...
        random_seed, ...
        concurrence_quality_threshold)
% VALIDATE_CONFIGURATION  Validate runner-local experiment parameters.

    if ~isnumeric(fiber_length_values_km) || ...
            ~isreal(fiber_length_values_km) || ...
            ~isvector(fiber_length_values_km) || ...
            isempty(fiber_length_values_km) || ...
            any(~isfinite(fiber_length_values_km), 'all') || ...
            any(fiber_length_values_km < 0, 'all')
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidFiberLengths'], ...
            ['fiber_length_values_km must be a non-empty vector of ', ...
             'finite non-negative values.']);
    end

    if any(diff(fiber_length_values_km) <= 0)
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'NonIncreasingFiberLengths'], ...
            'fiber_length_values_km must be strictly increasing.');
    end

    if ~isnumeric(pmd_coefficient_values_ps_sqrt_km) || ...
            ~isreal(pmd_coefficient_values_ps_sqrt_km) || ...
            ~isvector(pmd_coefficient_values_ps_sqrt_km) || ...
            isempty(pmd_coefficient_values_ps_sqrt_km) || ...
            any(~isfinite( ...
                pmd_coefficient_values_ps_sqrt_km), 'all') || ...
            any(pmd_coefficient_values_ps_sqrt_km < 0, 'all')
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidPMDCoefficients'], ...
            ['pmd_coefficient_values_ps_sqrt_km must be a non-empty ', ...
             'vector of finite non-negative values.']);
    end

    if any(diff(pmd_coefficient_values_ps_sqrt_km) <= 0)
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'NonIncreasingPMDCoefficients'], ...
            ['pmd_coefficient_values_ps_sqrt_km must be strictly ', ...
             'increasing.']);
    end

    if ~isnumeric(sigma_omega) || ...
            ~isscalar(sigma_omega) || ...
            ~isreal(sigma_omega) || ...
            ~isfinite(sigma_omega) || ...
            sigma_omega <= 0
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidSigmaOmega'], ...
            'sigma_omega must be a positive finite real scalar.');
    end

    if ~isnumeric(num_segments) || ...
            ~isscalar(num_segments) || ...
            ~isreal(num_segments) || ...
            ~isfinite(num_segments) || ...
            num_segments < 1 || ...
            num_segments ~= floor(num_segments)
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidNumSegments'], ...
            'num_segments must be a positive integer.');
    end

    if ~isnumeric(num_realizations) || ...
            ~isscalar(num_realizations) || ...
            ~isreal(num_realizations) || ...
            ~isfinite(num_realizations) || ...
            num_realizations < 2 || ...
            num_realizations ~= floor(num_realizations)
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidNumRealizations'], ...
            'num_realizations must be an integer greater than or equal to 2.');
    end

    if ~isnumeric(num_frequency_points) || ...
            ~isscalar(num_frequency_points) || ...
            ~isreal(num_frequency_points) || ...
            ~isfinite(num_frequency_points) || ...
            num_frequency_points < 3 || ...
            num_frequency_points ~= floor(num_frequency_points) || ...
            mod(num_frequency_points, 2) == 0
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidNumFrequencyPoints'], ...
            ['num_frequency_points must be an odd integer greater than ', ...
             'or equal to 3.']);
    end

    if ~isnumeric(max_offset_factor) || ...
            ~isscalar(max_offset_factor) || ...
            ~isreal(max_offset_factor) || ...
            ~isfinite(max_offset_factor) || ...
            max_offset_factor <= 0
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidMaxOffsetFactor'], ...
            'max_offset_factor must be a positive finite real scalar.');
    end

    if ~isnumeric(random_seed) || ...
            ~isscalar(random_seed) || ...
            ~isreal(random_seed) || ...
            ~isfinite(random_seed) || ...
            random_seed < 0 || ...
            random_seed ~= floor(random_seed) || ...
            random_seed > 2^32 - 1
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidRandomSeed'], ...
            ['random_seed must be an integer in the interval ', ...
             '[0, 2^32 - 1].']);
    end

    if ~isnumeric(concurrence_quality_threshold) || ...
            ~isscalar(concurrence_quality_threshold) || ...
            ~isreal(concurrence_quality_threshold) || ...
            ~isfinite(concurrence_quality_threshold) || ...
            concurrence_quality_threshold <= 0 || ...
            concurrence_quality_threshold > 1
        error( ...
            ['run_experiment_4_fiber_parameter_entanglement_maps:', ...
             'InvalidConcurrenceThreshold'], ...
            ['concurrence_quality_threshold must satisfy ', ...
             '0 < C_quality <= 1.']);
    end

end
