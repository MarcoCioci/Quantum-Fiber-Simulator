function plot_composite_pure_summary(results_experiment_5, do_save)
% PLOT_COMPOSITE_PURE_SUMMARY  Plot Experiment 5 pure composite channel summary.
%
% Objective:
%   Provide a compact summary of the pure-branch composite fiber channel:
%
%       1) correlation observables c_xx, c_yy, c_zz
%       2) state metrics γ, F, C
%       3) maximal CHSH parameter S_max
%
% Input:
%   results_experiment_5 - structure containing numerical and analytical
%                          quantities assembled by the Experiment 5 pure runner.
%
%   do_save              - optional logical flag to enable figure saving.
%                          Default value: false.
%
% Output:
%   None

    % =========================
    % Robustness checks
    % =========================

    if nargin < 1 || nargin > 2
        error('plot_composite_pure_summary:InvalidNumInputs', ...
              'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = false;
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error('plot_composite_pure_summary:InvalidDoSave', ...
              'do_save must be a logical scalar.');
    end

    if ~isstruct(results_experiment_5)
        error('plot_composite_pure_summary:InvalidInputType', ...
              'results_experiment_5 must be a structure.');
    end

    required_fields = { ...
        'theta_values', ...
        'p_A', ...
        'p_B', ...
        'eta', ...
        'c_xx', ...
        'c_yy', ...
        'c_zz', ...
        'purity_global', ...
        'purity_A', ...
        'purity_B', ...
        'fidelity_psi_plus', ...
        'concurrence', ...
        'S_max', ...
        'analytical' ...
    };

    check_required_fields(results_experiment_5, required_fields, ...
        'plot_composite_pure_summary:MissingField');

    if ~isstruct(results_experiment_5.analytical)
        error('plot_composite_pure_summary:InvalidAnalyticalType', ...
              'Field "analytical" must be a structure.');
    end

    required_analytical_fields = { ...
        'c_xx', ...
        'c_yy', ...
        'c_zz', ...
        'purity_global', ...
        'purity_A', ...
        'purity_B', ...
        'fidelity_psi_plus', ...
        'concurrence', ...
        'S_max' ...
    };

    check_required_fields(results_experiment_5.analytical, required_analytical_fields, ...
        'plot_composite_pure_summary:MissingAnalyticalField');


    % =========================
    % Extract data
    % =========================

    theta_values = results_experiment_5.theta_values(:).';

    p_A = real(results_experiment_5.p_A);
    p_B = real(results_experiment_5.p_B);
    eta = real(results_experiment_5.eta);

    if ~isnumeric(theta_values) || ~isreal(theta_values) || isempty(theta_values)
        error('plot_composite_pure_summary:InvalidThetaValues', ...
              'theta_values must be a non-empty real numeric vector.');
    end

    if any(~isfinite(theta_values))
        error('plot_composite_pure_summary:InvalidThetaValuesValues', ...
              'theta_values must contain only finite values.');
    end

    correlation_num = real([ ...
        results_experiment_5.c_xx; ...
        results_experiment_5.c_yy; ...
        results_experiment_5.c_zz ...
    ]);

    correlation_analytical = real([ ...
        results_experiment_5.analytical.c_xx; ...
        results_experiment_5.analytical.c_yy; ...
        results_experiment_5.analytical.c_zz ...
    ]);

    metric_num = real([ ...
        results_experiment_5.purity_global; ...
        results_experiment_5.purity_A; ...
        results_experiment_5.purity_B; ...
        results_experiment_5.fidelity_psi_plus; ...
        results_experiment_5.concurrence ...
    ]);

    metric_analytical = real([ ...
        results_experiment_5.analytical.purity_global; ...
        results_experiment_5.analytical.purity_A; ...
        results_experiment_5.analytical.purity_B; ...
        results_experiment_5.analytical.fidelity_psi_plus; ...
        results_experiment_5.analytical.concurrence ...
    ]);

    S_max_num = real(results_experiment_5.S_max);
    S_max_analytical = real(results_experiment_5.analytical.S_max);

    scalar_values = [ ...
        p_A, ...
        p_B, ...
        eta, ...
        correlation_num(:).', ...
        correlation_analytical(:).', ...
        metric_num(:).', ...
        metric_analytical(:).', ...
        S_max_num(:).', ...
        S_max_analytical(:).' ...
    ];

    if any(~isfinite(scalar_values))
        error('plot_composite_pure_summary:InvalidScalarValues', ...
              'All scalar numerical values must be finite.');
    end


    % =========================
    % Plot style
    % =========================

    style = get_plot_style();
    palette = get_plot_palette();


    % =========================
    % Auxiliary quantities
    % =========================

    theta_min = min(theta_values);
    theta_max = max(theta_values);

    if theta_min == theta_max
        theta_min = theta_min - 0.5;
        theta_max = theta_max + 0.5;
    end


    % =========================
    % Figure and tab
    % =========================

    tab_title = 'Pure channel summary';
    figure_name = 'Experiment 5 — Composite Fiber Channel';

    [fig, tab] = get_experiment_figure_tab( ...
        style.figure.experiment_5_id, ...
        tab_title, ...
        figure_name, ...
        style);

    build_plot(tab, false);

    set(fig, 'Visible', style.figure.visible_after_build);


    % =========================
    % Save (conditional)
    % =========================

    if do_save
        output_folder = '/home/marcocioci/HPC/THESIS-Quantum-Communications/Quantum-Fiber-Simulator/images/experiment_5';

        output_path = fullfile(output_folder, ...
            'experiment_5_summary_pure_channel.png');

        export_plot(output_path, ...
            @(parent) build_plot(parent, false), ...
            style);
    end


    % =========================
    % Local plot builder
    % =========================

    function layout = build_plot(parent_container, show_title)

        if nargin < 2
            show_title = false;
        end

        layout = tiledlayout(parent_container, 3, 1, ...
            'TileSpacing', 'compact', ...
            'Padding', 'compact');


        % =========================
        % Panel 1: correlation observables
        % =========================

        ax = nexttile(layout);
        hold(ax, 'on');
        grid(ax, 'on');
        box(ax, 'on');

        plot(ax, theta_values, correlation_analytical(1,:), '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.obs_x);

        plot(ax, theta_values, correlation_num(1,:), 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.obs_x, ...
            'MarkerEdgeColor', palette.obs_x);

        plot(ax, theta_values, correlation_analytical(2,:), '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.obs_y);

        plot(ax, theta_values, correlation_num(2,:), 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.obs_y, ...
            'MarkerEdgeColor', palette.obs_y);

        plot(ax, theta_values, correlation_analytical(3,:), '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.obs_z);

        plot(ax, theta_values, correlation_num(3,:), 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.obs_z, ...
            'MarkerEdgeColor', palette.obs_z);

        xlim(ax, [theta_min, theta_max]);
        ylim(ax, [-1.1, 1.1]);

        xlabel(ax, '\theta');
        ylabel(ax, 'correlation');
        title(ax, 'Correlation observables');

        legend(ax, { ...
            'c_{xx} analytical', ...
            'c_{xx} numerical', ...
            'c_{yy} analytical', ...
            'c_{yy} numerical', ...
            'c_{zz} analytical', ...
            'c_{zz} numerical' ...
            }, ...
            'Location', 'southoutside', ...
            'Orientation', 'horizontal');


        % =========================
        % Panel 2: state metrics
        % =========================

        ax = nexttile(layout);
        hold(ax, 'on');
        grid(ax, 'on');
        box(ax, 'on');

        plot(ax, theta_values, metric_analytical(1,:), '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.metric_global);

        plot(ax, theta_values, metric_num(1,:), 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.metric_global, ...
            'MarkerEdgeColor', palette.metric_global);

        plot(ax, theta_values, metric_analytical(2,:), '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.metric_A);

        plot(ax, theta_values, metric_num(2,:), 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.metric_A, ...
            'MarkerEdgeColor', palette.metric_A);

        plot(ax, theta_values, metric_analytical(3,:), '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.metric_B);

        plot(ax, theta_values, metric_num(3,:), 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.metric_B, ...
            'MarkerEdgeColor', palette.metric_B);

        plot(ax, theta_values, metric_analytical(4,:), '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.metric_F);

        plot(ax, theta_values, metric_num(4,:), 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.metric_F, ...
            'MarkerEdgeColor', palette.metric_F);

        plot(ax, theta_values, metric_analytical(5,:), '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.metric_C);

        plot(ax, theta_values, metric_num(5,:), 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.metric_C, ...
            'MarkerEdgeColor', palette.metric_C);

        xlim(ax, [theta_min, theta_max]);
        ylim(ax, [0, 1.05]);

        xlabel(ax, '\theta');
        ylabel(ax, 'value');
        title(ax, 'State metrics');

        legend(ax, { ...
            '\gamma(\rho_{AB}) analytical', ...
            '\gamma(\rho_{AB}) numerical', ...
            '\gamma(\rho_A) analytical', ...
            '\gamma(\rho_A) numerical', ...
            '\gamma(\rho_B) analytical', ...
            '\gamma(\rho_B) numerical', ...
            'F_{\Psi^+} analytical', ...
            'F_{\Psi^+} numerical', ...
            'C analytical', ...
            'C numerical' ...
            }, ...
            'Location', 'southoutside', ...
            'Orientation', 'horizontal');


        % =========================
        % Panel 3: CHSH maximal value
        % =========================

        ax = nexttile(layout);
        hold(ax, 'on');
        grid(ax, 'on');
        box(ax, 'on');

        plot(ax, theta_values, S_max_analytical, '-', ...
            'LineWidth', 1.8, ...
            'Color', palette.analytical);

        plot(ax, theta_values, S_max_num, 'o', ...
            'MarkerSize', 3, ...
            'MarkerFaceColor', palette.numerical, ...
            'MarkerEdgeColor', palette.numerical);

        yline(ax, 2, '--', ...
            'LineWidth', 1.2, ...
            'Color', palette.gray_dark);

        xlim(ax, [theta_min, theta_max]);
        ylim(ax, [0, max(2.2, 1.1 * max(S_max_num))]);

        xlabel(ax, '\theta');
        ylabel(ax, 'S_{max}');
        title(ax, 'Maximal CHSH value');

        legend(ax, { ...
            'S_{max} analytical', ...
            'S_{max} numerical', ...
            'classical bound' ...
            }, ...
            'Location', 'southoutside', ...
            'Orientation', 'horizontal');

        text(ax, 0.02, 0.95, ...
            sprintf(['p_A = %.4f\n' ...
                     'p_B = %.4f\n' ...
                     'eta = %.4f\n' ...
                     'S_{max,min} = %.4f\n' ...
                     'S_{max,max} = %.4f'], ...
                    p_A, ...
                    p_B, ...
                    eta, ...
                    min(S_max_num), ...
                    max(S_max_num)), ...
            'Units', 'normalized', ...
            'VerticalAlignment', 'top', ...
            'BackgroundColor', 'w', ...
            'EdgeColor', palette.gray_dark);


        % =========================
        % Global title
        % =========================

        if show_title
            title(layout, ...
                'Experiment 5 — Composite Fiber Channel | Pure branch', ...
                'FontWeight', 'bold');
        end

    end

end


function check_required_fields(input_struct, required_fields, error_id)
% CHECK_REQUIRED_FIELDS  Verify that all required fields are present.

    for field_idx = 1:numel(required_fields)
        field_name = required_fields{field_idx};

        if ~isfield(input_struct, field_name)
            error(error_id, 'Field "%s" not found.', field_name);
        end
    end

end