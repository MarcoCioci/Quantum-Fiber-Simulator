function plot_random_phase_summary(results_experiment_2)
% PLOT_RANDOM_PHASE_SUMMARY  Complete and compact summary plot for Experiment 2.
%
% Objective:
%   Provide a single manageable figure that summarizes the essential
%   components of Experiment 2:
%
%       1) sampled phase distribution
%       2) pure-state trend cos(theta) and sampled realizations
%       3) ensemble correlation observables
%       4) purity and fidelity metrics
%
% Input:
%   results_experiment_2 - structure containing:
%       .theta_samples
%       .case_label
%       .distribution_type
%       .c_xx
%       .c_yy
%       .c_zz
%       .purity_global
%       .purity_A
%       .purity_B
%       .fidelity_psi_plus
%       .sample_mean_cos_theta
%       .sample_mean_sin_theta
%       .theory_c_xx
%       .theory_c_yy
%       .theory_c_zz
%       .theory_purity_global
%       .theory_purity_A
%       .theory_purity_B
%       .theory_fidelity_psi_plus
%
% Output:
%   None
%
% Notes:
%   This plotting function does not recompute theoretical predictions.
%   It only visualizes the numerical and theoretical quantities already
%   assembled by the experiment runner.

    % =========================
    % Robustness checks
    % =========================

    required_fields = { ...
        'theta_samples', ...
        'case_label', ...
        'distribution_type', ...
        'c_xx', ...
        'c_yy', ...
        'c_zz', ...
        'purity_global', ...
        'purity_A', ...
        'purity_B', ...
        'fidelity_psi_plus', ...
        'sample_mean_cos_theta', ...
        'sample_mean_sin_theta', ...
        'theory_c_xx', ...
        'theory_c_yy', ...
        'theory_c_zz', ...
        'theory_purity_global', ...
        'theory_purity_A', ...
        'theory_purity_B', ...
        'theory_fidelity_psi_plus' ...
    };

    for k = 1:numel(required_fields)
        if ~isfield(results_experiment_2, required_fields{k})
            error('plot_random_phase_summary:MissingField', ...
                'Field "%s" not found.', required_fields{k});
        end
    end


    % =========================
    % Extract and validate data
    % =========================

    theta_samples = results_experiment_2.theta_samples(:).';
    case_label = char(results_experiment_2.case_label);
    distribution_type = char(results_experiment_2.distribution_type);

    c_xx_num = real(results_experiment_2.c_xx);
    c_yy_num = real(results_experiment_2.c_yy);
    c_zz_num = real(results_experiment_2.c_zz);

    purity_global_num = real(results_experiment_2.purity_global);
    purity_A_num = real(results_experiment_2.purity_A);
    purity_B_num = real(results_experiment_2.purity_B);
    fidelity_psi_plus_num = real(results_experiment_2.fidelity_psi_plus);

    sample_mean_cos_theta = real(results_experiment_2.sample_mean_cos_theta);
    sample_mean_sin_theta = real(results_experiment_2.sample_mean_sin_theta);

    c_xx_theory = real(results_experiment_2.theory_c_xx);
    c_yy_theory = real(results_experiment_2.theory_c_yy);
    c_zz_theory = real(results_experiment_2.theory_c_zz);

    purity_global_theory = real(results_experiment_2.theory_purity_global);
    purity_A_theory = real(results_experiment_2.theory_purity_A);
    purity_B_theory = real(results_experiment_2.theory_purity_B);
    fidelity_psi_plus_theory = real(results_experiment_2.theory_fidelity_psi_plus);

    if ~isnumeric(theta_samples) || ~isvector(theta_samples)
        error('plot_random_phase_summary:InvalidThetaSamplesType', ...
            'theta_samples must be a numeric vector.');
    end

    if isempty(theta_samples)
        error('plot_random_phase_summary:EmptyThetaSamples', ...
            'theta_samples must not be empty.');
    end

    if ~isreal(theta_samples)
        error('plot_random_phase_summary:ComplexThetaSamples', ...
            'theta_samples must be real-valued.');
    end

    if any(~isfinite(theta_samples))
        error('plot_random_phase_summary:InvalidThetaSamples', ...
            'theta_samples must contain only finite values.');
    end

    if ~(ischar(results_experiment_2.case_label) || ...
            (isstring(results_experiment_2.case_label) && isscalar(results_experiment_2.case_label)))
        error('plot_random_phase_summary:InvalidCaseLabel', ...
            'case_label must be a character vector or a scalar string.');
    end

    if ~(ischar(results_experiment_2.distribution_type) || ...
            (isstring(results_experiment_2.distribution_type) && isscalar(results_experiment_2.distribution_type)))
        error('plot_random_phase_summary:InvalidDistributionType', ...
            'distribution_type must be a character vector or a scalar string.');
    end

    scalar_values = [ ...
        c_xx_num, ...
        c_yy_num, ...
        c_zz_num, ...
        purity_global_num, ...
        purity_A_num, ...
        purity_B_num, ...
        fidelity_psi_plus_num, ...
        sample_mean_cos_theta, ...
        sample_mean_sin_theta, ...
        c_xx_theory, ...
        c_yy_theory, ...
        c_zz_theory, ...
        purity_global_theory, ...
        purity_A_theory, ...
        purity_B_theory, ...
        fidelity_psi_plus_theory ...
    ];

    if any(~isfinite(scalar_values))
        error('plot_random_phase_summary:InvalidValues', ...
            'Numerical values must be finite.');
    end


    % =========================
    % Organize theory and numerical data
    % =========================

    correlation_labels = {'c_{xx}', 'c_{yy}', 'c_{zz}'};
    correlation_theory = [c_xx_theory, c_yy_theory, c_zz_theory];
    correlation_num = [c_xx_num, c_yy_num, c_zz_num];

    metric_labels = {'\gamma(\rho_{AB})', '\gamma(\rho_A)', '\gamma(\rho_B)', 'F_{\Psi^+}'};
    metric_theory = [ ...
        purity_global_theory, ...
        purity_A_theory, ...
        purity_B_theory, ...
        fidelity_psi_plus_theory ...
    ];
    metric_num = [ ...
        purity_global_num, ...
        purity_A_num, ...
        purity_B_num, ...
        fidelity_psi_plus_num ...
    ];


    % =========================
    % Auxiliary arrays
    % =========================

    theta_min = min(theta_samples);
    theta_max = max(theta_samples);

    if theta_min == theta_max
        theta_min = theta_min - 0.5;
        theta_max = theta_max + 0.5;
    end

    theta_plot = linspace(theta_min, theta_max, 400);
    pure_state_cosine_trend = cos(theta_plot);
    sampled_cosine_values = cos(theta_samples);

    correlation_errors = abs(correlation_num - correlation_theory);
    metric_errors = abs(metric_num - metric_theory);


    % =========================
    % Figure
    % =========================

    fig = figure('Name', 'Experiment 2: random-phase ensemble summary', ...
                 'NumberTitle', 'off');

    tiledlayout(2, 2, 'TileSpacing', 'compact', 'Padding', 'compact');


    % ==========================================================
    % Panel 1: phase distribution
    % ==========================================================
    nexttile;
    hold on;
    grid on;
    box on;

    num_bins = max(10, round(sqrt(numel(theta_samples))));
    histogram(theta_samples, num_bins, ...
        'Normalization', 'pdf', ...
        'FaceColor', [0.75 0.75 0.75], ...
        'EdgeColor', [0.35 0.35 0.35]);

    xlim([theta_min, theta_max]);
    ylabel('pdf');
    xlabel('\theta');
    title('Sampled phase distribution');

    mean_theta = mean(theta_samples);
    std_theta = std(theta_samples);

    text(0.02, 0.95, ...
        sprintf(['N = %d   mean(\\theta) = %.4f   std(\\theta) = %.4f\n' ...
                 'mean(cos\\theta) = %.4f   mean(sin\\theta) = %.4f'], ...
                numel(theta_samples), ...
                mean_theta, ...
                std_theta, ...
                sample_mean_cos_theta, ...
                sample_mean_sin_theta), ...
        'Units', 'normalized', ...
        'VerticalAlignment', 'top', ...
        'BackgroundColor', 'w', ...
        'EdgeColor', [0.8 0.8 0.8]);


    % ==========================================================
    % Panel 2: pure-state trend and samples
    % ==========================================================
    nexttile;
    hold on;
    grid on;
    box on;

    plot(theta_plot, pure_state_cosine_trend, 'b', 'LineWidth', 1.8);
    plot(theta_samples, sampled_cosine_values, 'ko', ...
        'MarkerSize', 3, ...
        'MarkerFaceColor', 'k');

    yline(sample_mean_cos_theta, '--', 'Color', [0 0 0], 'LineWidth', 1.2);
    yline(c_xx_num, '-', 'Color', [0.4 0 0.4], 'LineWidth', 1.4);

    xlim([theta_min, theta_max]);
    ylim([-1.1, 1.1]);

    xlabel('\theta');
    ylabel('$\cos(\theta)$', 'Interpreter', 'latex');
    title('Pure-state trend and ensemble average');

    legend({'$\cos(\theta)$ trend', ...
            'sample realizations', ...
            '$\langle \cos(\theta)\rangle$ from runner', ...
            '$c_{xx}$ numerical ensemble'}, ...
            'Interpreter', 'latex', ...
            'Location', 'southoutside', ...
            'Orientation', 'horizontal');


    % ==========================================================
    % Panel 3: ensemble correlations
    % ==========================================================
    nexttile;
    hold on;
    grid on;
    box on;

    x_corr = 1:3;
    bar_width = 0.36;

    bar(x_corr - bar_width/2, correlation_theory, bar_width, ...
        'FaceColor', [0.65 0.65 0.85], ...
        'EdgeColor', 'k');

    bar(x_corr + bar_width/2, correlation_num, bar_width, ...
        'FaceColor', [0.85 0.85 0.85], ...
        'EdgeColor', 'k');

    xlim([0.4, 3.6]);
    ylim([-1.1, 1.1]);

    set(gca, 'XTick', x_corr, 'XTickLabel', correlation_labels);
    xlabel('correlation observables');
    ylabel('value');
    title('Ensemble correlations');

    legend({'theory from runner', 'numerical'}, ...
        'Location', 'southoutside', ...
        'Orientation', 'horizontal');

    for k = 1:3
        text(x_corr(k) - bar_width/2, ...
            correlation_theory(k) + 0.06 * sign(correlation_theory(k) + eps), ...
            sprintf('%.4f', correlation_theory(k)), ...
            'HorizontalAlignment', 'center', ...
            'FontSize', 9);

        text(x_corr(k) + bar_width/2, ...
            correlation_num(k) + 0.06 * sign(correlation_num(k) + eps), ...
            sprintf('%.4f', correlation_num(k)), ...
            'HorizontalAlignment', 'center', ...
            'FontSize', 9);
    end

    correlation_error_text = sprintf(['|theory - numerical|:\n' ...
                                      'c_{xx}: %.3e\n' ...
                                      'c_{yy}: %.3e\n' ...
                                      'c_{zz}: %.3e'], ...
                                      correlation_errors(1), ...
                                      correlation_errors(2), ...
                                      correlation_errors(3));

    text(0.98, 0.05, correlation_error_text, ...
        'Units', 'normalized', ...
        'HorizontalAlignment', 'right', ...
        'VerticalAlignment', 'bottom', ...
        'BackgroundColor', 'w', ...
        'EdgeColor', [0.8 0.8 0.8]);


    % ==========================================================
    % Panel 4: purity and fidelity
    % ==========================================================
    nexttile;
    hold on;
    grid on;
    box on;

    x_met = 1:4;

    bar(x_met - bar_width/2, metric_theory, bar_width, ...
        'FaceColor', [0.65 0.65 0.85], ...
        'EdgeColor', 'k');

    bar(x_met + bar_width/2, metric_num, bar_width, ...
        'FaceColor', [0.85 0.85 0.85], ...
        'EdgeColor', 'k');

    xlim([0.4, 4.6]);
    ylim([0, 1.05]);

    set(gca, 'XTick', x_met, ...
             'XTickLabel', metric_labels, ...
             'TickLabelInterpreter', 'tex');

    xlabel('state metrics');
    ylabel('value');
    title('Purity and fidelity');

    legend({'theory from runner', 'numerical'}, ...
        'Location', 'southoutside', ...
        'Orientation', 'horizontal');

    for k = 1:4
        text(x_met(k) - bar_width/2, metric_theory(k) + 0.04, ...
            sprintf('%.4f', metric_theory(k)), ...
            'HorizontalAlignment', 'center', ...
            'FontSize', 9);

        text(x_met(k) + bar_width/2, metric_num(k) + 0.04, ...
            sprintf('%.4f', metric_num(k)), ...
            'HorizontalAlignment', 'center', ...
            'FontSize', 9);
    end

    metric_error_text = sprintf(['|theory - numerical|:\n' ...
                                 '\\gamma(\\rho_{AB}): %.3e\n' ...
                                 '\\gamma(\\rho_A): %.3e\n' ...
                                 '\\gamma(\\rho_B): %.3e\n' ...
                                 'F_{\\Psi^+}: %.3e'], ...
                                 metric_errors(1), ...
                                 metric_errors(2), ...
                                 metric_errors(3), ...
                                 metric_errors(4));

    text(0.98, 0.05, metric_error_text, ...
        'Units', 'normalized', ...
        'HorizontalAlignment', 'right', ...
        'VerticalAlignment', 'bottom', ...
        'BackgroundColor', 'w', ...
        'EdgeColor', [0.8 0.8 0.8]);


    % =========================
    % Global title
    % =========================

    sgtitle(sprintf('Experiment 2: random-phase ensemble (%s)', case_label), ...
        'FontWeight', 'bold');


end