function fig = plot_depolarization_summary(results_experiment_3, do_save)
% PLOT_DEPOLARIZATION_SUMMARY  Plot numerical and analytical results for Experiment 3.
%
% Objective:
%   Visualize the effect of the two-qubit depolarizing channel on the
%   reference Bell state |Ψ⁺⟩ by comparing numerical results with the
%   corresponding analytical predictions.
%
% Input:
%   results_experiment_3 - structure containing Experiment 3 numerical
%                          and analytical results
%
%   do_save (optional) - logical flag to enable figure saving (default: false)
%
% Output:
%   fig - handle to the experiment figure window

    % =========================
    % Input checks
    % =========================

    if nargin < 1 || nargin > 2
        error('plot_depolarization_summary:InvalidNumInputs', ...
              'Expected 1 or 2 input arguments.');
    end

    if nargin < 2 || isempty(do_save)
        do_save = false;
    end

    if ~islogical(do_save) || ~isscalar(do_save)
        error('plot_depolarization_summary:InvalidDoSave', ...
              'do_save must be a logical scalar.');
    end

    if ~isstruct(results_experiment_3)
        error('plot_depolarization_summary:InvalidType', ...
              'results_experiment_3 must be a structure.');
    end

    required_fields = { ...
        'p_values', ...
        'purity_global', ...
        'purity_A', ...
        'purity_B', ...
        'fidelity_psi_plus', ...
        'concurrence', ...
        'c_xx', ...
        'c_yy', ...
        'c_zz', ...
        'analytical'};

    for k = 1:numel(required_fields)
        if ~isfield(results_experiment_3, required_fields{k})
            error('plot_depolarization_summary:MissingField', ...
                  'Missing required field: %s.', required_fields{k});
        end
    end

    required_analytical_fields = { ...
        'purity_global', ...
        'purity_A', ...
        'purity_B', ...
        'fidelity_psi_plus', ...
        'concurrence', ...
        'c_xx', ...
        'c_yy', ...
        'c_zz'};

    for k = 1:numel(required_analytical_fields)
        if ~isfield(results_experiment_3.analytical, required_analytical_fields{k})
            error('plot_depolarization_summary:MissingAnalyticalField', ...
                  'Missing required analytical field: %s.', ...
                  required_analytical_fields{k});
        end
    end

    p_values = results_experiment_3.p_values(:).';
    num_p = numel(p_values);

    if isempty(p_values) || ~isnumeric(p_values) || any(~isfinite(p_values))
        error('plot_depolarization_summary:InvalidPValues', ...
              'p_values must be a non-empty finite numeric vector.');
    end

    numeric_fields = { ...
        results_experiment_3.purity_global, ...
        results_experiment_3.purity_A, ...
        results_experiment_3.purity_B, ...
        results_experiment_3.fidelity_psi_plus, ...
        results_experiment_3.concurrence, ...
        results_experiment_3.c_xx, ...
        results_experiment_3.c_yy, ...
        results_experiment_3.c_zz, ...
        results_experiment_3.analytical.purity_global, ...
        results_experiment_3.analytical.purity_A, ...
        results_experiment_3.analytical.purity_B, ...
        results_experiment_3.analytical.fidelity_psi_plus, ...
        results_experiment_3.analytical.concurrence, ...
        results_experiment_3.analytical.c_xx, ...
        results_experiment_3.analytical.c_yy, ...
        results_experiment_3.analytical.c_zz};

    for k = 1:numel(numeric_fields)
        current_values = numeric_fields{k};

        if ~isnumeric(current_values) || ~isvector(current_values)
            error('plot_depolarization_summary:InvalidFieldShape', ...
                  'All plotted fields must be numeric vectors.');
        end

        if numel(current_values) ~= num_p
            error('plot_depolarization_summary:InconsistentLength', ...
                  'All plotted fields must have the same length as p_values.');
        end

        if any(~isfinite(current_values(:)))
            error('plot_depolarization_summary:InvalidValues', ...
                  'All plotted fields must contain finite values.');
        end
    end


    % =========================
    % Plot style
    % =========================

    palette = get_plot_palette();
    style   = get_plot_style();

    x_limits = [min(p_values), max(p_values)];

    if x_limits(1) == x_limits(2)
        x_limits = x_limits + [-0.05, 0.05];
    end

    metric_limits = [-0.05, 1.05];
    correlation_limits = [-1.2, 1.2];


    % =========================
    % Figure and tab
    % =========================

    [fig, tab] = get_experiment_figure_tab( ...
        style.figure.experiment_3_id, ...
        'Summary', ...
        'Experiment 3 — Depolarizing Channel', ...
        style);

    build_plot(tab);

    set(fig, 'Visible', style.figure.visible_after_build);


    % =========================
    % Save (conditional)
    % =========================

    if do_save
        output_folder = [ ...
            '/home/marcocioci/HPC/THESIS-Quantum-Communications/', ...
            'Quantum-Fiber-Simulator/Images/Experiment_3'];

        if ~exist(output_folder, 'dir')
            mkdir(output_folder);
        end

        output_path = fullfile(output_folder, ...
            'experiment_3_depolarizing_channel_summary.png');

        export_plot(output_path, @build_plot, style);
    end


    % =========================
    % Local plot builder
    % =========================

    function build_plot(parent_container)

        tl = tiledlayout(parent_container, 2, 1, ...
            'TileSpacing', style.layout.tile_spacing, ...
            'Padding', style.layout.padding);


        % =========================
        % Panel 1: State metrics
        % =========================

        ax = nexttile(tl);
        hold(ax, 'on');
        grid(ax, style.axes.grid);
        box(ax, style.axes.box);

        plot(ax, p_values, results_experiment_3.analytical.purity_global, '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.metric_global, ...
            'DisplayName', '$\gamma(\rho_{AB})$ analytical');

        plot(ax, p_values, results_experiment_3.analytical.purity_A, '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.metric_A, ...
            'DisplayName', '$\gamma(\rho_A)$ analytical');

        plot(ax, p_values, results_experiment_3.analytical.purity_B, '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.metric_B, ...
            'DisplayName', '$\gamma(\rho_B)$ analytical');

        plot(ax, p_values, results_experiment_3.analytical.fidelity_psi_plus, '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.metric_F, ...
            'DisplayName', '$F_{\Psi^+}$ analytical');

        plot(ax, p_values, results_experiment_3.analytical.concurrence, '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.metric_C, ...
            'DisplayName', '$C$ analytical');

        plot(ax, p_values, results_experiment_3.purity_global, 'o', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.metric_global, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', '$\gamma(\rho_{AB})$ numerical');

        plot(ax, p_values, results_experiment_3.purity_A, 's', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.metric_A, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', '$\gamma(\rho_A)$ numerical');

        plot(ax, p_values, results_experiment_3.purity_B, 'd', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.metric_B, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', '$\gamma(\rho_B)$ numerical');

        plot(ax, p_values, results_experiment_3.fidelity_psi_plus, '^', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.metric_F, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', '$F_{\Psi^+}$ numerical');

        plot(ax, p_values, results_experiment_3.concurrence, 'v', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.metric_C, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', '$C$ numerical');

        xlabel(ax, '$p$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel(ax, 'Metric value', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title(ax, 'State metrics', ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

        xlim(ax, x_limits);
        ylim(ax, metric_limits);

        set(ax, ...
            'FontSize', style.axes.font_size, ...
            'LineWidth', style.axes.line_width, ...
            'TickLabelInterpreter', style.axes.tick_label_interpreter, ...
            'Layer', style.axes.layer);

        legend(ax, ...
            'Location', 'eastoutside', ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);


        % =========================
        % Panel 2: Correlations
        % =========================

        ax = nexttile(tl);
        hold(ax, 'on');
        grid(ax, style.axes.grid);
        box(ax, style.axes.box);

        plot(ax, p_values, results_experiment_3.analytical.c_xx, '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.obs_x, ...
            'DisplayName', '$c_{xx}$ analytical');

        plot(ax, p_values, results_experiment_3.analytical.c_yy, '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.obs_y, ...
            'DisplayName', '$c_{yy}$ analytical');

        plot(ax, p_values, results_experiment_3.analytical.c_zz, '-', ...
            'LineWidth', style.lines.width_main, ...
            'Color', palette.obs_z, ...
            'DisplayName', '$c_{zz}$ analytical');

        plot(ax, p_values, results_experiment_3.c_xx, 'o', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.obs_x, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', '$c_{xx}$ numerical');

        plot(ax, p_values, results_experiment_3.c_yy, 's', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.obs_y, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', '$c_{yy}$ numerical');

        plot(ax, p_values, results_experiment_3.c_zz, 'd', ...
            'MarkerSize', style.markers.size, ...
            'MarkerFaceColor', palette.obs_z, ...
            'MarkerEdgeColor', palette.gray_dark, ...
            'LineWidth', style.markers.edge_width, ...
            'DisplayName', '$c_{zz}$ numerical');

        xlabel(ax, '$p$', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        ylabel(ax, 'Correlation value', ...
            'Interpreter', style.labels.interpreter, ...
            'FontSize', style.labels.font_size_axis);

        title(ax, 'Correlation observables', ...
            'FontSize', style.title.font_size_small, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

        xlim(ax, x_limits);
        ylim(ax, correlation_limits);

        set(ax, ...
            'FontSize', style.axes.font_size, ...
            'LineWidth', style.axes.line_width, ...
            'TickLabelInterpreter', style.axes.tick_label_interpreter, ...
            'Layer', style.axes.layer);

        legend(ax, ...
            'Location', 'eastoutside', ...
            'Interpreter', style.legend.interpreter, ...
            'FontSize', style.legend.font_size);


        % =========================
        % Global title
        % =========================

        title(tl, ...
            'Experiment 3 — Depolarizing Channel | analytical vs numerical', ...
            'FontSize', style.title.font_size, ...
            'FontWeight', style.title.font_weight, ...
            'Interpreter', style.title.interpreter);

    end

end